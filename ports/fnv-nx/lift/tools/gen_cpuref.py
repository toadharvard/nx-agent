#!/usr/bin/env python3
"""Generate the reference-CPU facts of the lift runtime from the ONE record (verify/cpuref.json: the identity) and the pinned cpuid data (verify/cpuid_model.json):
  rt/fnvl_cpuref.h   FNVL_CPUREF_FAMILY/MODEL/STEPPING, FNVL_CPUID1_EAX (SDM Vol 2A cpuid leaf 1 encoding of the identity), FNVL_CPUID1_ECX/EDX, FNVL_MAX_BASIC (included by rt/fnvl_abi.h)
  rt/rcpref.h        FNVL_RCP_REF_VENDOR/FAMILY/MODEL/STEPPING (proof/gate_fpexact.py reads exactly these four defines)
  rt/cpumodel_tab.inc  the vendor, leaf 2/4, 0x80000001 and brand tables of rt/cpumodel.c
Deterministic.   gen_cpuref.py [--check]"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); LIFT = os.path.dirname(HERE); VER = os.path.join(os.path.dirname(LIFT), 'verify')
ref = json.load(open(os.path.join(VER, 'cpuref.json'))); mod = json.load(open(os.path.join(VER, 'cpuid_model.json')))
I = lambda x: int(x, 0) if isinstance(x, str) else x
def le32(s): return int.from_bytes(s.encode().ljust(((len(s) + 3) // 4) * 4, b'\0'), 'little')
def words(s, n):
    b = s.encode().ljust(n * 4, b'\0'); assert len(s) <= n * 4
    return [int.from_bytes(b[4 * i:4 * i + 4], 'little') for i in range(n)]
def eax1(fam, model, step):
    assert fam in (6, 15) or model < 16 and fam < 15
    ef = fam - 15 if fam >= 15 else 0; bf = min(fam, 15); em, m = (model >> 4, model & 15) if bf in (6, 15) else (0, model); assert bf in (6, 15) or model < 16
    return ef << 20 | em << 16 | bf << 8 | m << 4 | step
def hx(v): return '0x%08xu' % v
def w(p, t): open(p, 'w').write(t)
EAX = eax1(ref['family'], ref['model'], ref['stepping'])
ECX = I(mod['leaf1_ecx_raw']) & I(mod['leaf1_ecx_keep']); EDX = I(mod['leaf1_edx_raw']) & ~I(mod['leaf1_edx_clear']) & 0xffffffff
E1 = [0, 0, I(mod['ext1_ecx_raw']) & I(mod['ext1_ecx_keep']), I(mod['ext1_edx_raw']) & I(mod['ext1_edx_keep'])]
def abi():
    return '\n'.join(['/* GENERATED by tools/gen_cpuref.py from verify/cpuref.json and verify/cpuid_model.json -- do not edit. */',
        '#define FNVL_MAX_BASIC %du' % mod['max_basic'], '#define FNVL_MAX_EXT %su' % hex(I(mod['max_ext'])),
        '#define FNVL_CPUREF_FAMILY %du' % ref['family'], '#define FNVL_CPUREF_MODEL %du' % ref['model'], '#define FNVL_CPUREF_STEPPING %du' % ref['stepping'],
        '#define FNVL_CPUID1_EAX %s' % hx(EAX), '#define FNVL_CPUID1_ECX %s' % hx(ECX), '#define FNVL_CPUID1_EDX %s' % hx(EDX)]) + '\n'
def rcp():
    return '\n'.join(['/* GENERATED by tools/gen_cpuref.py from verify/cpuref.json -- do not edit. The identity of the one reference CPU whose RCPSS / RSQRTSS results rt/rcptab.c tabulates',
        ' * (the values CPUID reports: leaf 0 vendor string; leaf 1 EAX family / model / stepping). Included by rt/rcptab.c and tools/rcpcert.c; proof/gate_fpexact.py reads the four defines. */',
        '#ifndef FNVL_RCPREF_H', '#define FNVL_RCPREF_H', '#define FNVL_RCP_REF_VENDOR "%s"' % ref['vendor_id'], '#define FNVL_RCP_REF_FAMILY %d' % ref['family'],
        '#define FNVL_RCP_REF_MODEL %d' % ref['model'], '#define FNVL_RCP_REF_STEPPING %d' % ref['stepping'], '#endif']) + '\n'
def tab():
    v = words(ref['vendor_id'], 3); b = words(ref['model_name'], 12)      # leaf 0: EBX, EDX, ECX in cpuid's register order; brand: leaves 0x80000002..4
    o = ['/* GENERATED by tools/gen_cpuref.py from verify/cpuref.json and verify/cpuid_model.json -- do not edit. */',
         'static const u32 L0[4] = { FNVL_MAX_BASIC, %s, %s, %s };   /* EAX max leaf, EBX, EDX, ECX of the vendor string "%s" */' % (hx(v[0]), hx(v[1]), hx(v[2]), ref['vendor_id']),
         'static const u32 L2[4] = { %s };' % ', '.join(hx(I(x)) for x in mod['raw']['2']), 'static const u32 L4[4][4] = {']
    for s in mod['raw']['4']:
        o.append('    { %s | FNVL_CPUID4_CORES%s, %s, %s, %s },' % (hx(I(s[0])), ' | FNVL_CPUID4_SHARE_L3' if I(s[3]) == 4 else '', hx(I(s[1])), hx(I(s[2])), hx(I(s[3]))))
    o[-1] = o[-1].rstrip(',') + ' };'
    o.append('static const u32 E1[4] = { %s };' % ', '.join(hx(x) for x in E1))
    o.append('static const u32 BRAND[3][4] = { %s };      /* "%s" */' % (', '.join('{ ' + ', '.join(hx(x) for x in b[4 * i:4 * i + 4]) + ' }' for i in range(3)), ref['model_name']))
    return '\n'.join(o) + '\n'
FILES = {os.path.join(LIFT, 'rt', 'fnvl_cpuref.h'): abi, os.path.join(LIFT, 'rt', 'rcpref.h'): rcp, os.path.join(LIFT, 'rt', 'cpumodel_tab.inc'): tab}
def main():
    bad = 0
    for p, f in FILES.items():
        t = f()
        if '--check' in sys.argv:
            if not os.path.exists(p) or open(p).read() != t: print('STALE', p); bad = 1
        else: w(p, t)
    return bad
if __name__ == '__main__': sys.exit(main())
