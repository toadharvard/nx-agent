#!/usr/bin/env python3
"""Generate the C side of the CPU fault table (fnvlift/faults.json): rt/fnvl_faults.h (the FNVL_* codes) and rt/seh_faults.inc (the case rows of rt/seh.cc
fnvl_raise).  Deterministic.   gen_faults.py            write both files
                               gen_faults.py --check    exit 1 when a file differs from what the table generates (the recipe stage / gate form)"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); LIFT = os.path.dirname(HERE)
sys.path.insert(0, LIFT)
from fnvlift import faults
def header():
    o = ['/* GENERATED by tools/gen_faults.py from fnvlift/faults.json -- do not edit.  The ONE numbering of the CPU fault kinds: a Form kind (dsl.FAULTS) and the runtime code passed to fnvl_raise(code, at) are the same number. */']
    for r in faults.ROWS:
        if r.get('entry') == 'raise_av': o.append('/* FNVL_AV %d: raised through fnvl_raise_av(access, addr, at), not fnvl_raise */' % r['code'])
        o.append('#define FNVL_%s %d' % (r['name'], r['code']))
    return '\n'.join(o) + '\n'
def rows():
    o = ['/* GENERATED by tools/gen_faults.py from fnvlift/faults.json -- do not edit.  One case per fault code that fnvl_raise serves by table; the custom rows are hand code in seh.cc. */']
    for r in faults.ROWS:
        if r.get('entry') or r.get('custom') or r.get('alias'): continue
        b = 'nt = %su;' % r['status']
        if r['np']: b += ' np = %d;' % r['np']
        if r['eip']: b += ' eip = at + %d;' % r['eip']
        o.append('    case FNVL_%s: %s break;      /* %s */' % (r['name'], b, r['src'].replace('*/', '* /')))
    return '\n'.join(o) + '\n'
FILES = {os.path.join(LIFT, 'rt', 'fnvl_faults.h'): header, os.path.join(LIFT, 'rt', 'seh_faults.inc'): rows}
def main():
    bad = 0
    for p, f in FILES.items():
        t = f()
        if '--check' in sys.argv:
            if not os.path.exists(p) or open(p).read() != t: print('STALE', p); bad = 1
        else: open(p, 'w').write(t)
    return bad
if __name__ == '__main__': sys.exit(main())
