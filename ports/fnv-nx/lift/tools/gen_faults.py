#!/usr/bin/env python3
"""Generate the C side of the CPU fault table (fnvlift/faults.json): fnvl_faults.h (the FNVL_* codes) and seh_faults.inc (the case rows of rt/seh.cc fnvl_raise).
Deterministic, standalone (reads only the record).   gen_faults.py OUTDIR  (recipe stage: input ports/fnv-nx/lift/fnvlift/faults.json)"""
import json, os, sys
REL = 'ports/fnv-nx/lift/fnvlift/faults.json'
def rows_json():
    for root in ('/in', os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..')):
        if os.path.exists(os.path.join(root, REL)): return json.load(open(os.path.join(root, REL)))['rows']
    raise SystemExit('faults.json not found')
ROWS = rows_json()
def header():
    o = ['/* GENERATED by tools/gen_faults.py from fnvlift/faults.json -- do not edit.  The ONE numbering of the CPU fault kinds: a Form kind (dsl.FAULTS) and the runtime code passed to fnvl_raise(code, at) are the same number. */']
    for r in ROWS:
        if r.get('entry') == 'raise_av': o.append('/* FNVL_AV %d: raised through fnvl_raise_av(access, addr, at), not fnvl_raise */' % r['code'])
        o.append('#define FNVL_%s %d' % (r['name'], r['code']))
    return '\n'.join(o) + '\n'
def rows():
    o = ['/* GENERATED by tools/gen_faults.py from fnvlift/faults.json -- do not edit.  One case per fault code that fnvl_raise serves by table; the custom rows are hand code in seh.cc. */']
    for r in ROWS:
        if r.get('entry') or r.get('custom') or r.get('alias'): continue
        b = 'nt = %su;' % r['status']
        if r['np']: b += ' np = %d;' % r['np']
        if r['eip']: b += ' eip = at + %d;' % r['eip']
        o.append('    case FNVL_%s: %s break;      /* %s */' % (r['name'], b, r['src'].replace('*/', '* /')))
    return '\n'.join(o) + '\n'
FILES = {'fnvl_faults.h': header, 'seh_faults.inc': rows}
def main(a):
    os.makedirs(a[0], exist_ok=True)
    for n, f in FILES.items(): open(os.path.join(a[0], n), 'w').write(f())
if __name__ == '__main__': main(sys.argv[1:])
