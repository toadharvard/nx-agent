#!/usr/bin/env python3
"""universe_schema.py OUT.tsv : the schema of universe.tsv, generated from the definitions in the two producers (not written as prose): tools/universe.py (exe) and tools/modlift.py (modules).
Read with ast: the kind lists `PRI` (priority order: the first kind an entry has is its `kind` column, the rest go to the flags), the feature list `FEATS` (flag name = bit index of the entry's instruction features),
and the flag expression `fl = [...]` of each producer (every string literal and format string in it is a flag form). Output rows: producer, item, name, value."""
import ast, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
def assigns(path, name):
    t = ast.parse(open(path).read()); out = []
    for n in ast.walk(t):
        if isinstance(n, ast.Assign) and any(isinstance(x, ast.Name) and x.id == name for x in n.targets): out.append(n)
        if isinstance(n, ast.Assign):          # `a = 1; PRI = [...]` on one line is separate Assign nodes: handled by walk
            pass
    return out
def lits(node):
    return [x.value for x in ast.walk(node) if isinstance(x, ast.Constant) and isinstance(x.value, str)]
def main(out):
    R = []
    for prod, f in (('exe', 'universe.py'), ('modules', 'modlift.py')):
        p = os.path.join(HERE, f)
        pri = next(a for a in assigns(p, 'PRI') if isinstance(a.value, ast.List))
        R += [(prod, 'kind', k, str(i)) for i, k in enumerate(ast.literal_eval(pri.value))]
        if prod == 'exe':
            ft = next(a for a in assigns(p, 'FEATS') if isinstance(a.value, ast.List))
            R += [(prod, 'feature-flag', k, 'bit %d' % i) for i, k in enumerate(ast.literal_eval(ft.value))]
        fl = [a for a in assigns(p, 'fl') if isinstance(a.value, (ast.List, ast.BinOp))]
        for a in fl:
            for s in sorted(set(lits(a.value))):
                if s in ('%s=%d', ): R.append((prod, 'flag-form', s, 'name=count (a count flag only when nonzero)'))
                elif prod == 'modules' and s in ('ud', 'xf', 'reloc-misfit') or s.startswith('%s'): continue
                else: R.append((prod, 'flag', s, 'literal'))
        if prod == 'modules':
            for a in fl:
                for n in ast.walk(a.value):
                    if isinstance(n, ast.Tuple) and len(n.elts) == 2 and isinstance(n.elts[0], ast.Constant) and n.elts[0].value in ('ud', 'xf', 'reloc-misfit'): R.append((prod, 'count-flag', n.elts[0].value, 'name=N when N > 0'))
    R.append(('both', 'flags-column', 'other kinds', 'every kind of the entry except its primary kind (kind column), sorted; `-` when the flags column would be empty (exe)'))
    with open(out, 'w') as o:
        o.write('# universe.tsv schema, generated by tools/universe_schema.py from tools/universe.py and tools/modlift.py: producer, item, name, value\n')
        o.write('# columns of universe.tsv: entry (hex VA), kind, extent (bytes, the SPAN [entry, entry+extent)), flags (comma separated); header line `# base=0x...` states the address base\n')
        for r in R: o.write('\t'.join(r) + '\n')
    print('%d schema rows' % len(R))
if __name__ == '__main__': main(sys.argv[1])
