#!/usr/bin/env python3
"""The exit-bridge generator: one X_<A> per exe address A that a native root defines and lifted code reaches (README "Every address has both entries").

    exitgen.py --rows NATIVE.tsv --out exits.cc [--entries entries.tsv]

NATIVE.tsv: `address(hex)<TAB>native symbol<TAB>descriptor<TAB>pop` per line (`#` lines and blank lines ignored). The address and symbol are the rows of
contract/nativerows.py (the native bodies bound to exe addresses); the descriptor is the SAME grammar and the SAME parser as DISPATCH1's bridges
(tools/bridgegen.py: `conv:ret:args`, the descriptor class of the native's own function type, from the L2 plugin's facts); pop is `callee` or `caller`: who removes the
stack words on return (the exe's `ret N` of A: stdcall/thiscall/fastcall callee, cdecl caller; a fact of the exe, not of the descriptor).
RULE: a row with no descriptor or no pop, a descriptor outside the grammar, a duplicate address or symbol, a descriptor the x86 convention does not define (bridgegen.parse:
a hidden result pointer under `fast`) is a BUILD ERROR listing every such row; nothing is generated.

X_<A> is bridgegen's bridge in the opposite direction. It runs in the lifted state (guest registers in w19..w26, c in x27) and is entered like every lifted function: the return
address is at [esp]. It
  1. reads the x86 arguments from the guest stack (and ecx / edx for this / fast) by the MSVC convention of the descriptor: the hidden result pointer is stack word 0 when the
     result is in memory, then the arguments left to right (the layout bridgegen builds in the other direction),
  2. fnvl_native_enter (rt/imp.h: the caller's guest registers to c->r[], the frame linked; FP is NOT parked: guest -> native body is guest -> guest, rule R-FP),
  3. makes the AAPCS call of the descriptor's signature to the native symbol (an asm-label declaration: any symbol name, mangled or not),
  4. fnvl_native_leave, REGS(), writes the result (eax; edx:eax; ST0 as a binary64 carrier; an aggregate in eax / edx:eax; or the bytes at the hidden pointer with eax = that
     pointer, as MSVC does), and returns: c->ra = [sp], esp = sp + 4 + (pop words * 4 for callee-pop).
--entries F writes `address<TAB>X_<address><TAB>native` rows for the dispatcher's entry list (tools/dispgen.py)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))      # the descriptor parser lives in this tool root: one parser for both directions
import bridgegen

HEAD = '''/* Generated by lift/tools/exitgen.py: the exit bridges X_<A> (lifted code -> a native body of the exe address A). A pure function of the rows. */
#include "fnvl.h"
#include "imp.h"
typedef float v8f __attribute__((vector_size(8)));
typedef float v16f __attribute__((vector_size(16)));
/* byte copies the optimizer must not turn into calls of memcpy (freestanding): the empty asm is in the loop */
static inline void cp(void *d, const void *s, u32 n) { u8 *a = (u8 *)d; const u8 *b = (const u8 *)s; for (u32 i = 0; i < n; i++) { a[i] = b[i]; __asm__ volatile("" ::: "memory"); } }
/* guest memory <-> host bytes, byte by byte through the memory proxy */
static inline void gld(void *d, u32 a, u32 n) { u8 *p = (u8 *)d; for (u32 i = 0; i < n; i++) p[i] = M8(a + i); }
static inline void gst(u32 a, const void *s, u32 n) { const u8 *p = (const u8 *)s; for (u32 i = 0; i < n; i++) M8(a + i) = p[i]; }
static inline float bitsf(u32 u) { union { float f; u32 u; } t; t.u = u; return t.f; }
static inline double bitsd(u64 u) { union { double f; u64 u; } t; t.u = u; return t.f; }
'''


def parse_rows(lines):
    """-> ([(addr, symbol, desc, pop)], [error strings])."""
    rows, bad, seen_a, seen_s = [], [], {}, {}
    for n, ln in enumerate(lines, 1):
        ln = ln.rstrip('\n')
        if not ln.strip() or ln.startswith('#'): continue
        f = ln.split('\t')
        if len(f) < 4 or not f[0] or not f[1]: bad.append('line %d: a row is `address<TAB>symbol<TAB>descriptor<TAB>pop`' % n); continue
        try: a = int(f[0], 16)
        except ValueError: bad.append('line %d: %r is not a hex address' % (n, f[0])); continue
        if not f[2]: bad.append('%08x %s: no descriptor' % (a, f[1])); continue
        if f[3] not in ('callee', 'caller'): bad.append('%08x %s: pop is `callee` or `caller`, not %r' % (a, f[1], f[3])); continue
        try: conv, ret, args, reg_ret = bridgegen.parse(f[2])
        except ValueError as e: bad.append('%08x %s: descriptor %r: %s' % (a, f[1], f[2], e)); continue
        if conv == 'fast' and f[3] == 'caller': bad.append('%08x %s: a __fastcall function pops its own stack words (pop callee)' % (a, f[1])); continue
        if a in seen_a: bad.append('%08x: twice in the list (%s, %s)' % (a, seen_a[a], f[1])); continue
        if f[1] in seen_s: bad.append('symbol %s: two addresses (%08x, %08x)' % (f[1], seen_s[f[1]], a)); continue
        seen_a[a] = f[1]; seen_s[f[1]] = a
        rows.append((a, f[1], f[2], f[3]))
    return sorted(rows), bad


def emit(a, sym, desc, pop):
    conv, ret, args, reg_ret = bridgegen.parse(desc)
    cls, rn, rk, re_ = ret
    rt = {'v': 'void', 'i': 'u32', 'q': 'u64', 'f': 'float', 'd': 'double', 'a': 'G%d' % rn, 'm': 'M%d' % rn, 'h': 'H%s_%d' % (re_, rk)}[cls]
    decl, load, call = [], [], []
    off = 4                                   # [sp] is the return address
    hid = None
    if not reg_ret: hid = 'hid'; load.append('u32 hid = M32(sp + %du);' % off); off += 4
    nregs = 0
    for i, (c, n, k, e) in enumerate(args):
        v = 'a%d' % i
        pt = {'i': 'u32', 'q': 'u64', 'f': 'float', 'd': 'double', 'r': 'u32', 'g': 'G%d' % n, 'h': 'H%s_%d' % (e, k) if c == 'h' else ''}[c]
        decl.append('%s' % pt)
        inreg = (conv == 'this' and i == 0) or (conv == 'fast' and c == 'i' and nregs < 2)
        if inreg:
            load.append('%s %s = %s;' % (pt, v, 'ecx' if (conv == 'this' or nregs == 0) else 'edx')); nregs += 1
        elif c == 'i': load.append('u32 %s = M32(sp + %du);' % (v, off)); off += 4
        elif c == 'f': load.append('float %s = bitsf(M32(sp + %du));' % (v, off)); off += 4
        elif c == 'q': load.append('u64 %s = (u64)M32(sp + %du) | ((u64)M32(sp + %du) << 32);' % (v, off, off + 4)); off += 8
        elif c == 'd': load.append('double %s = bitsd((u64)M32(sp + %du) | ((u64)M32(sp + %du) << 32));' % (v, off, off + 4)); off += 8
        elif c in ('g', 'h'): load.append('%s %s; gld(&%s, sp + %du, %d);' % (pt, v, v, off, n)); off += (n + 3) // 4 * 4
        elif c == 'r': load.append('u8 %s_b[%d]; gld(%s_b, sp + %du, %d); u32 %s = (u32)(unsigned long)%s_b;' % (v, n, v, off, n, v, v)); off += (n + 3) // 4 * 4
        call.append(v)
    words = (off - 4) // 4                    # stack words the callee pops under callee-pop (the hidden pointer is one)
    popb = 4 + (4 * words if pop == 'callee' else 0)
    name = 'nat_%08x' % a
    pre = 'extern %s %s(%s) __asm__("%s");\n' % (rt, name, ', '.join(decl) or 'void', sym)
    callx = '%s(%s)' % (name, ', '.join(call))
    if cls == 'v': do, put = callx + ';', ''
    elif cls == 'i': do, put = 'u32 r = ' + callx + ';', 'eax = r;'
    elif cls == 'q': do, put = 'u64 r = ' + callx + ';', 'eax = (u32)r; edx = (u32)(r >> 32);'
    elif cls in ('f', 'd'): do, put = '%s r = %s;' % (rt, callx), 'fnvl_ret_st0(r);'
    elif reg_ret: do, put = '%s r = %s;' % (rt, callx), 'u32 rw[2] = { 0, 0 }; cp(rw, &r, %d); eax = rw[0]; edx = rw[1];' % rn
    else: do, put = '%s r = %s;' % (rt, callx), 'gst(hid, &r, %d); eax = hid;' % rn        # the result is in memory on the x86 side: the bytes, and the pointer in eax
    body = ('extern "C" __attribute__((section(".text.fnvl"))) void X_%08x(void)   /* %s %s pop %s */\n'
            '{ struct fnvl_nframe nf; u32 sp = esp;\n'
            '%s'
            '  fnvl_native_enter(&nf);\n'
            '  if (__builtin_setjmp((void **)nf.jb)) { c->nf = nf.prev; return; }\n'
            '  %s\n'
            '  fnvl_native_leave(&nf); REGS(); %s c->ra = M32(sp); esp = sp + %du; }\n') % (
            a, sym, desc, pop, ''.join('  %s\n' % x for x in load), do, put, popb)
    return pre, body


def generate(rows):
    """rows [(addr, sym, desc, pop)] -> C++ text. The rows are already validated (parse_rows)."""
    out = [HEAD, bridgegen.types(sorted({r[2] for r in rows}))]
    for a, sym, desc, pop in rows:
        pre, body = emit(a, sym, desc, pop)
        out += [pre, body]
    return '\n'.join(out) + '\n'


def main(argv):
    rows_f = out = ent = None; i = 0
    while i < len(argv):
        if argv[i] == '--rows': rows_f = argv[i + 1]
        elif argv[i] == '--out': out = argv[i + 1]
        elif argv[i] == '--entries': ent = argv[i + 1]
        else: sys.exit('usage: exitgen.py --rows NATIVE.tsv --out exits.cc [--entries entries.tsv]')
        i += 2
    if not rows_f or not out: sys.exit('exitgen: --rows and --out are required')
    with open(rows_f) as f: rows, bad = parse_rows(f)
    if bad: sys.exit('exitgen: %d native rows have no exit bridge:\n%s' % (len(bad), '\n'.join(bad)))
    with open(out, 'w', newline='') as f: f.write(generate(rows))
    if ent:
        with open(ent, 'w', newline='') as f: f.write(''.join('%08x\tX_%08x\tnative\n' % (r[0], r[0]) for r in rows))
    print('exitgen: %d exit bridges' % len(rows))


if __name__ == '__main__': main(sys.argv[1:])
