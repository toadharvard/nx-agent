#!/usr/bin/env python3
"""Generate gen/fnvl_sys.h (included by rt/fnvl.h) from the declared x86 system record platform/declared/x86sys.json: SEL_CS SEL_DS SEL_ES SEL_SS SEL_FS SEL_TR (selectors) and fnvl_seg_ok (the
selectors MOV/POP/LxS may load into each segment register at CPL 3, SDM Vol 3 MOV-to-Sreg: a data segment of DPL 3 loads with any RPL, SS needs RPL = CPL = 3 and a writable data segment, the null
selector loads into ES/DS/FS/GS only).  A selector the record leaves undecided (mov_to_sreg.undecided) calls fnvl_undecided_selector, which is declared and has NO definition: code that can load
it does not link.  Deterministic, standalone (reads only the record).   gen_sys.py RECORD OUTDIR  -> OUTDIR/fnvl_sys.h   (recipe stage: RECORD = the platform root's output X86SYS, taken through `uses`)"""
import json, os, sys
def record(path): return json.load(open(path))
def header(rec):
    sel = {n: v['value'] for n, v in rec['selectors'].items() if 'value' in v}
    o = ['/* GENERATED by tools/gen_sys.py from platform/declared/x86sys.json -- do not edit. */']
    for n in ('cs', 'ds', 'es', 'ss', 'fs', 'tr'): o.append('#define SEL_%s 0x%xu' % (n.upper(), sel[n]))
    o.append('#define FNVL_TR_SEL SEL_TR')
    o.append('extern "C" void fnvl_undecided_selector(u32 sel);      /* no definition: x86sys.json leaves this selector undecided */')
    und = sorted({s & 0xfffc for s in rec['mov_to_sreg']['undecided']['selectors']})
    o.append('static inline u32 fnvl_seg_ok(u32 idx, u32 sel){ u32 k=SELK(sel);')
    for r, idx in (('ss', 'SEG_SS'), ('es', 'SEG_ES'), ('ds', 'SEG_DS'), ('fs', 'SEG_FS'), ('gs', 'SEG_GS')):
        sels, null = rec['mov_to_sreg'][r]['selectors'], rec['mov_to_sreg'][r]['null']
        idxs = sorted({s & 0xfffc for s in sels})
        ok = ' || '.join(['k==0'] * bool(null) + ['k==0x%xu' % i for i in idxs]) or '0'
        if r == 'ss': o.append('  if(idx==%s) return (sel&3u)==3u && (%s);' % (idx, ok))
        else:
            u = ''.join('if(k==0x%xu) fnvl_undecided_selector(sel); ' % i for i in und)
            o.append('  if(idx==%s){ %sreturn %s; }' % (idx, u, ok))
    o.append('  return 0; }')
    return '\n'.join(o) + '\n'
def main(a):
    out = a[1]; os.makedirs(out, exist_ok=True)
    open(os.path.join(out, 'fnvl_sys.h'), 'w').write(header(record(a[0])))
if __name__ == '__main__': main(sys.argv[1:])
