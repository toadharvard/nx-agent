"""SDM specs (OWNER 10: the x86 ISA outside the pinned formal models; the pinned Sail model is 64-bit oriented and answers `illegal in 64-bit mode` or `Opcode Unimplemented` for all of these) of the legacy integer
instructions DAA DAS AAA AAS AAM AAD, SALC, SLDT, far RET and LES / LDS, each compared with the DSL Form (symform.symbuild) by z3 (`unsat` of a difference, as in sysspec_gap).  Every SDM quote is checked by
sdm_cite_check.py against sysspec_legacy_pages.tsv (generated by sdm_pages.py from this file).  A spec claims a key by DECODING it (the mnemonic of the decoded instruction), never by a key list.  Declared values are read
from the record (platform/declared/x86sys.json through proof/x86sys.py).  Result: proved | FAILED(dsl) | uncertified: <why> | not-covered.  Result texts: sysspec_text.py.  The guest is a 32-bit process (compatibility
mode), so the Operation's `ELSE` of `IF 64-Bit Mode` is the behaviour.

DAA, SDM 2A:DAA
  'IF (((AL AND 0FH) > 9) or AF = 1)'   'AL := AL + 6;'   'CF := old_CF or (Carry from AL := AL + 6);'   'AF := 1;'   'AF := 0;'   (the ELSE)
  'IF ((old_AL > 99H) or (old_CF = 1))'   'AL := AL + 60H;'   'CF := 1;'   'CF := 0;'   (the ELSE: DAA has it)
  'The SF, ZF, and PF flags are set according to the result. The OF flag is undefined.'
DAS, SDM 2A:DAS
  'AL := AL - 6;'   'CF := old_CF or (Borrow from AL := AL - 6);'   'IF ((old_AL > 99H) or (old_CF = 1))'   'AL := AL - 60H;'   'CF := 1;'   (no ELSE: CF keeps the value of the first test)
  'The SF, ZF, and PF flags are set according to the result. The OF flag is unde'
AAA, SDM 2A:AAA
  'IF ((AL AND 0FH) > 9) or (AF = 1)'   'AX := AX + 106H;'   'AL := AL AND 0FH;'   'The OF, SF, ZF, and PF flags are undefined.'
AAS, SDM 2A:AAS
  'IF ((AL AND 0FH) > 9) or (AF = 1)'   'AX := AX - 6;'   'AH := AH - 1;'   'AL := AL AND 0FH;'   'The OF, SF, ZF, and PF flags are undefined.'
AAM, SDM 2A:AAM
  'AH := tempAL / imm8; (* imm8 is set to 0AH for the AAM mnemonic *)'   'AL := tempAL MOD imm8;'   '#DE                      If an immediate value of 0 is used.'
  'The SF, ZF, and PF flags are set according to the resulting binary value in the AL register.'   'The OF, AF, and CF flags are undefined.'
AAD, SDM 2A:AAD
  'AL := (tempAL + (tempAH ∗ imm8)) AND FFH;'   'AH := 0;'   'The SF, ZF, and PF flags are set according to the resulting binary value in the AL register;'
SALC, SDM 2B:SALC
  'Sets register AL to either 00H or FFH depending on the value of the carry flag (CF).'   'THEN AL := 00H;'   'ELSE AL := FFH;'   'Flags Affected None.'
SLDT, SDM 2B:SLDT
  'DEST := LDTR(SegmentSelector);'   'the segment selector is written to memory as a 16-bit quantity, regardless of'   'The high-order 16 bits of the register are cleared'
  The LDTR selector is the record's sldt row (a new process has the null LDTR).
LES / LDS, SDM 2A:LDS
  'SegmentRegister := SegmentSelector(SRC) AND RPL;'   'DEST := Offset(SRC);'   the selector classes are those of MOV Sreg (sysspec_seg: the record's mov_to_sreg rows).  The far pointer is the
  offset (16 or 32 bits) at the effective address and the selector 2 or 4 bytes above it.
RETF, SDM 2B:RET and SDM 2B:P1860, SDM 2B:P1861
  'IF return code segment selector RPL < CPL'   'EIP := Pop();'   'CS := Pop(); (* 32-bit pop, high-order 16 bits discarded *)'   'ESP := ESP + SRC;'   'IF return code segment selector is NULL'
  'IF return code segment descriptor is not a code segment'   'IF return code segment selector addresses descriptor beyond descriptor table limit'
  The descriptor classes are the record's (rows jmp_far, gdt, ldt through sysspec_far.rows): a #GP is the access violation of the declared machine (fault kind AV).
"""
