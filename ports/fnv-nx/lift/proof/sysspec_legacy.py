V = G.V
LEGACY_PFX = (0x66, 0x67, 0x2e, 0x36, 0x3e, 0x26, 0x64, 0x65, 0xf0, 0xf2, 0xf3)
ROWS = {'sgdt': (('sgdt', 'limit'), ('sgdt', 'base')), 'iretd': (('iret',),), 'iret': (('iret',),)}      # the record rows the Form of each needs (iret: no row exists today; the Form builder names the same blockers)
BCD = ('daa', 'das', 'aaa', 'aas', 'aam', 'aad')
K_DE, K_AV = FT['DE0']['code'], FT['AV']['code']


def family(ins):
    """the spec that claims the decoded instruction (by its mnemonic and operand kinds), or None"""
    m = ins.mnemonic.split()[-1]; o = ins.operands
    b = bytes(ins.bytes); i = 0
    while i < len(b) and b[i] in LEGACY_PFX: i += 1
    if i + 1 < len(b) and b[i] != 0x0f and (b[i], (b[i + 1] >> 3) & 7) in intud.CLEARED_UD: return 'cleared'      # by encoding (opcode byte, ModRM.reg), whatever mnemonic the decoder gives
    if m in BCD or m in ('salc', 'sldt'): return m
    if m in ('les', 'lds') and len(o) == 2 and o[1].type == X.X86_OP_MEM: return m
    if m in ('retf', 'lret'): return 'retf'
    if m in ('sgdt', 'iretd', 'iret'): return 'row'
    return None


def same(a, b):
    s = z3.Solver(); s.add(a != b); return s.check() == z3.unsat


def unsat(*a):
    s = z3.Solver(); s.add(*a); return s.check() == z3.unsat


def b(n, lo=0): return z3.BitVec(n, 8)


def spec_bcd(ins, fields):
    """-> (regs, flags, faults-wanted, undefined flags) of the Operation, over the pre-state eax, cf, af"""
    m = ins.mnemonic.split()[-1]; ax = z3.Extract(15, 0, V('eax')); al = z3.Extract(7, 0, ax); ah = z3.Extract(15, 8, ax)
    cf, af = V('cf', 1), V('af', 1); one = z3.BitVecVal(1, 1)
    new = lambda x: z3.Concat(z3.Extract(31, 16, V('eax')), x)
    hi4 = lambda a: z3.Extract(3, 0, a)
    gt9 = z3.UGT(z3.ZeroExt(4, hi4(al)), z3.BitVecVal(9, 8))
    if m in ('daa', 'das'):
        adj = z3.Or(gt9, af == one); old_al, old_cf = al, cf
        t = al - 6 if m == 'das' else al + 6
        carry = z3.ULT(al, 6) if m == 'das' else z3.ULT(t, al)                       # the Borrow / Carry of AL := AL -/+ 6
        al1 = z3.If(adj, t, al); cf1 = z3.If(adj, z3.If(z3.Or(old_cf == one, carry), one, z3.BitVecVal(0, 1)), z3.BitVecVal(0, 1)); af1 = z3.If(adj, one, z3.BitVecVal(0, 1))
        hi = z3.Or(z3.UGT(old_al, z3.BitVecVal(0x99, 8)), old_cf == one)
        al2 = z3.If(hi, al1 - 0x60 if m == 'das' else al1 + 0x60, al1)
        cf2 = z3.If(hi, one, z3.BitVecVal(0, 1) if m == 'daa' else cf1)               # DAA: ELSE CF := 0; DAS: no ELSE
        flags = {'cf': cf2, 'af': af1, 'zf': z3.If(al2 == 0, one, z3.BitVecVal(0, 1)), 'sf': z3.Extract(7, 7, al2), 'pf': parity(al2)}
        return {'eax': new(z3.Concat(ah, al2))}, flags, None, {'of'}
    if m in ('aaa', 'aas'):
        adj = z3.Or(gt9, af == one)
        ax1 = ax - 6 if m == 'aas' else ax + 0x106
        if m == 'aas': ax1 = z3.Concat(z3.Extract(15, 8, ax1) - 1, z3.Extract(7, 0, ax1))      # AX := AX - 6; AH := AH - 1
        ax2 = z3.If(adj, ax1, ax); ax3 = z3.Concat(z3.Extract(15, 8, ax2), z3.Extract(7, 0, ax2) & 0xf)
        f = z3.If(adj, one, z3.BitVecVal(0, 1))
        return {'eax': new(ax3)}, {'af': f, 'cf': f}, None, {'of', 'sf', 'zf', 'pf'}
    imm = z3.BitVec('fld_imm', 8) if fields['imm'] else z3.BitVecVal(ins.operands[0].imm & 0xff, 8)
    if m == 'aam':
        r = z3.URem(al, imm)
        flags = {'zf': z3.If(r == 0, one, z3.BitVecVal(0, 1)), 'sf': z3.Extract(7, 7, r), 'pf': parity(r)}
        return {'eax': new(z3.Concat(z3.UDiv(al, imm), r))}, flags, imm == 0, {'of', 'af', 'cf'}
    r = al + ah * imm                                                                 # AL := (tempAL + (tempAH * imm8)) AND FFH, in 8 bits
    flags = {'zf': z3.If(r == 0, one, z3.BitVecVal(0, 1)), 'sf': z3.Extract(7, 7, r), 'pf': parity(r)}
    return {'eax': new(z3.Concat(z3.BitVecVal(0, 8), r))}, flags, None, {'of', 'af', 'cf'}


def parity(r):
    """PF: 1 iff the low byte has an even number of set bits (SDM 1:3.4.3.1 'PF (bit 2) Parity flag')"""
    x = z3.Extract(0, 0, r)
    for i in range(1, 8): x = x ^ z3.Extract(i, i, r)
    return x ^ z3.BitVecVal(1, 1)


def check_bcd(ins, f, fields):
    regs, flags, fault, und = spec_bcd(ins, fields); d = []
    if ins.prefix[2]: return 'uncertified', TEXT['o16']
    if fault is None:
        if f.faults: d.append('faults')
    elif len(f.faults) != 1 or f.faults[0][0] != K_DE or not same(dsl.to_smt(f.faults[0][1]) == 1, fault): d.append('fault')
    if f.swhen or f.flo is not None or f.stores or f.xs: d.append(TEXT['cond'])
    pr = {r[0]: dsl.to_smt(r[1]) for r in f.regs}
    for n in sorted(set(pr) | set(regs)):
        if not same(pr.get(n, V(n)), regs.get(n, V(n))): d.append(n)
    pf = {r[0]: dsl.to_smt(r[1]) for r in f.flags}
    for n in sorted(flags):
        if n not in pf or not same(pf[n], flags[n]): d.append(n)
    for n in sorted(set(pf) - set(flags)): d.append(n + '(written)')
    if set(f.undef) != und: d.append('undefined=%s' % ','.join(sorted(f.undef)))
    if not same(dsl.to_smt(f.eip), V('eip') + ins.size): d.append('eip')
    return ('proved', TEXT['ok'] % ins.mnemonic.split()[-1].upper()) if not d else ('FAILED(dsl)', TEXT['diff'] % ','.join(d))


def check_salc(ins, f):
    new = z3.Concat(z3.Extract(31, 8, V('eax')), z3.If(V('cf', 1) == 1, z3.BitVecVal(0xff, 8), z3.BitVecVal(0, 8)))
    d = G.compare(f, ins, {'eax': new}, {}, None)
    return ('proved', TEXT['ok'] % 'SALC') if not d else ('FAILED(dsl)', TEXT['diff'] % ','.join(d))


def check_sldt(ins, f, fields, rec):
    v = z3.BitVecVal(x86sys.get(rec, 'sldt'), 16); dst = ins.operands[0]
    if dst.type == X.X86_OP_REG:
        r = ins.reg_name(dst.reg)
        if dst.size == 4: d = G.compare(f, ins, {r: z3.ZeroExt(16, v)}, {}, None)       # the high-order 16 bits of a 32-bit register are cleared (SLDT above)
        else: return 'uncertified', TEXT['sldt16']
    else:
        a = G.ea(ins, fields); m = dsl.mem_array()
        d = G.compare(f, ins, {}, {}, z3.Store(z3.Store(m, a, z3.Extract(7, 0, v)), a + 1, z3.Extract(15, 8, v)))      # a 16-bit quantity regardless of the operand size
    return ('proved', TEXT['ok'] % 'SLDT') if not d else ('FAILED(dsl)', TEXT['diff'] % ','.join(d))


def check_lseg(ins, f, fields, rec):
    import sysspec_seg
    reg = ins.mnemonic.split()[-1][1:]; w = 16 if ins.prefix[2] == 0x66 else 32
    if rec['mov_to_sreg']['undecided']['selectors']: return 'FAILED(dsl)', TEXT['noundecided']      # the spec says the record decides nothing: the Form raises UndecidedRow before
    a = G.ea(ins, fields); m = dsl.mem_array(); nb = w // 8
    sel = z3.ZeroExt(16, z3.Concat(*[z3.Select(m, a + nb + i) for i in (1, 0)])); off = z3.Concat(*[z3.Select(m, a + i) for i in reversed(range(nb))])
    d = []
    if len(f.faults) != 1 or f.faults[0][0] != K_AV or not same(dsl.to_smt(f.faults[0][1]) == 1, z3.Not(sysspec_seg.loadable(reg, sel, rec))): d.append('fault')
    if [x[:2] for x in f.xs] != [('sel', G.SREGS.index(reg))] or not same(dsl.to_smt(f.xs[0][2]), z3.Extract(15, 0, sel)): d.append('selector')
    dst = ins.reg_name(ins.operands[0].reg); pr = {r[0]: dsl.to_smt(r[1]) for r in f.regs}
    want = off if w == 32 else z3.Concat(z3.Extract(31, 16, V(dst)), off)
    if list(pr) != [dst] or not same(pr[dst], want): d.append(dst)
    if f.flags or f.stores or f.swhen or not same(dsl.to_smt(f.eip), V('eip') + ins.size): d.append('effects')
    return ('proved', TEXT['ok'] % ins.mnemonic.split()[-1].upper()) if not d else ('FAILED(dsl)', TEXT['diff'] % ','.join(d))


def check_retf(ins, f, fields, rec):
    import sysspec_far
    w = 16 if ins.prefix[2] == 0x66 else 32; nb = w // 8
    r = sysspec_far.rows(rec); cs = x86sys.get(rec, 'selectors', 'cs'); m = dsl.mem_array(); esp = V('esp')
    ld = lambda a, n: z3.Concat(*[z3.Select(m, a + i) for i in reversed(range(n))])
    sel = ld(esp + nb, 2); eip = ld(esp, nb); cl = sysspec_far.classes(sel, r); cpl = x86sys.cpl(rec)
    ret_valid = z3.And(cl['valid'], sel & 3 == cpl)                                    # an RPL below the CPL is #GP (RETF above): the valid class of the jump rows needs RPL = CPL
    imm = (z3.BitVec('fld_imm', 16) if fields['imm'] else z3.BitVecVal(ins.operands[0].imm & 0xffff, 16)) if ins.operands else z3.BitVecVal(0, 16)
    if any(k != K_AV for k, _ in f.faults) or not f.faults: return 'FAILED(dsl)', TEXT['diff'] % 'faults'
    fault = z3.Or([dsl.to_smt(c) == 1 for _, c in f.faults]); out = []
    out.append(('valid', unsat(ret_valid, fault))); out.append(('rpl', unsat(sel & 3 != cpl, z3.Not(fault))))
    for n in ('null', 'ti1', 'beyond', 'gp'): out.append((n, unsat(cl[n], z3.Not(fault))))
    out.append(('cs-selector', unsat(ret_valid, sel != cs)))
    pr = {r_[0]: dsl.to_smt(r_[1]) for r_ in f.regs}
    out.append(('esp', list(pr) == ['esp'] and unsat(ret_valid, pr['esp'] != esp + (2 * nb) + z3.ZeroExt(16, imm))))
    out.append(('eip', unsat(ret_valid, dsl.to_smt(f.eip) != z3.ZeroExt(32 - w, eip))))
    out.append(('no-store', not f.stores and not f.flags and not f.xs))
    bad = [n for n, ok in out if not ok]
    if bad: return 'FAILED(dsl)', TEXT['diff'] % ','.join(bad)
    return 'uncertified', TEXT['retf'] % (','.join(n for n, _ in out), sysspec_far.domain(rec))


def opcode(key):
    """(the opcode byte, ModRM.reg) of a one-byte-opcode shape key, after its legacy prefixes"""
    b = shape.rep_bytes(key); i = 0
    while b[i] in LEGACY_PFX: i += 1
    return b[i], (b[i + 1] >> 3) & 7


def cleared(key):
    """the encoding has no cell in the SDM opcode map (intud.CLEARED_UD, evidence tests/opmap_cells.tsv); the Form is fault(UD), valid only under L3a's unreachable-or-data certificate of the site"""
    return 'uncertified', TEXT['cleared'] % intud.CLEARED_UD[opcode(key)]


def check(key, rec=None):
    ins = G.decode(key); fam = family(ins)
    if fam is None: return 'not-covered', 'no spec'
    if fam == 'cleared': return cleared(key)      # a prefix takes no part
    rec = rec or x86sys.load()
    if fam == 'row':      # the rows of the CONFIGURED record decide: an undecided or absent row is the blocker; a prefix takes no part
        for path in ROWS[ins.mnemonic.split()[-1]]: x86sys.get(rec, *path)      # raises x86sys.Undecided (sysspec.check: uncertified: <why>)
        try: symform.symbuild(key)
        except KeyError: return 'not-covered', 'no Form'
        return 'not-covered', TEXT['nospec']      # the record decides the rows and a Form builds: its spec belongs here
    why = G.unclaimed_prefix(ins, key)
    if why: return 'uncertified', TEXT['unc'] % why
    lead = shape.rep_bytes(key)
    for x in lead:
        if x in (0xf0, 0xf2, 0xf3): return 'uncertified', TEXT['unc'] % (TEXT['rep'] % x)      # LOCK / REP on a non-string instruction: reserved (SDM 2A:2.1.1), no effect is specified
        if x not in LEGACY_PFX: break
    fields = symform.parse_key(key)[1]
    try: f = symform.symbuild(key).form
    except KeyError: return 'not-covered', 'no Form'
    except dsl.UndecidedRow as e: return 'uncertified', TEXT['unc'] % e
    if fam in BCD: return check_bcd(ins, f, fields)
    if fam == 'salc': return check_salc(ins, f)
    if fam == 'sldt': return check_sldt(ins, f, fields, rec)
    if fam in ('les', 'lds'): return check_lseg(ins, f, fields, rec)
    return check_retf(ins, f, fields, rec)
