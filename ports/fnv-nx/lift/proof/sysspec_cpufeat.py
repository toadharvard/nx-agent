"""SDM spec (OWNER 10) of the instructions whose CPUID feature the declared CPU clears (forms_cpufeat.py), compared with the DSL Form (symform.symbuild).  Every SDM quote is checked by sdm_cite_check.py against
sysspec_cpufeat_pages.tsv (generated by sdm_pages.py from this file).  The spec claims a key by DECODING it (the decoder's capstone groups through fnvlift/f_cpufeat.py, the one reader of the feature table and the declared
CPU's words), never by a key list or mnemonic.  Result: proved | FAILED(dsl) | not-covered.  The Form is valid only for a site that L3a's call-graph certificate shows unreachable on the declared CPU or data; reachability is not decided here.

#UD, SDM 3A:P3382, Event 6 (Invalid Opcode Exception):
  'Attempted to execute an invalid or reserved opcode.'
  3DNow (0F 0E, 0F 0F): the Intel SDM Table A-3 has no cell at those opcodes (tests/opmap_cells.tsv), so they are the invalid or reserved opcode of Event 6.
  'Attempted to execute an MMX or SSE/SSE2/SSE3 instruction on an Intel 64 or IA-32 processor that does not'      support the extension: #UD (the flags MMX, SSE, SSE2, SSE3, SSSE3 are the CPUID bits the model reports)
  SSE3 (FISTTP), SDM 2A:P1054:  '#UD                      If CPUID.01H:ECX.SSE3[0] = 0.'
  AVX (VEX-encoded), SDM 2A:P648, the exception table of the VEX-encoded instructions:  'If CPUID.01H:ECX.AVX[28]=0.'
The Form: the fault #UD, always, and nothing else (no register, flag, store or segment effect).
NOP, SDM 1:P579, Appendix E (Intel MPX), E.4.1 Instruction Encoding:
  'All Intel MPX instructions are NOP on processors that report CPUID.07H.00H:EBX.MPX[14] = 0'
The opcodes 0F 1A and 0F 1B hold only MPX cells (opmap).  The Form has no effect: no register, flag, memory access or fault; EIP advances over the encoding.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import z3  # noqa: E402
from fnvlift import dsl, inputs  # noqa: E402
from fnvlift.faults import BYNAME as FT  # noqa: E402
from proof import forms_cpufeat, shape, symform  # noqa: E402
import sysspec_gap as G  # noqa: E402
from sysspec_text import CPUFEAT as TEXT  # noqa: E402

K_UD = FT['UD']['code']
LEGACY_PFX = (0x66, 0x67, 0x2e, 0x36, 0x3e, 0x26, 0x64, 0x65, 0xf0, 0xf2, 0xf3)


def kind(ins):
    """'ud' | 'nop' | None for the decoded instruction (forms_cpufeat.decide over its bytes); None also when the cpufeat input is not configured"""
    b = bytes(ins.bytes); i = 0
    while i < len(b) and b[i] in LEGACY_PFX: i += 1
    return forms_cpufeat.decide(ins, b, i)


def check(key, rec=None):
    ins = G.decode(key); k = kind(ins)
    if k is None: return 'not-covered', TEXT['none']
    try: f = symform.symbuild(key).form
    except KeyError: return 'FAILED(dsl)', TEXT['noform']
    d = []
    if f.regs or f.flags or f.stores or f.xs or f.swhen or f.flo is not None: d.append('effects')
    if k == 'ud':
        if len(f.faults) != 1 or f.faults[0][0] != K_UD or G.differs(dsl.to_smt(f.faults[0][1]), z3.BitVecVal(1, 1)) is not False: d.append('fault')
    else:
        if f.faults: d.append('fault')
        if G.differs(dsl.to_smt(f.eip), G.V('eip') + ins.size): d.append('eip')
    from fnvlift import f_cpufeat
    what = ','.join(f_cpufeat.missing(next(iter(shape.decoder().disasm(bytes(ins.bytes), 0))))) or 'MPX'
    return ('proved', TEXT['ud' if k == 'ud' else 'nop'] % what) if not d else ('FAILED(dsl)', TEXT['diff'] % ','.join(d))
