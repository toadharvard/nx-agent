#!/usr/bin/env python3
"""Mechanical check of the ACL2 citations of proof/simdspec.py against the pinned ACL2 tree (acl2/acl2 3ccb342c, books/projects/x86isa/machine/instructions).
    python3 -I acl2_cite_check.py DIR [--write]
DIR = the checkout root.  A cite is (file, def-inst name, quote): the quote must occur (whitespace-normalised) in the body of `(def-inst NAME` (up to the next def-inst).
Without --write the resolved file:line of every cite must equal the row of acl2_cites.tsv (the committed record); with --write that file is regenerated.
Exit 0 = every cite resolves and matches.  Output: OK/MISS lines."""
import os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import simdspec as S
REL = 'books/projects/x86isa/machine/instructions'
RTL = 'books/rtl/rel11/lib'
TSV = os.path.join(HERE, 'acl2_cites.tsv')


def cites():
    out = {}
    for r in S.ROWS.values():
        cs = r.cites
        name = r.name
        for c in cs: out[c] = None
    for c in getattr(S, 'EXTRA_CITES', ()): out[c] = None
    return sorted(out)


def resolve(root, c):
    f, inst, q = c
    base = RTL if f.startswith('rtl/') else REL                              # rtl/<file>: the RTL library the x86isa FP books include (books/rtl/rel11/lib)
    lines = open(os.path.join(root, base, f[4:] if f.startswith('rtl/') else f), encoding='utf-8', errors='replace').read().split('\n')
    start = next((i for i, l in enumerate(lines) if re.match(r'\((def-inst|defund|defun|define)\s+' + re.escape(inst) + r'(\s|$)', l.strip())), None)
    if start is None: return None
    nq = ' '.join(q.split())
    for i in range(start + 1, len(lines)):
        if lines[i].startswith(('(def-inst ', '(defund ', '(defun ', '(define ')): break
        if nq in ' '.join(lines[i].split()): return i + 1
    return None


def main(a):
    root, write = a[0], '--write' in a
    rec = {}
    if os.path.exists(TSV) and not write:
        for l in open(TSV):
            if l.strip() and not l.startswith('#'):
                f, ln, inst, q = l.rstrip('\n').split('\t'); rec[(f, inst, q)] = int(ln)
    bad, rows = 0, []
    for c in cites():
        ln = resolve(root, c)
        if ln is None: print('MISS', c); bad += 1; continue
        if not write and rec.get(c) != ln: print('STALE', c, rec.get(c), ln); bad += 1; continue
        rows.append((c[0], ln, c[1], c[2]))
    if write:
        with open(TSV, 'w') as fh:
            fh.write('# acl2/acl2 3ccb342c %s: file, line, def-inst, quote (regenerated by acl2_cite_check.py DIR --write)\n' % REL)
            for f, ln, inst, q in rows: fh.write('%s\t%d\t%s\t%s\n' % (f, ln, inst, q))
    print('cites', len(cites()), 'bad', bad)
    return 1 if bad else 0


if __name__ == '__main__': sys.exit(main(sys.argv[1:]))
