"""SDM specs (OWNER 10: the part of the x86 ISA that no pinned formal model covers) of the instructions the pinned Sail model answers `Opcode Unimplemented` / does not execute, each compared with the DSL Form (symform.symbuild)
by z3 (the comparison is `unsat` of a difference, as in sysspec_str / stringspec).  Every SDM quote is checked by sdm_cite_check.py against sysspec_gap_pages.tsv (generated by sdm_pages.py from this file).
A spec claims a key by DECODING it (the mnemonic and operand kinds of the decoded instruction), so every key of one of these instructions falls under it by rule.  Result of check(): proved | FAILED(dsl) | uncertified: <why> | not-covered.
Declared values are read from the record (platform/declared/x86sys.json through proof/x86sys.py); nothing of it is held here.

BSWAP, SDM 2A:BSWAP
  'Reverses the byte order of a 32-bit or 64-bit (destination) register.'   Operation, the 32-bit case (OperandSize is 32 outside 64-bit mode):
  'DEST[7:0] := TEMP[31:24];'   'DEST[15:8] := TEMP[23:16];'   'DEST[23:16] := TEMP[15:8];'   'DEST[31:24] := TEMP[7:0];'     Flags: 'None.'
  'When the BSWAP instruction references a 16-bit register, the result is undefined.'  (a 0x66-prefixed form is uncertified: nothing is specified)
XLAT/XLATB, SDM 2D:XLAT
  'AL := (DS:EBX + ZeroExtend(AL));'  with the 32-bit address size ('ELSE IF (AddressSize = 32)'); 'Flags Affected' None.  A 0x67 prefix or a segment override is outside this spec (uncertified).
MOV r/m16, Sreg and MOV r32, Sreg, SDM 2B:P1317 / P1318
  'Move zero extended 16-bit segment register to r16/r32/m16.'   'DEST := SRC;'   'the processor copies the content of Sreg to the 16 least significant bits of the'
  SRC is the selector of the segment register, the pre-state variable sel_<reg> (fnvlift/dsl.py XIN: the six selectors of the guest context).  The values it can hold are the record's: the initial ones
  (`selectors` rows) and the loadable ones (`mov_to_sreg`); a register whose `selectors` row is undecided is `uncertified: <the row's why>`.
  The memory operand is written as 16 bits whatever the operand size: the value is a 16-bit quantity ('r16/r32/m16' above), and the effective address is the ModRM offset:
  SDM 1:P89  'Offset = Base + (Index * Scale) + Displacement'   SDM 2A:P622  'The disp8 nomenclature denotes an 8-bit displacement that follows the ModR/M byte (or the SIB byte if one is present) and that is sign-extended and added to the index.'
BTS, SDM 2A:BTS and BT, SDM 2A:P816 (memory bit strings)
  'CF := Bit(BitBase, BitOffset);'   'Bit(BitBase, BitOffset) := 1;'   'The CF flag contains the value of the selected bit before it is set. The ZF flag is unaffected.'   'flags are undefined.' (OF SF AF PF)
  'If the bit base operand specifies a register, the instruction takes the modulo 16, 32, or 64 of the bit offset'
  'the operand represents the address of the byte in memory that contains the bit base (bit 0 of the specified byte) of the bit string.'
  SDM 2A:P697 'Bits are numbered from low-order to high-order within registers and within memory bytes.'
  With a register offset the bit offset is a signed number, the bit is bit (offset mod 8) of the byte at address + (offset DIV 8) (DIV = floor); with an immediate offset the processor
  SDM 2A:P816 'The processor will ignore the high order bits if they are not zero.'   so the offset is the immediate modulo the operand size.
  SDM 2A:P816 'the processor may access 4 bytes starting from the memory address for a 32-bit'   (the dword of the Form covers the same bit; the comparison is on the whole memory, so the unchanged bytes it rewrites are equal).
"""
