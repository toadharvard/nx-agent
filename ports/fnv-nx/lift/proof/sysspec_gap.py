import capstone.x86_const as X  # noqa: E402
import z3  # noqa: E402
from fnvnx.lift.fnvlift import dsl  # noqa: E402
from fnvnx.lift.proof import shape, symform, x86sys  # noqa: E402
from fnvnx.lift.proof.sysspec_text import GAP as TEXT  # noqa: E402       # result texts: not SDM quotes, so kept out of the quoted file

SREGS = ('es', 'cs', 'ss', 'ds', 'fs', 'gs')


def V(n, w=32): return dsl.to_smt(dsl.V(n, w))


def decode(key):
    return next(iter(shape.decoder().disasm(symform.parse_key(key)[0], shape.ADDR)))


def family(ins):
    """the spec that claims the decoded instruction, by its mnemonic and operand kinds (never by a key list), or None"""
    m = ins.mnemonic.split()[-1]
    o = ins.operands
    if m == 'bswap': return 'bswap'
    if m in ('xlat', 'xlatb'): return 'xlat'
    if m == 'bts': return 'bts'
    if m == 'mov' and len(o) == 2 and o[1].type == X.X86_OP_REG and ins.reg_name(o[1].reg) in SREGS and o[0].type in (X.X86_OP_MEM, X.X86_OP_REG): return 'movsreg'
    return None


def consumed(key):
    """the address kinds the Form of the key uses (forms.ACC): explicit (a ModRM/SIB address), ds (implicit DS source), es, stack (implicit SS), areg (an address-size register of string/loop/xlat); None when no Form builds"""
    try: return symform.symbuild(key).form.access
    except Exception: return None


def unclaimed_prefix(ins, key=None):
    """a prefix outside the spec -> why.  Claimed by its SDM scope, from the Form's address kinds and the operands (never a mnemonic or a key list):
      a segment override (26 2E 36 3E 64 65) applies to an explicit memory operand or an implicit DS-default operand only; a push or pop reference is always SS (SDM 1:3.7.4 'Push and pop operations must always reference the SS segment.'; SDM 1:6.2.3 the stack address attribute is that of the stack segment, not of an instruction prefix), so a Form
      whose addresses are stack and ES only takes the prefix with no effect;
      0x67 is consumed by an explicit address, a string/xlat/loop/jcxz register; on an instruction with none SDM 2A:2.1.1 'Using this prefix and/or other undefined opcodes when operands for the instruction do not reside in memory is reserved; such use may cause unpredictable behavior.' calls the use reserved: it stays unclaimed (TEXT['addr']);
      LOCK/REP stay outside."""
    rp, seg, _op, addr = ins.prefix
    mem = [x for x in ins.operands if x.type == X.X86_OP_MEM]
    kinds = consumed(key) if key else None
    used = (kinds is None) or bool(kinds & {'explicit', 'ds'}) or bool(mem)
    if addr and ((kinds is None) or bool(kinds & {'explicit', 'ds', 'areg'}) or bool(mem)): return TEXT['addr']
    if addr: return TEXT['addrres']
    if seg and used: return TEXT['seg']
    if rp: return TEXT['rep'] % rp
    if mem and mem[0].mem.segment: return TEXT['segmem']
    return None


def ea(ins, fields):
    """SDM 1:P89 Offset = Base + (Index * Scale) + Displacement; the displacement of a shape with a displacement field is the symbolic field (an 8-bit one sign-extended: SDM 2A:P622)"""
    mem = [x for x in ins.operands if x.type == X.X86_OP_MEM][0].mem
    t = z3.BitVecVal(0, 32)
    if mem.base: t = t + V(ins.reg_name(mem.base))
    if mem.index: t = t + V(ins.reg_name(mem.index)) * mem.scale
    d = fields['disp']
    if d:
        raw = z3.BitVec('fld_disp', 8 * d[1]); t = t + (z3.SignExt(32 - 8 * d[1], raw) if d[1] < 4 else raw)
    else: t = t + z3.BitVecVal(mem.disp & 0xffffffff, 32)
    return t


def mem_after(stores):
    m = dsl.mem_array()
    for a, v in stores:
        a, v = dsl.to_smt(a), dsl.to_smt(v)
        for i in range(v.size() // 8): m = z3.Store(m, a + i, z3.Extract(8 * i + 7, 8 * i, v))
    return m


def differs(a, b):
    s = z3.Solver(); s.add(a != b)
    return s.check() != z3.unsat


def compare(f, ins, regs, flags, mem):
    """the Form against the spec state: {reg: term}, {flag: 1-bit term} (a flag not named is unchanged, one the SDM calls undefined is not in `flags` and not compared: UNDEF),
    mem = the spec's memory after the instruction (None: unchanged) -> the list of differing parts"""
    d = []
    import fnvnx.lift.proof.sysspec_store as sysspec_store
    if sysspec_store.faults_ok(f, ins): return ['faults']
    if f.swhen or f.flo is not None: d.append(TEXT['cond'])
    pr = {r[0]: dsl.to_smt(r[1]) for r in f.regs}
    for n in sorted(set(pr) | set(regs)):
        if differs(pr.get(n, V(n)), regs.get(n, V(n))): d.append(n)
    pf = {r[0]: dsl.to_smt(r[1]) for r in f.flags}
    for n in sorted(set(flags)):
        if n not in pf or differs(pf[n], flags[n]): d.append(n)
    for n in sorted(set(pf) - set(flags) - UNDEF.get(family(ins), set())): d.append(n + '(written)')
    if differs(mem_after(f.stores), mem if mem is not None else dsl.mem_array()): d.append('memory')
    if differs(dsl.to_smt(f.eip), V('eip') + ins.size): d.append('eip')
    return d


UNDEF = {'bts': {'of', 'sf', 'af', 'pf'}}         # SDM 2A:BTS: 'The OF, SF, AF, and PF flags are undefined.': the Form may write them, with any value



def bswap(ins, f, rec):
    o = ins.operands[0]
    if o.type != X.X86_OP_REG or o.size != 4: return 'uncertified', TEXT['bswap16']
    r = ins.reg_name(o.reg); t = V(r)
    new = z3.Concat(z3.Extract(7, 0, t), z3.Extract(15, 8, t), z3.Extract(23, 16, t), z3.Extract(31, 24, t))        # DEST[31:24] := TEMP[7:0] ... DEST[7:0] := TEMP[31:24]
    d = compare(f, ins, {r: new}, {}, None)
    return ('proved', TEXT['okbswap']) if not d else ('FAILED(dsl)', 'differs: ' + ','.join(d))


def xlat(ins, f, rec):
    al = z3.Extract(7, 0, V('eax'))
    new = z3.Concat(z3.Extract(31, 8, V('eax')), z3.Select(dsl.mem_array(), V('ebx') + z3.ZeroExt(24, al)))        # AL := (DS:EBX + ZeroExtend(AL))
    d = compare(f, ins, {'eax': new}, {}, None)
    return ('proved', TEXT['okxlat']) if not d else ('FAILED(dsl)', 'differs: ' + ','.join(d))


def movsreg(ins, f, rec, fields):
    dst, src = ins.operands; sr = ins.reg_name(src.reg)
    try: x86sys.get(rec, 'selectors', sr)
    except x86sys.Undecided as e: return 'uncertified', TEXT['unc'] % e
    v = V('sel_' + sr, 16)      # SRC is the segment register: its selector is the pre-state sel_<reg> (dsl.XIN); the record rows (decided above) say which values it can hold
    if dst.type == X.X86_OP_REG:
        if dst.size != 4: return 'uncertified', TEXT['mov16']
        d = compare(f, ins, {ins.reg_name(dst.reg): z3.ZeroExt(16, v)}, {}, None)
    else:
        a = ea(ins, fields); m = dsl.mem_array()
        d = compare(f, ins, {}, {}, z3.Store(z3.Store(m, a, z3.Extract(7, 0, v)), a + 1, z3.Extract(15, 8, v)))        # DEST := SRC, a 16-bit quantity at the effective address
    return ('proved', TEXT['okmov'] % sr) if not d else ('FAILED(dsl)', 'differs: ' + ','.join(d))


def bts(ins, f, rec, fields):
    dst, src = ins.operands; w = 8 * dst.size
    if w not in (16, 32): return 'uncertified', TEXT['btsw'] % w
    if ins.prefix[2] and w == 32: return 'uncertified', TEXT['btsop']
    if src.type == X.X86_OP_REG: off = z3.ZeroExt(32 - w, z3.Extract(w - 1, 0, V(ins.reg_name(src.reg))))
    else: off = z3.ZeroExt(24, z3.BitVec('fld_imm', 8)) if fields['imm'] else z3.BitVecVal(src.imm & 0xff, 32)
    flags = {}; regs = {}; mem = None
    if dst.type == X.X86_OP_REG:
        r = ins.reg_name(dst.reg); t = z3.ZeroExt(32 - w, z3.Extract(w - 1, 0, V(r))); n = z3.URem(off, z3.BitVecVal(w, 32))        # the modulo of the bit offset
        flags['cf'] = z3.Extract(0, 0, z3.LShR(t, n))
        new = z3.Extract(w - 1, 0, t | (z3.BitVecVal(1, 32) << n))
        regs[r] = new if w == 32 else z3.Concat(z3.Extract(31, w, V(r)), new)
    else:
        if src.type == X.X86_OP_REG:
            so = z3.SignExt(32 - w, z3.Extract(w - 1, 0, V(ins.reg_name(src.reg)))) if w < 32 else V(ins.reg_name(src.reg))      # the offset of a register operand is signed
        else: so = z3.URem(off, z3.BitVecVal(w, 32))                                                                              # an immediate: the high-order bits are ignored
        a = ea(ins, fields) + (so >> 3); b = z3.Extract(2, 0, so)
        m = dsl.mem_array(); byte = z3.Select(m, a)
        flags['cf'] = z3.Extract(0, 0, z3.LShR(byte, z3.ZeroExt(5, b)))
        mem = z3.Store(m, a, byte | (z3.BitVecVal(1, 8) << z3.ZeroExt(5, b)))
    d = compare(f, ins, regs, flags, mem)
    return ('proved', TEXT['okbts']) if not d else ('FAILED(dsl)', 'differs: ' + ','.join(d))


def check(key, rec=None):
    ins = decode(key); fam = family(ins)
    if fam is None: return 'not-covered', 'no spec'
    why = unclaimed_prefix(ins, key)
    if why: return 'uncertified', TEXT['unc'] % why
    fields = symform.parse_key(key)[1]
    if fam == 'bswap' and ins.operands[0].size != 4: return 'uncertified', TEXT['bswap16']      # no Form is asked for: the SDM states no result
    try: f = symform.symbuild(key).form
    except KeyError: return 'not-covered', 'no Form'
    if fam == 'movsreg' and rec is None: rec = x86sys.load()
    if fam == 'bswap': return bswap(ins, f, rec)
    if fam == 'xlat': return xlat(ins, f, rec)
    if fam == 'movsreg': return movsreg(ins, f, rec, fields)
    return bts(ins, f, rec, fields)


def main(argv):
    argv = list(argv)
    if '--x86sys' not in argv: sys.stderr.write(TEXT['req']); return 2
    i = argv.index('--x86sys'); x86sys.configure(argv[i + 1]); del argv[i:i + 2]
    keys = [ln.split()[0] for ln in open(argv[0]) if ln.strip() and ln[0] != '#']
    bad = 0
    for k in keys:
        r, n = check(k); bad += r.startswith('FAILED')
        print('%s\t%s\t%s' % (k, r, n))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
