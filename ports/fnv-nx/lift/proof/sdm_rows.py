#!/usr/bin/env python3
"""Expected-value rows of the tests, extracted from the pinned Intel SDM by a rule over the SDM's own tables (never typed).

    python3 -I sdm_rows.py ea16 SDM.txt OUT.tsv      SDM.txt: `pdftotext -layout` of the combined-volumes SDM (sha256 in the header; the pages are those of that edition)

ea16: SDM Vol. 2A Table 2-1 "16-Bit Addressing Forms with the ModR/M Byte".  Universe: every row of the table whose Mod is 00, 01 or 10 (24 rows), each with the ModR/M byte of its first value column (REG = 000), i.e. the table's own cell.
  Row text `[BX+SI]+disp8` gives the terms (registers summed) and the displacement kind: none / disp8 / disp16 (a row `disp16` alone: no terms).  Note 3 of the table: disp8 is sign-extended and added to the index; Note 2: disp16 is added to the index.
  The displacement values stimulate each kind at its two ends of the sign: disp8 0x10 and 0xf0 (= -16), disp16 0x1234 and 0xfff0 (= -16); the expected displacement is the signed value of those bytes under Notes 2 and 3.
  The address is the sum of the 16-bit halves mod 2^16 (SDM Vol. 1 3.7.5 "Specifying an Offset"; the test states it).
Output: `ea16<TAB>encoding hex (67 8B modrm disp)<TAB>citation<TAB>terms<TAB>signed displacement`."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sdmfeat as S  # noqa: E402

ROW = re.compile(r'^\s*(\[[A-Z+]+\](?:\+disp(?:8|16)\d?)?|disp16\d?)\s+(?:(\d\d)\s+)?([01]{3})\s+((?:[0-9A-F]{2}\s+){7}[0-9A-F]{2})\s*$')
DISPS = {'none': [(b'', 0)], 'disp8': [(b'\x10', 16), (b'\xf0', -16)], 'disp16': [(b'\x34\x12', 0x1234), (b'\xf0\xff', -16)]}


def table_rows(lines):
    a = next(i for i, l in enumerate(lines) if l.strip().startswith('Table 2-1. 16-Bit Addressing Forms with the ModR/M Byte') and i > 20000)
    mod = None; out = []
    for l in lines[a:a + 60]:
        m = ROW.match(l)
        if not m:
            continue
        ea, md, rm, vals = m.groups()
        mod = md or mod
        out.append((re.sub(r'(disp(?:8|16))\d$', r'\1', ea), mod, rm, vals.split()[0]))
    return a, out


def ea16(lines):
    a, rows = table_rows(lines)
    page = S.page_after(lines, a)
    res = []
    for ea, mod, rm, v0 in rows:
        if mod == '11':
            continue
        terms = '+'.join(t.lower() for t in re.findall(r'[A-Z]{2}', ea.split('+disp')[0])) if ea.startswith('[') else ''
        kind = 'disp16' if ea.endswith('disp16') or ea == 'disp16' else 'disp8' if ea.endswith('disp8') else 'none'
        for b, val in DISPS[kind]:
            res.append(('ea16', '678b' + v0.lower() + b.hex(), 'SDM %s Table 2-1 mod %s r/m %s %s' % (page, mod, rm, ea), terms, str(val)))
    return res


def main(argv):
    kind, sdm, outp = argv
    rs = {'ea16': ea16}[kind](S.load(sdm))
    with open(outp, 'w') as fh:
        fh.write('# fnvnx-sdm-test-rows/1 kind=%s sdm_sha256=%s rows=%d\n# generated by proof/sdm_rows.py (rule in its docstring) from the pinned SDM; not hand-edited\n' % (kind, S.sha_file(sdm), len(rs)))
        for r in rs:
            fh.write('\t'.join(r) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
