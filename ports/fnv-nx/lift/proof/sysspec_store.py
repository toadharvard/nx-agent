SEGREG = {X.X86_REG_CS: 'cs', X.X86_REG_DS: 'ds', X.X86_REG_ES: 'es', X.X86_REG_FS: 'fs', X.X86_REG_GS: 'gs', X.X86_REG_SS: 'ss'}


def segment(ins, op):
    """the segment register of an explicit memory operand: the decoder's segment (an override prefix, or ES for a string destination), else the default"""
    if op.mem.segment in SEGREG: return SEGREG[op.mem.segment]
    return 'ss' if op.mem.base in (X.X86_REG_ESP, X.X86_REG_EBP) else 'ds'


def code_selectors(rec, seg):
    held = {rec['selectors'][seg]['value']} | set(rec['mov_to_sreg'].get(seg, {}).get('selectors', ())) | (set(rec['jmp_far']['jumps']['selectors']) if seg == 'cs' else set())
    d = rec['gdt']['descriptors']
    return sorted(s for s in held if d.get('0x%02x' % ((s >> 3) * 8), {}).get('type', 0) & 8 and d['0x%02x' % ((s >> 3) * 8)]['s'] == 1)


def held(rec, seg):
    """the non-null selectors segment register `seg` can hold on the declared machine (the record's initial selector and mov_to_sreg; for CS the far-jump targets): the domain of the store spec"""
    h = {rec['selectors'][seg]['value']} | set(rec['mov_to_sreg'].get(seg, {}).get('selectors', ())) | (set(rec['jmp_far']['jumps']['selectors']) if seg == 'cs' else set())
    return sorted(v for v in h if v >> 3)


def write_segments(ins):
    return sorted({segment(ins, o) for o in ins.operands if o.type == X.X86_OP_MEM and o.access & 2})      # capstone CS_AC_WRITE = 2


def expected(ins, rec=None, rep=False):
    """the z3 condition (1-bit) of the #GP of the instruction's explicit memory stores (the OR over the segments they go through), or None when no store goes through a segment register that can hold a code selector"""
    rec = rec or x86sys.load(); c = None
    for seg in write_segments(ins):
        cs = code_selectors(rec, seg)
        if not cs: continue
        sel = z3.BitVec('sel_' + seg, 16)
        t = z3.Or(*[z3.Extract(15, 3, sel) == (v >> 3) for v in cs])
        c = t if c is None else z3.Or(c, t)
    if c is not None and rep: c = z3.And(c, z3.BitVec('ecx', 32) != 0)
    return c


def domain(rec, ins):
    """every segment register the instruction writes through holds a non-null selector of `held`: both halves of the domain, the data selectors (decided by the Sail model, prove.py) and the code selectors (decided by this spec)"""
    return z3.And(*[z3.Or(*[z3.BitVec('sel_' + s, 16) == v for v in held(rec, s)]) for s in write_segments(ins)] or [z3.BoolVal(True)])


def _consts(t):
    out, st, seen = set(), [t], set()
    while st:
        e = st.pop()
        if e.get_id() in seen: continue
        seen.add(e.get_id())
        if z3.is_const(e) and e.decl().kind() == z3.Z3_OP_UNINTERPRETED: out.add(e.decl().name())
        st.extend(e.children())
    return out


def code_cond(rec, seg):
    cs = code_selectors(rec, seg)
    return z3.Or(*[z3.Extract(15, 3, z3.BitVec('sel_' + seg, 16)) == (v >> 3) for v in cs]) if cs else z3.BoolVal(False)


def prove_codestore(f, ins, rec=None, rep=False):
    """a Form that carries a code-segment store fault: (a) its AV faults are, over the domain of the segments it names (the `codestore:<seg>` of Form.access: both halves, data selectors give none, code selectors give one), exactly the OR of the SDM
    conditions of those segments (under REP also ECX != 0); (b) every explicit memory operand that the decoder says is written goes through one of those segments, with the override prefix honoured.  Which operands are stored is not decided here: the
    decoder's access flags miss some stores (SSE moves, SETcc, shifts by an immediate), so (b) is one direction; the stores themselves are proved against the Sail model by prove.py.  -> 'proved' or the reason"""
    rec = rec or x86sys.load(); segs = sorted(a[len('codestore:'):] for a in getattr(f, 'access', ()) if a.startswith('codestore:'))
    if not segs: return 'no code-segment store fault'
    e = z3.Or(*[code_cond(rec, s) for s in segs])
    if rep: e = z3.And(e, z3.BitVec('ecx', 32) != 0)
    if f.swhen and len(f.stores) == len(f.swhen):      # every store is conditional (ARPL writes the destination only when its RPL is lower): the fault is as conditional as the stores, whichever of them happens
        e = z3.And(e, z3.Or(*[dsl.to_smt(w) == 1 for w in f.swhen.values()]))
    got = [dsl.to_smt(c) == 1 for k, c in f.faults if k == FT['AV']['code'] and 'sel_' in str(dsl.to_smt(c))]
    g = z3.Or(*got) if got else z3.BoolVal(False)
    names = {n[4:] for t in got + [g] for n in _consts(t) if n.startswith('sel_')}      # a segment named by another fault of the Form (the null-selector fault of a gs read) is in the domain too: non-null selectors
    dom = z3.And(*[z3.Or(*[z3.BitVec('sel_' + s, 16) == v for v in held(rec, s)]) for s in sorted(set(segs) | names)])
    sv = z3.Solver(); sv.add(dom, z3.Not(g == e))
    if sv.check() != z3.unsat: return 'differs'
    miss = [s for s in write_segments(ins) if code_selectors(rec, s) and s not in segs]
    return 'proved' if not miss else 'missing ' + ','.join(miss)


def faults_ok(f, ins, rec=None, rep=False):
    """None when the Form's faults are exactly the SDM's (none, or one AV equal to the condition); else the code 'faults'"""
    e = expected(ins, rec, rep)
    if e is None: return None if not f.faults else 'faults'
    if len(f.faults) != 1 or f.faults[0][0] != FT['AV']['code']: return 'faults'
    s = z3.Solver(); s.add(z3.Not((dsl.to_smt(f.faults[0][1]) == 1) == e))
    return None if s.check() == z3.unsat else 'faults'
