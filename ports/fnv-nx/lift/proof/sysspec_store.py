"""The SDM fault of a memory store (OWNER 10): a store through a segment register whose selector names a code descriptor is #GP(0), which the declared machine reports as the access violation (fault kind AV).
Every quote is checked by sdm_cite_check.py against sysspec_store_pages.tsv (generated by sdm_pages.py).
SDM 3A:3.4.5.1 'In protected mode, code segments are not writable.'
The #GP(0) condition list of SDM 3A:7.15 (Event 13) names writing to a code segment; it is the consequence this spec takes (no quote: the list is pages after its heading).
The segment of an explicit memory operand without override is DS, or SS when the base register is ESP or EBP (the default segment selection of SDM 1:3.7.4; an override prefix is outside the specs that call this).
The selectors a segment register can hold are the record's (selectors.<reg>.value and mov_to_sreg.<reg>.selectors); a selector is a code selector when the record's GDT descriptor at its index is S=1 with the code type bit (type & 8).
Written from the raw record rows, not from fnvlift.x86sys.code_indices that the Form builder uses."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import z3  # noqa: E402
from capstone import x86 as X  # noqa: E402
from fnvlift import dsl  # noqa: E402
from fnvlift.faults import BYNAME as FT  # noqa: E402
from proof import x86sys  # noqa: E402


def segment(ins, op):
    if op.mem.segment == X.X86_REG_ES: return 'es'      # a string destination ES:(E)DI
    return 'ss' if op.mem.base in (X.X86_REG_ESP, X.X86_REG_EBP) else 'ds'


def code_selectors(rec, seg):
    held = {rec['selectors'][seg]['value']} | set(rec['mov_to_sreg'][seg]['selectors'])
    d = rec['gdt']['descriptors']
    return sorted(s for s in held if d.get('0x%02x' % ((s >> 3) * 8), {}).get('type', 0) & 8 and d['0x%02x' % ((s >> 3) * 8)]['s'] == 1)


def expected(ins, rec=None, rep=False):
    """the z3 condition (1-bit) of the #GP of the instruction's explicit memory store, or None when it stores nothing through a segment"""
    import capstone
    rec = rec or x86sys.load()
    mem = [o for o in ins.operands if o.type == X.X86_OP_MEM and o.access & capstone.CS_AC_WRITE]
    if not mem: return None
    seg = segment(ins, mem[0]); sel = z3.BitVec('sel_' + seg, 16)
    cs = code_selectors(rec, seg)
    if not cs: return None
    c = z3.BoolVal(False)
    for s in cs: c = z3.Or(c, z3.Extract(15, 3, sel) == (s >> 3))
    return z3.And(c, z3.BitVec('ecx', 32) != 0) if rep else c


def faults_ok(f, ins, rec=None, rep=False):
    """None when the Form's faults are exactly the SDM's (none, or one AV equal to the condition); else the code 'faults'"""
    e = expected(ins, rec, rep)
    if e is None: return None if not f.faults else 'faults'
    if len(f.faults) != 1 or f.faults[0][0] != FT['AV']['code']: return 'faults'
    s = z3.Solver(); s.add(z3.Not((dsl.to_smt(f.faults[0][1]) == 1) == e))
    return None if s.check() == z3.unsat else 'faults'
