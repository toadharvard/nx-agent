#!/usr/bin/env python3
"""gen_header.py TARGETS_JSON OUT.h: the C header of the declared console CPU's constants, generated from verify/targets.json (owner order 2026-11-15, rules 1, 2 and 5).
It holds `FNVNX_FPCR`, the one integer `targets.fpcr_value` derives from the row `console_cpu.fpcr` (Arm DDI0488H 14.4.1). Every `msr fpcr` site of guest code reads this macro and never spells
a literal. The row is judged by `targets.fpcr_errors` before it is written; a row that fails is an error, not a header."""
import os
import sys

from verify import targets   # qualified: the derived edge contract/target -> verify; the stage mounts that closure at /imp (PYTHONPATH)


def render(t):
    bad = targets.fpcr_errors(t)
    if bad:
        raise ValueError("; ".join(bad))
    return ("/* generated by contract/target/gen_header.py from verify/targets.json console_cpu.fpcr; do not edit */\n"
            "#ifndef FNVNX_TARGET_H\n#define FNVNX_TARGET_H\n"
            "#define FNVNX_FPCR 0x%xull\n"
            "#endif\n") % targets.fpcr_value(t)


def main(argv):
    if len(argv) != 2:
        print("usage: gen_header.py TARGETS_JSON OUT.h", file=sys.stderr)
        return 2
    text = render(targets.load(argv[0]))
    os.makedirs(os.path.dirname(os.path.abspath(argv[1])), exist_ok=True)
    with open(argv[1], "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
