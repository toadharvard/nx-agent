"""gen_wire_errno.py - the wire errno list of hostabi/include/fnvnx/sockwire_errno.h, generated; pure Python over three pinned externals.

    gen_wire_errno.py --libnx-convert convert_errno.c --newlib-errno sys/errno.h --linux-errno-base errno-base.h --linux-errno errno.h
                      [--committed sockwire_errno.h] [--out FILE] [--unit dom_errno.c]

Rule (class-closing, no hand-written name or number):
  Linux table      the numeric #defines of the pinned linux-libc-dev uapi asm-generic/errno-base.h and errno.h: one primary name per
                   number n (an alias, #define A B, is not a second name). The bsd service's numbers are these (libnx: "Nintendo
                   actually used the Linux errno definitions").
  libnx encoding   libnx's convert_errno.c `_error_code_map`: index n -> the guest libc's name, or 0: that n comes out as 10000 + n.
  guest libc       D = the errno names of the runtime external's newlib sys/errno.h.
  list             for every Linux number n: the guest name is the libnx entry when it is not 0, else the Linux name when D has it;
                   FNVNX_WIRE_ERRNO_LIST(X) holds X(guest name, n) (the host maps its errno by name, the guest maps n to a name).
  no guest name    a Linux number whose name D lacks: FNVNX_WIRE_ERRNO_UNNAMED(X) holds X(Linux name, n); the guest's errno is
                   FNVNX_ERRNO_UNKNOWN_OFFSET + n, the same encoding libnx itself gives.
  decode           a host errno e < 10000 is a name of the list; e >= 10000 is the unknown encoding of n = e - 10000, which must be a
                   number of the list or UNNAMED. Anything else cannot come from the service while ASM-004 holds
                   (fnvnx_assume_violation).
Two modes of the same generator, both from the same pinned externals (they cannot diverge): the hostabi root regenerates and checks the
committed header (--committed with --out STAMP); the platform root emits the C unit from the externals only (--unit). With --committed,
the generated text must equal the committed header (else exit 1). With --unit the C unit of the domain checks is
written (fnvnx_dom_errno[], fnvnx_dom_errno_check, fnvnx_wire_from_host_errno): hand code calls the checks only (L1: a direct call of
fnvnx_assume_violation is red)."""
import re, sys


def table(text):
    zero = set(re.findall(r"^#define\s+(E[A-Z0-9]+)\s+0\s*$", text, re.M))
    body = text[text.index("_error_code_map[]"):]
    body = body[body.index("{") + 1:body.index("};")]
    names = []
    for tok in re.split(r",", re.sub(r"//[^\n]*", "", body)):
        tok = tok.strip()
        if tok:
            names.append(tok)
    return [None if t == "0" or t in zero else t for t in names]


def linux(*texts):
    """{number: primary name} of the numeric #defines of the headers (an alias to another name is not a second name)."""
    nums = {}
    for t in texts:
        for name, num in re.findall(r"^#define\s+(E[A-Z0-9]+)\s+(\d+)\b", t, re.M):
            nums[int(num)] = name
    return nums


def compute(convert_text, newlib_text, base_text, errno_text):
    """(Linux count, newlib name count, named [(name, n, via_libnx)], unnamed [(name, n)])."""
    dom = set(re.findall(r"^#\s*define\s+(E[A-Z0-9]+)\b", newlib_text, re.M))
    tab = table(convert_text)
    lx = linux(base_text, errno_text)
    named, unnamed = [], []
    for n in sorted(lx):
        entry = tab[n] if n < len(tab) else None
        if entry is not None and entry in dom:
            named.append((entry, n, True))
        elif lx[n] in dom:
            named.append((lx[n], n, False))
        else:
            unnamed.append((lx[n], n))
    seen = {}
    for name, n, _ in named:
        if name in seen:
            raise SystemExit("gen_wire_errno: guest name %s for the numbers %d and %d" % (name, seen[name], n))
        seen[name] = n
    return len(lx), len(dom), named, unnamed


def fmt(rows):
    lines, cur = [], "   "
    for name, n in rows:
        r = "X(%s, %d)" % (name, n)
        if len(cur) + len(r) + 1 > 118:
            lines.append(cur + " \\")
            cur = "   "
        cur += " " + r
    lines.append(cur)
    return "\n".join(lines)


def generate(convert_text, newlib_text, base_text, errno_text):
    nlx, ndom, named, unnamed = compute(convert_text, newlib_text, base_text, errno_text)
    decoded = sum(1 for x in named if not x[2]) + len(unnamed)
    return ("/* GENERATED by manifest/gen_wire_errno.py from the pinned uapi errno headers (%d Linux numbers), libnx's convert_errno.c and the\n"
            " * guest libc's sys/errno.h (%d names); do not edit. LIST: %d guest names; %d numbers reach the host as 10000 + n (the libnx\n"
            " * entry is 0), %d of them have no guest name (UNNAMED). The checks of the domains are the generated unit os/gen/dom_errno.c:\n"
            " * fnvnx_dom_errno_check (a wire number) and fnvnx_wire_from_host_errno (a host errno). */\n"
            "#define FNVNX_ERRNO_UNKNOWN_OFFSET 10000\n"
            "#define FNVNX_WIRE_ERRNO_LIST(X) \\\n%s\n"
            "#define FNVNX_WIRE_ERRNO_UNNAMED(X) \\\n%s\n"
            "int fnvnx_dom_errno_check(int v);          /* v when it is a wire number of LIST or UNNAMED, else the OWNER-assumption exit */\n"
            "int fnvnx_wire_from_host_errno(int e);     /* the wire number of a host errno (by name, or the libnx encoding 10000 + n), else the exit */\n"
            ) % (nlx, ndom, len(named), decoded, len(unnamed), fmt([(a, b) for a, b, _ in named]), fmt(unnamed))


def unit(convert_text, newlib_text, base_text, errno_text):
    """The C unit os/gen/dom_errno.c: the domain arrays and their checks. The OWNER id is the literal 4 (ASM-004)."""
    nlx, ndom, named, unnamed = compute(convert_text, newlib_text, base_text, errno_text)
    wire = sorted([n for _, n, _ in named] + [n for _, n in unnamed])
    cases = "\n".join("    case %d:" % n for n in wire)
    names = [(a, b) for a, b, via in named if via]
    host = "\n".join("    case %s:" % a for a, _ in names)
    byname = "\n".join("    if (e == %s) return %d;" % (a, b) for a, b in names)
    return ("/* GENERATED by manifest/gen_wire_errno.py; do not edit. The domains of the bsd service's errno (ASM-004: the console behaves as\n"
            " * documented). A value outside the domain ends the process through fnvnx_assume_violation with the OWNER id 4. */\n"
            "#include <errno.h>\n#include <stdint.h>\n#include \"fnvnx/reach.h\"\n#include \"fnvnx/sockwire.h\"\n\n"
            "const int fnvnx_dom_errno[%d] = {%s};\n\n"
            "int fnvnx_dom_errno_check(int v)\n{\n    switch (v) {\n%s\n        return v;\n    default:\n"
            "        fnvnx_assume_violation(4u, (uint64_t)(uint32_t)v);\n    }\n}\n\n"
            "int fnvnx_wire_from_host_errno(int e)\n{\n%s\n"
            "    if (e >= FNVNX_ERRNO_UNKNOWN_OFFSET)\n        return fnvnx_dom_errno_check(e - FNVNX_ERRNO_UNKNOWN_OFFSET);\n"
            "    fnvnx_assume_violation(4u, (uint64_t)(uint32_t)e);\n}\n") % (len(wire), ", ".join(str(n) for n in wire), cases, byname)


def main(argv):
    a = dict(zip(argv[::2], argv[1::2]))
    text = generate(open(a["--libnx-convert"]).read(), open(a["--newlib-errno"]).read(),
                    open(a["--linux-errno-base"]).read(), open(a["--linux-errno"]).read())
    if "--unit" in a:
        open(a["--unit"], "w").write(unit(open(a["--libnx-convert"]).read(), open(a["--newlib-errno"]).read(),
                                          open(a["--linux-errno-base"]).read(), open(a["--linux-errno"]).read()))
    if "--committed" in a:
        if open(a["--committed"]).read() != text:
            sys.exit("gen_wire_errno: %s differs from the list regenerated from the pinned externals" % a["--committed"])
    if "--out" in a:
        open(a["--out"], "w").write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
