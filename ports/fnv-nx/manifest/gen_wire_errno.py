"""gen_wire_errno.py - the wire errno list of hostabi/include/fnvnx/sockwire_errno.h, generated; pure Python over three pinned externals.

    gen_wire_errno.py --libnx-convert convert_errno.c --newlib-errno sys/errno.h --linux-errno-base errno-base.h --linux-errno errno.h
                      [--committed sockwire_errno.h] [--out FILE]

Rule (class-closing, no hand-written name or number):
  Linux table      the numeric #defines of the pinned linux-libc-dev uapi asm-generic/errno-base.h and errno.h: one primary name per
                   number n (an alias, #define A B, is not a second name). The bsd service's numbers are these (libnx: "Nintendo
                   actually used the Linux errno definitions").
  libnx encoding   libnx's convert_errno.c `_error_code_map`: index n -> the guest libc's name, or 0: that n comes out as 10000 + n.
  guest libc       D = the errno names of the runtime external's newlib sys/errno.h.
  list             for every Linux number n: the guest name is the libnx entry when it is not 0, else the Linux name when D has it;
                   FNVNX_WIRE_ERRNO_LIST(X) holds X(guest name, n) (the host maps its errno by name, the guest maps n to a name).
  no guest name    a Linux number whose name D lacks: FNVNX_WIRE_ERRNO_UNNAMED(X) holds X(Linux name, n); the guest's errno is
                   FNVNX_ERRNO_UNKNOWN_OFFSET + n, the same encoding libnx itself gives.
  decode           a host errno e < 10000 is a name of the list; e >= 10000 is the unknown encoding of n = e - 10000, which must be a
                   number of the list or UNNAMED. Anything else cannot come from the service while ASM-004 holds
                   (fnvnx_assume_violation).
With --committed, the generated text must equal the committed header (else exit 1)."""
import re, sys


def table(text):
    zero = set(re.findall(r"^#define\s+(E[A-Z0-9]+)\s+0\s*$", text, re.M))
    body = text[text.index("_error_code_map[]"):]
    body = body[body.index("{") + 1:body.index("};")]
    names = []
    for tok in re.split(r",", re.sub(r"//[^\n]*", "", body)):
        tok = tok.strip()
        if tok:
            names.append(tok)
    return [None if t == "0" or t in zero else t for t in names]


DECODE = """#include <errno.h>
#include "fnvnx/reach.h"
/* The host's errno (libnx / its libc) -> the wire number: by name over LIST, or the unknown encoding 10000 + n of a Linux number of LIST or
 * UNNAMED; any other value cannot come from the service while ASM-004 holds. */
static inline int fnvnx_wire_from_host_errno(int e) {
#define X(N, v) if (e == (N)) return (v);
    FNVNX_WIRE_ERRNO_LIST(X)
#undef X
    if (e >= FNVNX_ERRNO_UNKNOWN_OFFSET) {
#define X(N, v) if (e - FNVNX_ERRNO_UNKNOWN_OFFSET == (v)) return (v);
        FNVNX_WIRE_ERRNO_LIST(X)
        FNVNX_WIRE_ERRNO_UNNAMED(X)
#undef X
    }
    fnvnx_assume_violation(FNVNX_ASM_004, (uint64_t)(uint32_t)e);
}
"""


def linux(*texts):
    """{number: primary name} of the numeric #defines of the headers (an alias to another name is not a second name)."""
    nums = {}
    for t in texts:
        for name, num in re.findall(r"^#define\s+(E[A-Z0-9]+)\s+(\d+)\b", t, re.M):
            nums[int(num)] = name
    return nums


def generate(convert_text, newlib_text, base_text, errno_text):
    dom = set(re.findall(r"^#\s*define\s+(E[A-Z0-9]+)\b", newlib_text, re.M))
    tab = table(convert_text)
    lx = linux(base_text, errno_text)
    named, unnamed, decoded = [], [], 0
    for n in sorted(lx):
        entry = tab[n] if n < len(tab) else None
        if entry is not None and entry in dom:
            named.append((entry, n))
        elif lx[n] in dom:
            named.append((lx[n], n))
            decoded += 1
        else:
            unnamed.append((lx[n], n))
            decoded += 1
    seen = {}
    for name, n in named:
        if name in seen:
            raise SystemExit("gen_wire_errno: guest name %s for the numbers %d and %d" % (name, seen[name], n))
        seen[name] = n

    def fmt(rows):
        lines, cur = [], "   "
        for name, n in rows:
            r = "X(%s, %d)" % (name, n)
            if len(cur) + len(r) + 1 > 118:
                lines.append(cur + " \\")
                cur = "   "
            cur += " " + r
        lines.append(cur)
        return "\n".join(lines)
    return ("/* GENERATED by manifest/gen_wire_errno.py from the pinned uapi errno headers (%d Linux numbers), libnx's convert_errno.c and the\n"
            " * guest libc's sys/errno.h (%d names); do not edit. LIST: %d guest names; %d numbers reach the host as 10000 + n (the libnx\n"
            " * entry is 0), %d of them have no guest name (UNNAMED). */\n"
            "#define FNVNX_ERRNO_UNKNOWN_OFFSET 10000\n"
            "#define FNVNX_WIRE_ERRNO_LIST(X) \\\n%s\n"
            "#define FNVNX_WIRE_ERRNO_UNNAMED(X) \\\n%s\n"
            "%s") % (len(lx), len(dom), len(named), decoded, len(unnamed), fmt(named), fmt(unnamed), DECODE)


def main(argv):
    a = dict(zip(argv[::2], argv[1::2]))
    text = generate(open(a["--libnx-convert"]).read(), open(a["--newlib-errno"]).read(),
                    open(a["--linux-errno-base"]).read(), open(a["--linux-errno"]).read())
    if "--committed" in a:
        if open(a["--committed"]).read() != text:
            sys.exit("gen_wire_errno: %s differs from the list regenerated from the pinned externals" % a["--committed"])
    if "--out" in a:
        open(a["--out"], "w").write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
