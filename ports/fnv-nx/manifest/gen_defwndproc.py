#!/usr/bin/env python3
"""gen_defwndproc - the message table of DefWindowProc, from Wine 9.0's default window procedure.

    gen_defwndproc.py <wine-9.0 tree> <window.cpp> <out.inc>

The rule: our DefWindowProc answers exactly the messages that `default_window_proc` of dlls/win32u/defwnd.c (Wine 9.0) has a `case WM_*:`
label for, and no other message (every other message answers 0, as Wine's `default` does). The label set, the message ids and the citations
are read from the pinned tree; nothing about them is typed in this repository:
  - the labels: every `case WM_X:` inside the body of default_window_proc (comments removed, braces matched);
  - the id of WM_X: its `#define WM_X <value>` (a number, or another WM_ name) in include/winuser.rh or dlls/win32u/ntuser_private.h of the tree;
  - the handler of WM_X: the function `static LRESULT defwnd_WM_X(window *, HWND, WPARAM, LPARAM)` defined in <window.cpp>, bound by name.
Errors (exit 1, the stage is red): a label with no id; a label with no handler (a missing implementation); a handler `defwnd_WM_*` that is
not a label (a message Wine's procedure does not handle); a name defined twice; a duplicate id.
Output <out.inc>: forward declarations of the handlers and the table `k_defrules[]` {id, handler, citation}, sorted by id; the citation is
`wine-9.0:dlls/win32u/defwnd.c:default_window_proc case WM_X (line N)`, the line of the label in the tree. Python 3 standard library only."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_wine_cites import strip_comments  # noqa: E402

FILE = "dlls/win32u/defwnd.c"
FUNC = "default_window_proc"
IDS = ("include/winuser.rh", "dlls/win32u/ntuser_private.h")   # the public ids, and the private ones of the win32u implementation
HANDLER = re.compile(r"^static LRESULT (defwnd_(WM_[A-Z0-9_]+))\(window \*[a-z]*, HWND[a-z ]*, WPARAM[a-z ]*, LPARAM[a-z ]*\)", re.M)


def labels(tree):
    """-> [(WM_X, line)] of the labels in the body of default_window_proc, in source order"""
    text = strip_comments(open(os.path.join(tree, FILE), encoding="utf-8", errors="replace").read())
    m = re.search(r"^LRESULT[ \t]+" + FUNC + r"[ \t]*\(", text, re.M)
    if not m:
        raise ValueError("%s: no definition of %s" % (FILE, FUNC))
    i, depth = m.end(), 1
    while depth:
        depth += {"(": 1, ")": -1}.get(text[i], 0)
        i += 1
    start = text.index("{", i)
    j, depth = start + 1, 1
    while depth:
        depth += {"{": 1, "}": -1}.get(text[j], 0)
        j += 1
    out = []
    for lm in re.finditer(r"\bcase (WM_[A-Z0-9_]+)\s*:", text[start:j]):
        out.append((lm.group(1), text.count("\n", 0, start + lm.start()) + 1))
    return out


def main():
    tree, cpp, out = sys.argv[1:4]
    errors = []
    defs = {}
    for f in IDS:
        for m in re.finditer(r"^#[ \t]*define[ \t]+(WM_[A-Z0-9_]+)[ \t]+(0x[0-9A-Fa-f]+|[0-9]+|WM_[A-Z0-9_]+)\b", open(os.path.join(tree, f), encoding="utf-8", errors="replace").read(), re.M):
            defs.setdefault(m.group(1), m.group(2))
    ids = {}
    for n in defs:
        v, hops = defs[n], 0
        while v in defs and hops < 8:   # an alias (WM_KEYDOWN is WM_KEYFIRST)
            v, hops = defs[v], hops + 1
        if re.fullmatch(r"0x[0-9A-Fa-f]+|[0-9]+", v):
            ids[n] = int(v, 0)
    labs = labels(tree)
    handlers = {}
    for m in HANDLER.finditer(open(cpp, encoding="utf-8").read()):
        if m.group(2) in handlers:
            errors.append("handler %s is defined twice" % m.group(1))
        handlers[m.group(2)] = m.group(1)
    names = [n for n, _ in labs]
    for n, line in labs:
        if n not in ids:
            errors.append("%s (%s:%d): no #define in %s" % (n, FILE, line, " or ".join(IDS)))
        if n not in handlers:
            errors.append("%s (%s:%d): no handler defwnd_%s in %s (a message the reference answers, with no implementation)" % (n, FILE, line, n, os.path.basename(cpp)))
    for n in sorted(set(handlers) - set(names)):
        errors.append("defwnd_%s: %s of %s has no `case %s:`" % (n, FUNC, FILE, n))
    seen = {}
    for n, line in labs:
        if n in ids:
            if ids[n] in seen and seen[ids[n]] != n:
                errors.append("%s and %s have the id %#x" % (seen[ids[n]], n, ids[n]))
            seen[ids[n]] = n
    if errors:
        sys.stderr.write("\n".join(errors) + "\n%d errors\n" % len(errors))
        return 1
    rows = sorted((ids[n], n, line) for n, line in labs)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as fh:
        fh.write("/* generated by manifest/gen_defwndproc.py from wine-9.0 %s:%s (%d case labels); do not edit */\n" % (FILE, FUNC, len(rows)))
        for _, n, _ in rows:
            fh.write("static LRESULT %s(window *, HWND, WPARAM, LPARAM);\n" % handlers[n])
        fh.write("struct defrule { UINT msg; LRESULT (*fn)(window *, HWND, WPARAM, LPARAM); const char *src; };\n")
        fh.write("static const defrule k_defrules[] = {\n")
        for i, n, line in rows:
            fh.write('    { 0x%04X, %s, "wine-9.0:%s:%s case %s (line %d)" },\n' % (i, handlers[n], FILE, FUNC, n, line))
        fh.write("};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
