#!/usr/bin/env python3
"""gen_wine_colors - the system colours and the default colour tables, from the pinned Wine 9.0 tree.

    gen_wine_colors.py <wine-9.0 tree> <out.inc>

Emits, each row with the Wine source line it is read from:
  k_syscolor[31]   COLORREF (0x00BBGGRR) of every `RGB_ENTRY( COLOR_X, RGB(r, g, b), "name" )` of `system_colors[]` in dlls/win32u/sysparams.c;
                   the row's position must equal the COLOR_X id of include/winuser.h (alias-resolved), and the ids must be exactly 0..N-1.
  k_pal1[2], k_pal4[16], k_pal8[256]   the RGBQUAD tables table_1/table_4/table_8 of get_default_color_table in dlls/win32u/dib.c, as
                   0x00RRGGBB (RGBQUAD is blue, green, red, reserved); the sizes must match the declared bounds.
Any other shape (a row that does not parse, a size mismatch, a gap in the ids) exits 1. Python 3 standard library only."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_wine_cites import strip_comments  # noqa: E402

SYSP = "dlls/win32u/sysparams.c"
DIB = "dlls/win32u/dib.c"
IDS = "include/winuser.h"


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def main():
    tree, out = sys.argv[1:3]
    err = []
    raw = open(os.path.join(tree, SYSP), encoding="utf-8", errors="replace").read()
    text = strip_comments(raw)
    defs = {}
    for m in re.finditer(r"^#[ \t]*define[ \t]+(COLOR_[A-Z0-9_]+)[ \t]+(\d+|COLOR_[A-Z0-9_]+)\b",
                         open(os.path.join(tree, IDS), encoding="utf-8", errors="replace").read(), re.M):
        defs.setdefault(m.group(1), m.group(2))

    def ident(n):
        v = defs.get(n)
        while v in defs:
            v = defs[v]
        return int(v) if v and v.isdigit() else None

    s = re.search(r"static struct sysparam_rgb_entry system_colors\[\]\s*=\s*\{", text)
    if not s:
        sys.exit("%s: no system_colors[]" % SYSP)
    e = text.index("};", s.end())
    cols = []
    for m in re.finditer(r"RGB_ENTRY\(\s*(COLOR_[A-Z0-9_]+)\s*,\s*RGB\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)\s*,\s*\)", text[s.end():e]):
        cols.append((m.group(1), [int(m.group(i)) for i in (2, 3, 4)], line_of(text, s.end() + m.start())))
    nrows = len(re.findall(r"RGB_ENTRY\(\s*COLOR_", text[s.end():e]))
    if len(cols) != nrows or not cols:
        err.append("system_colors: %d rows, %d parsed" % (nrows, len(cols)))
    for i, (n, rgb, line) in enumerate(cols):
        if ident(n) != i:
            err.append("system_colors row %d is %s (id %s)" % (i, n, ident(n)))
        if any(c > 255 for c in rgb):
            err.append("%s: component out of range" % n)

    dib = strip_comments(open(os.path.join(tree, DIB), encoding="utf-8", errors="replace").read())
    g = dib.index("get_default_color_table")
    tabs = {}
    for bpp in (1, 4, 8):
        m = re.compile(r"static const RGBQUAD table_%d\[(\d+)\]\s*=\s*\{" % bpp).search(dib, g)
        if not m:
            err.append("%s: no table_%d" % (DIB, bpp)); continue
        stop = dib.index("};", m.end())
        rows = [(int(a, 16), int(b, 16), int(c, 16)) for a, b, c in
                re.findall(r"\{\s*0x([0-9a-fA-F]{2})\s*,\s*0x([0-9a-fA-F]{2})\s*,\s*0x([0-9a-fA-F]{2})\s*\}", dib[m.end():stop])]
        if len(rows) != int(m.group(1)) or len(rows) != 1 << bpp:
            err.append("table_%d: %d rows, declared %s" % (bpp, len(rows), m.group(1)))
        tabs[bpp] = (rows, line_of(dib, m.start()))
    if err:
        sys.stderr.write("\n".join(err) + "\n%d errors\n" % len(err))
        return 1
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as fh:
        fh.write("/* generated by manifest/gen_wine_colors.py from wine-9.0 %s system_colors and %s get_default_color_table; do not edit */\n" % (SYSP, DIB))
        fh.write("/* COLORREF 0x00BBGGRR, row i = COLOR_<i>; wine-9.0:%s:system_colors (line of each row in the comment) */\n" % SYSP)
        fh.write("static const uint32_t k_syscolor[%d] = {\n" % len(cols))
        for n, (r, gg, b), line in cols:
            fh.write("    0x%06X,   /* %s: line %d */\n" % (r | gg << 8 | b << 16, n, line))
        fh.write("};\n")
        for bpp in (1, 4, 8):
            rows, line = tabs[bpp]
            fh.write("/* 0x00RRGGBB; wine-9.0:%s:get_default_color_table table_%d (line %d) */\n" % (DIB, bpp, line))
            fh.write("static const uint32_t k_pal%d[%d] = {" % (bpp, len(rows)))
            for i, (b, gg, r) in enumerate(rows):
                fh.write("%s0x%06X," % ("\n    " if i % 8 == 0 else " ", r << 16 | gg << 8 | b))
            fh.write("\n};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
