#!/usr/bin/env python3 -I
"""Generator of the declared machine's font registry values (L5), emitted as platform/win32/font_machine.gen.inc.

  gen_fontmachine.py <wine.inf.in> <font.c> <30-metric-aliases.conf> <fonts-dir> <out.inc>

Inputs are the pinned files of fnv-nx-build tools/fonts-wine9 (inputs/ and fonts/); nothing is typed by hand:
  FontSubstitutes  every `HKLM,%FontSubStr%,"from",,"to"` line of wine.inf.in ([Fonts] section, file order), preceded by the `shelldlg` and `tmsrmn`
                   values of the nls_update_font_list row of the declared machine (ANSI 1252, OEM 437; font.c update_font_list writes them as
                   "MS Shell Dlg" and "Tms Rmn")
  ACP              the row's ansi code page
  Hardware Fonts   OEMFONT.FON, FIXEDFON.FON, FONTS.FON = the row's oem, fixed, system (update_font_list)
  Fonts            Courier, MS Serif, MS Sans Serif, Small Fonts = the row's courier, serif, sserif_96 (96 dpi: add_font_list takes sserif_96 for dpi <= 108),
                   small
  Replacements     for every <alias binding="same"> of the alias conf with an <accept> list: (alias family, first accepted family that has a file in
                   <fonts-dir> by fontfamilies.py), in conf order, one row per alias family
Refusals (exit 1): the row is absent or has fewer than the ten string fields; no substitute line is found; the fonts directory holds no font file.
Assumptions: Wine 9.0 and fontconfig as documented (ASM-003); the compiler is correct (ASM-001).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fontfamilies

inf, fontc, conf, fdir, out = sys.argv[1:6]
src = open(fontc).read()
m = re.search(r"/\* Latin 1 \(United States\) \*/\s*\{\s*(\d+),\s*(\d+),((?:\s*\"[^\"]*\"\s*,?)+?)\s*\}", src)
if not m:
    sys.exit("gen_fontmachine: the 1252/437 row of nls_update_font_list is absent")
acp, oemcp = m[1], m[2]
f = re.findall(r'"([^"]*)"', m[3])
if len(f) != 10:
    sys.exit("gen_fontmachine: the row has %d string fields, not 10" % len(f))
oem, fixed, system, courier, serif, small, sserif96, sserif120, shell, tms = f
subs = [("MS Shell Dlg", shell), ("Tms Rmn", tms)] + re.findall(r'^HKLM,%FontSubStr%,"([^"]*)",,"([^"]*)"', open(inf).read(), re.M)
if len(subs) < 3:
    sys.exit("gen_fontmachine: no FontSubstitutes lines")
fam = set()
names = [x for x in sorted(os.listdir(fdir)) if os.path.isfile(os.path.join(fdir, x))]
for n in names:
    fam.update(x.lower() for x in fontfamilies.families(open(os.path.join(fdir, n), "rb").read()))
if not fam:
    sys.exit("gen_fontmachine: no font file in " + fdir)
rep, seen = [], set()
for a, body in re.findall(r'<alias binding="same">\s*<family>([^<]*)</family>\s*<accept>(.*?)</accept>', open(conf).read(), re.S):
    t = next((x for x in re.findall(r"<family>([^<]*)</family>", body) if x.lower() in fam), None)
    if t and a.lower() not in seen and a.lower() not in fam:
        seen.add(a.lower())
        rep.append((a, t))
q = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
o = ["/* generated by manifest/gen_fontmachine.py from tools/fonts-wine9 (wine.inf.in, font.c, 30-metric-aliases.conf, fonts/); do not edit */",
     "static const int kAcp = %s;" % acp]

def tab(name, rows):
    o.append("static const char *const %s[][2] = {" % name)
    o.extend("    { %s, %s }," % (q(a), q(b)) for a, b in rows)
    o.append("};")
tab("kHwFonts", [("OEMFONT.FON", oem), ("FIXEDFON.FON", fixed), ("FONTS.FON", system)])
tab("kFontsKey", [("Courier", courier), ("MS Serif", serif), ("MS Sans Serif", sserif96), ("Small Fonts", small)])
tab("kSubst", subs)
tab("kReplace", rep)
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(o) + "\n")
