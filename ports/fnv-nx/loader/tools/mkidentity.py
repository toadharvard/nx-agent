#!/usr/bin/env python3
"""mkidentity - the exe identity object of the guest boot glue (loader/guest/boot.c).

    mkidentity.py --exe FalloutNV.exe --out identity.c

Writes `const unsigned char fnvnx_exe_sha256[32]` (SHA-256 of the whole file) and `const unsigned int
fnvnx_exe_size` (its size in bytes).  Deterministic: the output is a function of the file's bytes only (no path,
no timestamp).  Exe-derived: write it outside the repository (container, fnv-nx-build), never commit it.
"""
import argparse, hashlib, os, sys


def render(data):
    h = hashlib.sha256(data).digest()
    rows = ''.join('    %s,\n' % ', '.join('0x%02x' % b for b in h[i:i + 8]) for i in range(0, 32, 8))
    return ('/* GENERATED by loader/tools/mkidentity.py from the game executable: exe-derived, never committed. */\n'
            'const unsigned char fnvnx_exe_sha256[32] = {\n%s};\n'
            'const unsigned int fnvnx_exe_size = %du;\n' % (rows, len(data)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--exe', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    with open(a.exe, 'rb') as f:
        data = f.read()
    if not 0 < len(data) < 1 << 32:
        sys.exit('mkidentity: %d bytes is not a file size the guest can hold' % len(data))
    with open(a.out, 'w') as f:
        f.write(render(data))


if __name__ == '__main__':
    main()
