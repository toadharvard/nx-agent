#!/usr/bin/env python3
"""Turn the decomp's build/image_check.json into the loader's probe table.

usage: mkprobes.py build/image_check.json --header OUT.h | --txt OUT.txt

The fingerprints come from the decomp, so the output is derived content: write it under build/, never commit it.
The C header defines `static const fnvnx_probe fnvnx_probes[]` and `FNVNX_NPROBES` for fnvnx_pe_check_probes().
"""
import argparse
import json


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('image_check')
    ap.add_argument('--header')
    ap.add_argument('--txt')
    a = ap.parse_args()
    spec = json.load(open(a.image_check))
    probes = [(int(va, 16), int(n), d.lower()) for va, n, d in spec['probes']]
    for va, n, d in probes:
        if len(d) != 64 or n > 4096:
            raise SystemExit('bad probe %#x' % va)
    if a.txt:
        with open(a.txt, 'w') as f:
            for va, n, d in probes:
                f.write('0x%08x %d %s\n' % (va, n, d))
    if a.header:
        with open(a.header, 'w') as f:
            f.write('/* generated by loader/tools/mkprobes.py from image_check.json (%s): local, do not commit */\n'
                    % spec.get('release', '?'))
            f.write('#include "fnvnx_loader.h"\n#define FNVNX_NPROBES %d\n' % len(probes))
            f.write('static const fnvnx_probe fnvnx_probes[FNVNX_NPROBES] = {\n')
            for va, n, d in probes:
                f.write('    {0x%08x, %d, {%s}},\n' % (va, n, ', '.join('0x' + d[i:i + 2] for i in range(0, 64, 2))))
            f.write('};\n')


if __name__ == '__main__':
    main()
