/* Guest-side boot glue: implements the loader's OS hooks (include/fnvnx_loader.h, fnvnx_os) on the host API v3
 * inside the ILP32 guest module and runs the start sequence (src/start.c, S1..S8). The guest runtime calls main().
 *
 * Nothing here decides anything: every hook is a total mapping onto one host call, and every failure is reported to
 * start.c, which stops the start with a logged message. There is no fallback value and no default provider.
 *   read        fs_open once, fs_pread of the exe (path FNVNX_EXE_PATH = the SD layout's exe, sdlayout.h)
 *   map_fixed   host map_fixed from a zeroed, page-aligned heap block (the host makes the block inaccessible)
 *   protect     FNVNX_PLAT_VM_PROTECT (host.c gains it, see below); R/W only, a request for X is refused
 *   alloc_va    pages of one VM-service reservation (the arena), committed per call; free_va decommits them
 * Imports: the platform's keys (fnvnx_import_key) for platform dlls; the lifted PE modules (fnvnx_modules, generated by
 * contract/modules.py) are loaded and bound by the loader itself (src/modules.c). Module files are read from the
 * directory of the exe under the table's name. */
#include <malloc.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "fnvnx/guest.h"
#include "fnvnx/hostapi.h"
#include "fnvnx/sdlayout.h"
#include "fnvnx_importkey.h"
#include "fnvnx_start.h"

#ifndef FNVNX_EXE_PATH
#define FNVNX_EXE_PATH FNVNX_SD_EXE   /* sdmc:/switch/fnv/FalloutNV.exe, where boot.cpp and the launcher look */
#endif
/* ext_call(FNVNX_EXT_PLATFORM, 8, {addr, size, prot}) -> 0 or a Horizon result: sets the protection of committed
 * guest pages (a map_fixed range or an arena range); prot bit0 = R, bit1 = W, 0 = no access. hostapi.h gains this. */
#ifndef FNVNX_PLAT_VM_PROTECT
#define FNVNX_PLAT_VM_PROTECT 8u
#endif
#ifndef FNVNX_EXE_NAME
#define FNVNX_EXE_NAME "FalloutNV.exe"
#endif
#define PAGE 0x1000u
#define EXIT_FAILED 0xF0000100u   /* main's result when the start sequence did not reach the guest's entry */

extern const uint8_t fnvnx_exe_sha256[32];   /* generated by loader/tools/mkidentity.py, linked in */
extern const unsigned int fnvnx_exe_size;

/* ---- files: file 0 is the exe, file k+1 module k of the table, found next to the exe under its name; opened on first
 * use (a missing file fails its reads, which the loader reports) ---- */
static int64_t g_fd[FNVNX_MAX_MODULES + 1u];
static uint8_t g_open[FNVNX_MAX_MODULES + 1u];

static int64_t file_fd(uint32_t file) {
    char path[512];
    size_t dir = strlen(FNVNX_EXE_PATH), n;
    const char *name;
    if (file > fnvnx_module_count) return -1;
    if (g_open[file]) return g_fd[file];
    if (file == FNVNX_FILE_EXE) return -1;   /* opened by main */
    while (dir && FNVNX_EXE_PATH[dir - 1] != '/') dir--;
    name = fnvnx_modules[file - 1u].name;
    n = strlen(name);
    if (dir + n + 1 > sizeof path) return -1;
    memcpy(path, FNVNX_EXE_PATH, dir);
    memcpy(path + dir, name, n + 1);
    g_fd[file] = (int64_t)fnvnx_hcall2(fnvnx_host->fs_open, FNVNX_ADDR(path), FNVNX_O_READ);
    if (g_fd[file] >= 0) g_open[file] = 1;
    return g_fd[file];
}

static int h_read(void *c, uint32_t file, uint32_t off, void *dst, uint32_t size) {
    uint8_t *d = (uint8_t *)dst;
    int64_t fd = file_fd(file);
    (void)c;
    if (fd < 0) return -1;
    while (size) {
        int64_t n = (int64_t)fnvnx_hcall4(fnvnx_host->fs_pread, (uint64_t)fd, FNVNX_ADDR(d), size, off);
        if (n <= 0) return -1;   /* error, or the file ends before the range does */
        d += n; off += (uint32_t)n; size -= (uint32_t)n;
    }
    return 0;
}

/* ---- memory ---- */
static uint64_t plat(uint32_t fn, uint64_t a, uint64_t b, uint64_t prot, uint32_t nargs) {
    uint64_t args[3];
    args[0] = a; args[1] = b; args[2] = prot;
    return fnvnx_hcall4(fnvnx_host->ext_call, FNVNX_EXT_PLATFORM, fn, FNVNX_ADDR(args), nargs);
}

/* The hook contract: zero-filled RW at exactly addr, failing if any of it is in use. Zero: the source block is
 * cleared before it is mapped (heap memory is not zero in general). In use: the host's map_fixed refuses a range
 * that is not free. The source block is surrounded by one page on each side so that no allocator metadata lies in
 * a page that becomes inaccessible; it is never freed (the host keeps its pages as the backing of the mapping). */
static int h_map_fixed(void *c, uintptr_t addr, uint32_t size, unsigned prot) {
    uint8_t *blk;
    (void)c; (void)prot;   /* the final protection is applied later by protect */
    if (!size || ((addr | size) & (PAGE - 1)) || size > 0xffff0000u - 2 * PAGE) return -1;
    if (!(blk = (uint8_t *)memalign(PAGE, size + 2 * PAGE))) return -1;
    memset(blk + PAGE, 0, size);
    if (fnvnx_hcall3(fnvnx_host->map_fixed, addr, size, FNVNX_ADDR(blk + PAGE))) { free(blk); return -1; }
    return 0;
}

static int h_protect(void *c, uintptr_t addr, uint32_t size, unsigned prot) {
    (void)c;
    if (prot & ~(unsigned)(FNVNX_PROT_R | FNVNX_PROT_W)) return -1;   /* the x86 image and the guest's data are never host-executable */
    return plat(FNVNX_PLAT_VM_PROTECT, addr, size, prot, 3) ? -1 : 0;
}

static void *h_alloc(void *c, uint32_t size) { (void)c; return malloc(size ? size : 1); }
static void h_free(void *c, void *p) { (void)c; free(p); }

static void h_log(void *c, const char *msg) {
    size_t n = strlen(msg);
    (void)c;
    fnvnx_hcall2(fnvnx_host->console_write, FNVNX_ADDR(msg), n);
    fnvnx_hcall2(fnvnx_host->console_write, FNVNX_ADDR("\n"), 1);
    fnvnx_hcall2(fnvnx_host->output_debug_string, FNVNX_ADDR(msg), n);
}

/* alloc_va: the arena. One reservation of the VM service (host_vm.inc: address space only, no hint) of ARENA_SIZE;
 * a call commits the pages it takes (zeroed, RW, whatever protect did there before) and free_va decommits them. Pages
 * are handed out first-fit from a bitmap under a lock (CreateThread calls from any thread). Why a result can never lie
 * in the reserved address set (sentinel and import keys, the exe image, the range of every module of the table, loaded
 * or not) or overlap any other mapping: the arena is a VM-service reservation, so the host gives out address space that
 * is neither mapped nor reserved; and the reservation is checked HERE, as a whole, against the reserved set by the
 * loader's own rule (fnvnx_address_reserved): a reservation that touches it is not used. start.c re-checks every
 * result of alloc_va (thread blocks) by the same rule. No address constant stands for the set. */
#define ARENA_SIZE 0x08000000u   /* 128 MiB of address space: stacks, TEBs and TLS blocks of all guest threads */
static fnvnx_proc proc;   /* large: not on the stack; the platform's VirtualQuery reads its section map */
const fnvnx_proc *fnvnx_start_proc(void) { return &proc; }
static uint32_t g_arena;
static uint32_t g_used[ARENA_SIZE / PAGE / 32];   /* bit per page: handed out */
static volatile uint32_t g_lock;

static int used(uint32_t pg) { return (g_used[pg >> 5] >> (pg & 31)) & 1u; }
static void mark(uint32_t pg, uint32_t n, int on) {
    for (; n; n--, pg++) { if (on) g_used[pg >> 5] |= 1u << (pg & 31); else g_used[pg >> 5] &= ~(1u << (pg & 31)); }
}

static uint32_t h_alloc_va(void *c, uint32_t size, unsigned prot) {
    uint32_t n = size / PAGE, pg, run = 0, va = 0;
    (void)c;
    if (!size || (size & (PAGE - 1)) || prot != (FNVNX_PROT_R | FNVNX_PROT_W) || n > ARENA_SIZE / PAGE) return 0;
    fnvnx_lock(&g_lock);
    if (!g_arena) {
        uint64_t a = plat(FNVNX_PLAT_VM_RESERVE, 0, ARENA_SIZE, 0, 2);
        if (!(a & (PAGE - 1)) && a <= 0x100000000ull - ARENA_SIZE && !fnvnx_address_reserved(&proc, (uint32_t)a, ARENA_SIZE))
            g_arena = (uint32_t)a;
    }
    for (pg = 0; g_arena && pg < ARENA_SIZE / PAGE; pg++) {
        run = used(pg) ? 0 : run + 1;
        if (run == n) { va = g_arena + (pg + 1 - n) * PAGE; break; }
    }
    if (va) {
        mark((va - g_arena) / PAGE, n, 1);
        if (plat(FNVNX_PLAT_VM_COMMIT, va, size, 0, 2)) { mark((va - g_arena) / PAGE, n, 0); va = 0; }
    }
    fnvnx_unlock(&g_lock);
    return va;
}

static int h_free_va(void *c, uint32_t va, uint32_t size) {
    uint32_t pg, n = size / PAGE, k;
    int r = -1;
    (void)c;
    if (!g_arena || !size || ((va | size) & (PAGE - 1)) || va < g_arena || va - g_arena > ARENA_SIZE - size) return -1;
    pg = (va - g_arena) / PAGE;
    fnvnx_lock(&g_lock);
    for (k = 0; k < n && used(pg + k); k++) {}
    if (k == n && !plat(FNVNX_PLAT_VM_DECOMMIT, va, size, 0, 2)) { mark(pg, n, 0); r = 0; }
    fnvnx_unlock(&g_lock);
    return r;
}

/* ---- imports ---- */
static uint32_t resolve(void *c, const char *dll, const char *name, uint32_t ordinal) {
    (void)c;
    return fnvnx_import_key(dll, name, ordinal);
}

/* ---- the process ---- */

static const fnvnx_os os = {NULL, h_read, h_map_fixed, h_protect, h_alloc, h_free, h_log, h_alloc_va, h_free_va};

static int fail(const char *what, long long v) {
    char b[160];
    snprintf(b, sizeof b, "fnvnx-start: %s %lld", what, v);
    h_log(NULL, b);
    return (int)EXIT_FAILED;
}

int main(void) {
    static fnvnx_start_cfg cfg;
    FnvnxStat st;
    int r;
    g_fd[0] = (int64_t)fnvnx_hcall2(fnvnx_host->fs_open, FNVNX_ADDR(FNVNX_EXE_PATH), FNVNX_O_READ);
    if (g_fd[0] < 0) { h_log(NULL, "fnvnx-start: cannot open " FNVNX_EXE_PATH); return fail("failed", (long long)g_fd[0]); }
    g_open[0] = 1;
    if (fnvnx_hcall2(fnvnx_host->fs_fstat, (uint64_t)g_fd[0], FNVNX_ADDR(&st)) || st.size != fnvnx_exe_size) {
        h_log(NULL, "fnvnx-start: identity mismatch: the exe is not the one the image was built from (size)");
        return fail("failed", FNVNX_START_E_IDENTITY);
    }
    cfg.file_size = (uint32_t)st.size;
    memcpy(cfg.sha256, fnvnx_exe_sha256, 32);
    cfg.resolve = resolve;
    cfg.modules = fnvnx_modules;
    cfg.nmodules = fnvnx_module_count;
    cfg.exe_name = FNVNX_EXE_NAME;
    cfg.bias = 0;   /* guest VA = host address */
    if ((r = fnvnx_start_prepare(&proc, &os, &cfg))) return fail("failed", r);
    if ((r = fnvnx_start_init_modules(&proc))) return fail("failed", r);
    return (int)fnvnx_start_enter(&proc);
}
