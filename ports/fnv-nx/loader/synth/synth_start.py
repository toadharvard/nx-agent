#!/usr/bin/env python3
"""Synthetic PE32 for loader/host/startcheck.c (rules S1-S8 of the start sequence).

    synth_start.py out.pe out.h

Writes a small deterministic image and a C header with the facts the test checks (import slots, TLS directory,
SHA-256 of the file).  The image has: headers, .text (code), .rdata (R, vsize > raw), .data (RW, bss tail),
a two-page gap, .disc (discardable), .big (raw size > virtual size), a trailing gap page, two import DLLs (by name
and by ordinal), a delay-import table, a TLS directory (template + zero fill + two callbacks, 16-byte alignment)
and a non-default stack reserve.  Nothing here is derived from any game file."""
import hashlib, struct, sys

BASE, SIZE_OF_IMAGE, HDRS, STACK_RES, STACK_COM = 0x400000, 0xc000, 0x400, 0x30000, 0x2000
ENTRY_RVA, CB1, CB2 = 0x1010, 0x1100, 0x1200
SECS = [  # name, rva, vsize, raw_off, raw_size, characteristics
    ('.text', 0x1000, 0x1800, 0x400, 0x1800, 0x60000020),
    ('.rdata', 0x3000, 0x1000, 0x1c00, 0x600, 0x40000040),
    ('.data', 0x4000, 0x3000, 0x2200, 0x400, 0xC0000040),
    ('.disc', 0x9000, 0x800, 0x2600, 0x200, 0x42000040),
    ('.big', 0xa000, 0x100, 0x2800, 0x200, 0xC0000040),
]
FILE_SIZE = 0x2a00
RD, DATA = 0x3000, 0x4000
TLS_TEMPLATE, TLS_TSIZE, TLS_ZERO, TLS_INDEX = DATA, 0x40, 0x30, DATA + 0x80
DELAY_IAT = DATA + 0x100
IMPORTS = [('KERNEL32.dll', ['GetTickCount', 'ExitProcess', 5, 'Sleep']), ('USER32.dll', ['MessageBoxA', 17])]
DELAY = ('delay.dll', ['DelayedOne', 3])

img = bytearray(FILE_SIZE)
for i in range(FILE_SIZE):
    img[i] = ((i * 7 + (i >> 8) * 13) & 0xfe) | 1          # never zero, so zero-fill checks mean something

def put(off, b): img[off:off + len(b)] = b
def u32(v): return struct.pack('<I', v)
def foff(rva):
    for n, r, vs, ro, rs, c in SECS:
        if r <= rva < r + rs: return ro + rva - r
    raise ValueError(hex(rva))

cur = [RD + 0xa0]
def hintname(name):
    rva = cur[0]; b = struct.pack('<H', 0x11) + name.encode() + b'\0'
    b += b'\0' * (len(b) & 1); put(foff(rva), b); cur[0] += len(b); return rva

put(foff(RD + 0x100), b'KERNEL32.dll\0'); put(foff(RD + 0x120), b'USER32.dll\0')
descs, tab, slots = [], RD + 0x40, []
for (dll, items), namerva in zip(IMPORTS, (RD + 0x100, RD + 0x120)):
    n = len(items); int_rva = tab; iat_rva = tab + 4 * (n + 1)
    words = [(0x80000000 | it) if isinstance(it, int) else hintname(it) for it in items] + [0]
    put(foff(int_rva), b''.join(u32(w) for w in words)); put(foff(iat_rva), b''.join(u32(w) for w in words))
    descs.append(struct.pack('<IIIII', int_rva, 0, 0, namerva, iat_rva))
    for k, it in enumerate(items): slots.append((iat_rva + 4 * k, dll, it))
    tab = iat_rva + 4 * (n + 1)
assert tab <= RD + 0xa0
put(foff(RD), b''.join(descs) + b'\0' * 20)
# TLS directory + callbacks
put(foff(RD + 0x140), u32(BASE + CB1) + u32(BASE + CB2) + u32(0))
put(foff(RD + 0x160), struct.pack('<IIIIII', BASE + TLS_TEMPLATE, BASE + TLS_TEMPLATE + TLS_TSIZE, BASE + TLS_INDEX,
                                  BASE + RD + 0x140, TLS_ZERO, 5 << 20))
put(foff(TLS_INDEX), u32(0x12345678))
# delay-import table (RVA form, attrs = 1); its slots hold a junk "thunk" the helper would use
put(foff(RD + 0x240), b'delay.dll\0')
cur[0] = RD + 0x260
dwords = [hintname(DELAY[1][0]), 0x80000003, 0]
put(foff(RD + 0x1c0), b''.join(u32(w) for w in dwords))
put(foff(RD + 0x180), struct.pack('<IIIIIIII', 1, RD + 0x240, DATA + 0x200, DELAY_IAT, RD + 0x1c0, 0, 0, 0) + b'\0' * 32)
put(foff(DELAY_IAT), u32(0xd1d1d1d1) + u32(0xd2d2d2d2) + u32(0))
delay_slots = [DELAY_IAT, DELAY_IAT + 4]

opt = bytearray(224)
struct.pack_into('<HBB', opt, 0, 0x10b, 14, 0)
struct.pack_into('<IIIIII', opt, 4, 0x1800, 0x1400, 0x3000, ENTRY_RVA, 0x1000, 0x3000)
struct.pack_into('<IIIHHHHHHIIII', opt, 28, BASE, 0x1000, 0x200, 5, 1, 0, 0, 5, 1, 0, SIZE_OF_IMAGE, HDRS, 0)
struct.pack_into('<HH', opt, 68, 2, 0x8140)
struct.pack_into('<IIIIII', opt, 72, STACK_RES, STACK_COM, 0x100000, 0x1000, 0, 16)
dirs = {1: (RD, 60), 9: (RD + 0x160, 24), 13: (RD + 0x180, 64)}
for k, (r, s) in dirs.items(): struct.pack_into('<II', opt, 96 + 8 * k, r, s)
hdr = bytearray(HDRS)
hdr[0:2] = b'MZ'; struct.pack_into('<I', hdr, 0x3c, 0x80)
hdr[0x80:0x84] = b'PE\0\0'
struct.pack_into('<HHIIIHH', hdr, 0x84, 0x14c, len(SECS), 0x5f000000, 0, 0, 224, 0x0102)
hdr[0x98:0x98 + 224] = opt
for i, (n, r, vs, ro, rs, c) in enumerate(SECS):
    struct.pack_into('<8sIIIIIIHHI', hdr, 0x178 + 40 * i, n.encode(), vs, r, rs, ro, 0, 0, 0, 0, c)
img[0:HDRS] = hdr
data = bytes(img)
open(sys.argv[1], 'wb').write(data)

with open(sys.argv[2], 'w') as h:
    h.write('/* generated by synth/synth_start.py: facts about the synthetic image */\n')
    h.write('#define SS_FILE_SIZE %du\n#define SS_BASE 0x%08xu\n#define SS_SIZE_OF_IMAGE 0x%xu\n' % (len(data), BASE, SIZE_OF_IMAGE))
    h.write('#define SS_STACK_RESERVE 0x%xu\n#define SS_ENTRY 0x%08xu\n#define SS_CB1 0x%08xu\n#define SS_CB2 0x%08xu\n' % (STACK_RES, BASE + ENTRY_RVA, BASE + CB1, BASE + CB2))
    h.write('#define SS_TLS_TEMPLATE 0x%08xu\n#define SS_TLS_TSIZE 0x%xu\n#define SS_TLS_ZERO 0x%xu\n#define SS_TLS_INDEX 0x%08xu\n#define SS_TLS_ALIGN 16u\n' % (BASE + TLS_TEMPLATE, TLS_TSIZE, TLS_ZERO, BASE + TLS_INDEX))
    h.write('static const unsigned char ss_sha256[32] = {%s};\n' % ','.join(str(b) for b in hashlib.sha256(data).digest()))
    h.write('static const struct { unsigned slot; const char *dll; const char *name; unsigned ordinal; } ss_imports[] = {\n')
    for rva, dll, it in slots:
        h.write('    {0x%08xu, "%s", %s, %du},\n' % (BASE + rva, dll, '0' if isinstance(it, int) else '"%s"' % it, it if isinstance(it, int) else 0xffffffff))
    h.write('};\n#define SS_NIMPORTS %d\n' % len(slots))
    h.write('static const unsigned ss_delay_slots[] = {0x%08xu, 0x%08xu};\n' % (BASE + delay_slots[0], BASE + delay_slots[1]))
