#ifndef FNVNX_MODULES_H
#define FNVNX_MODULES_H
/* The lifted PE modules of the exe's static import closure (rules M1..M4; contract/modules.py generates the table).
 *
 * Table order is the Windows initialisation order for static imports (dependencies first); it is also the order in
 * which the modules are mapped, in which they get TLS indices (the exe has index 0, a module with a TLS directory
 * takes the next index) and in which os->read numbers their files (FNVNX_FILE_MODULE(k)). `base` is the module's
 * static load base (64 KiB aligned): the lifter lifts the module at exactly this address, the loader maps it there
 * and relocates it when the base differs from the preferred one. */
#include <stdint.h>

#define FNVNX_MAX_MODULES 16u

typedef struct fnvnx_module_desc {
    const char *name;        /* lowercase file name with ".dll": the name the imports use (contract/iat.py norm_dll) */
    uint8_t     sha256[32];  /* SHA-256 of the whole file */
    uint32_t    file_size;
    uint32_t    base;
} fnvnx_module_desc;

/* Generated by contract/modules.py (modules.c). fnvnx_module_count may be 0 (the array then holds one unused entry). */
extern const fnvnx_module_desc fnvnx_modules[];
extern const uint32_t fnvnx_module_count;

#endif
