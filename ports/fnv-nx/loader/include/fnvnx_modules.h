#ifndef FNVNX_MODULES_H
#define FNVNX_MODULES_H
/* The lifted PE modules of the exe's static import closure (rules M1..M4; contract/modules.py generates the table).
 *
 * The table holds EVERY non-system PE32 dll the build found (a module loaded later through LoadLibrary must already
 * have its static base: lifted code is keyed by image address). The reserved address set of the process is
 * [0x000f0000, 0x00200000) (sentinel, import keys), the exe image and [base, base + size_of_image) of EVERY row, mapped or
 * not: nothing else (guest allocations, the VM arena, thread blocks) may ever be placed there. The static modules (is_static) come first, in the
 * Windows initialisation order for static imports (dependencies first), then the on-demand ones. Table order is also
 * the order in which the static modules are mapped, in which they get TLS indices (the exe has index 0, a module with a TLS directory
 * takes the next index) and in which os->read numbers their files (FNVNX_FILE_MODULE(k)). `base` is the module's
 * static load base (64 KiB aligned): the lifter lifts the module at exactly this address, the loader maps it there
 * and relocates it when the base differs from the preferred one. */
#include <stdint.h>

#define FNVNX_MAX_MODULES 32u

typedef struct fnvnx_module_desc {
    const char *name;        /* lowercase file name with ".dll": the name the imports use (contract/iat.py norm_dll) */
    uint8_t     sha256[32];  /* SHA-256 of the whole file */
    uint32_t    file_size;
    uint32_t    base;
    uint32_t    size_of_image;  /* SizeOfImage rounded up to a page: the range [base, base + size_of_image) is reserved for the module */
    uint32_t    is_static;   /* 1: in the exe's static import closure (mapped and initialised at start); 0: on demand */
} fnvnx_module_desc;

/* Generated by contract/modules.py (modules.c). fnvnx_module_count may be 0 (the array then holds one unused entry). */
extern const fnvnx_module_desc fnvnx_modules[];
extern const uint32_t fnvnx_module_count;

#endif
