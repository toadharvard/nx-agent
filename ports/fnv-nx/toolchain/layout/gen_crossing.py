#!/usr/bin/env python3
"""gen_crossing.py - writes crossing_terms.inc, the table of fnvnx_layout.cc's `.fnvnx.crossing` record: every term of
toolchain/msvcmodel/DATAMODEL.json crossing_forbidden.terms as `{ "<id>", CF_<TREE_FACT> }`. The ids and the tree fact each one is decided by
come from that file (generated by datamodel/gen.py from datamodel/facts.json); the plugin source names no id. A term whose `tree_fact` is not in
the plugin's vocabulary (VOCAB, the GCC predicates fnvnx_layout.cc implements) is an error here, so a new term cannot be built without its predicate.
  gen_crossing.py [--check]      writes next to this file; --check compares and exits 1 on a difference, never writes"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VOCAB = ('binfo_virtual', 'ptrmem', 'va_list_node')


def text():
    d = json.load(open(os.path.join(HERE, '..', 'msvcmodel', 'DATAMODEL.json')))
    out = ['// generated by gen_crossing.py from toolchain/msvcmodel/DATAMODEL.json crossing_forbidden.terms; do not edit']
    for t in d['crossing_forbidden']['terms']:
        if t['tree_fact'] not in VOCAB:
            sys.exit('term %s: tree_fact %r is not implemented by fnvnx_layout.cc (%s)' % (t['id'], t['tree_fact'], ', '.join(VOCAB)))
        out.append('{ "%s", CF_%s },' % (t['id'], t['tree_fact'].upper()))
    return '\n'.join(out) + '\n'


def main():
    here = os.path.join(HERE, 'crossing_terms.inc')
    s = text()
    if '--check' in sys.argv:
        return 0 if os.path.isfile(here) and open(here).read() == s else sys.exit('crossing_terms.inc differs from DATAMODEL.json')
    open(here, 'w').write(s)
    return 0


if __name__ == '__main__':
    sys.exit(main())
