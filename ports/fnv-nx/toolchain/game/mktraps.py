#!/usr/bin/env python3
"""undefined.txt -> traps.S: one stub per still-undefined symbol. A stub reports its own name and the caller
(x30) through __fnvnx_undef_trap(name, lr) (toolchain/game/boot.cpp), which logs and exits, so a partial link
still boots as far as it can and tells exactly which missing piece it hit first.

    python3 -I toolchain/game/mktraps.py undefined.txt traps.S
"""
import sys

names = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out = ["// GENERATED by toolchain/game/mktraps.py", "    .text"]
for i, n in enumerate(names):
    q = '"' + n.replace('"', '\\"') + '"'
    out += [f"    .section .text.fnvnx_trap.{i},\"ax\",%progbits", "    .p2align 2",
            f"    .globl {q}", f"    .type {q}, %function", f"{q}:",
            f"    adrp x0, .Ltrapname{i}", f"    add x0, x0, :lo12:.Ltrapname{i}",
            "    mov x1, x30", "    b __fnvnx_undef_trap",
            "    .section .rodata.fnvnx_trapnames,\"aMS\",%progbits,1", f".Ltrapname{i}:",
            "    .asciz " + q]
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print(f"{sys.argv[2]}: {len(names)} trap stubs")
