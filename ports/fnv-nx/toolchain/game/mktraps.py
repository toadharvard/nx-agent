#!/usr/bin/env python3
"""undefined.txt -> traps.S: one stub per still-undefined symbol, so a partial link still boots as far as it can.

    python3 -I toolchain/game/mktraps.py undefined.txt traps.S [--readelf R --objects @list obj...]

Functions get a code stub that reports its own name and the caller (x30) through __fnvnx_undef_trap(name, lr)
(toolchain/game/boot.cpp) and returns 0. Data gets zero-filled writable storage (DATA_SIZE bytes in .bss): a variable
the units declare but nothing defines and S2 binds to no image address. Before, the variable was a code stub, and
the first store into it faulted on read-only code. A name is data when no object calls it (no CALL26/JUMP26
relocation against it, which needs --readelf and --objects) and it is not a function by its name (an Itanium
function signature, __fnv_<address>, FUN_<address>, a Bink/D3DX import). Writes to data stubs do not reach the
image address the original used; the stub only lets the code run on. The names go to <traps.S>.data.txt.
"""
import argparse
import re
import subprocess

DATA_SIZE = 4096
FUNC_NAME = re.compile(r"^(__fnv_[0-9a-fA-F]{8}|FUN_[0-9a-fA-F]{8}$|Bink|_Bink|D3DX|__fnvnx_)")


def called_symbols(readelf, objs):
    called = set()
    for i in range(0, len(objs), 200):
        r = subprocess.run([readelf, "-rW"] + objs[i:i + 200], capture_output=True, text=True)
        for line in r.stdout.splitlines():
            f = line.split()
            if len(f) >= 5 and f[2].startswith("R_AARCH64_") and f[2].endswith(("CALL26", "JUMP26")):
                called.add(f[4])
    return called


def objects(args):
    for a in args:
        if a.startswith("@"):
            for line in open(a[1:]):
                if line.strip():
                    yield line.strip().strip('"')
        else:
            yield a


def is_function_name(name, demangled):
    if FUNC_NAME.match(name):
        return True
    if name.startswith("_Z"):
        return "(" in demangled   # Itanium: functions carry their parameter list, variables do not
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("undefined")
    ap.add_argument("out")
    ap.add_argument("--readelf")
    ap.add_argument("--objects", nargs="*", default=[])
    ap.add_argument("--cxxfilt", default="c++filt")
    a = ap.parse_args()
    names = [l.strip() for l in open(a.undefined) if l.strip()]
    data = set()
    if a.readelf and a.objects:
        called = called_symbols(a.readelf, list(objects(a.objects)))
        dem = subprocess.run([a.cxxfilt], input="\n".join(names), capture_output=True, text=True).stdout.split("\n")
        data = {n for n, d in zip(names, dem) if n not in called and not is_function_name(n, d)}
    out = ["// GENERATED by toolchain/game/mktraps.py", "    .text"]
    for i, n in enumerate(names):
        q = '"' + n.replace('"', '\\"') + '"'
        if n in data:
            out += [f"    .section .bss.fnvnx_undef_data.{i},\"aw\",%nobits", "    .p2align 4",
                    f"    .globl {q}", f"    .type {q}, %object", f"    .size {q}, {DATA_SIZE}", f"{q}:",
                    f"    .zero {DATA_SIZE}"]
            continue
        out += [f"    .section .text.fnvnx_trap.{i},\"ax\",%progbits", "    .p2align 2",
                f"    .globl {q}", f"    .type {q}, %function", f"{q}:",
                f"    adrp x0, .Ltrapname{i}", f"    add x0, x0, :lo12:.Ltrapname{i}",
                "    mov x1, x30", "    b __fnvnx_undef_trap",
                "    .section .rodata.fnvnx_trapnames,\"aMS\",%progbits,1", f".Ltrapname{i}:",
                "    .asciz " + q]
    open(a.out, "w").write("\n".join(out) + "\n")
    with open(a.out + ".data.txt", "w") as f:
        f.write("\n".join(sorted(data)) + ("\n" if data else ""))
    print(f"{a.out}: {len(names) - len(data)} trap stubs, {len(data)} data stubs ({DATA_SIZE} bytes each)")


if __name__ == "__main__":
    main()
