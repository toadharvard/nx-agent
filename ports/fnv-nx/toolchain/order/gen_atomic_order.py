#!/usr/bin/env python3
"""Derive the atomic memory-order table of fnvnx_order from the PINNED GCC 13.3.0 source tarball.

usage: gen_atomic_order.py <gcc-13.3.0.tar.xz>   -> prints the C++ block between the ATOMICS markers of fnvnx_order.cc
The tarball must have the sha256 below (the pin of toolchain/msvcmodel/build.sh); gcc/sync-builtins.def is read from it.
 ifn_order   the atomic internal functions (IFN_ATOMIC_*) and the memory-order arguments their expanders read (internal-fn.cc, builtins.cc).
 atomic_order  every __atomic_* builtin of sync-builtins.def with the bit mask of its memory-order parameters: the `INT`
             parameters of its BT_FN_ type (in these types every int is a memory order, the values are I1..I16)."""
import hashlib, re, sys, tarfile

PIN = "0845e9621c9543a13f484e94584a49ffc0129970e9914624235fc1d061a0c083"
raw = open(sys.argv[1], "rb").read()
if hashlib.sha256(raw).hexdigest() != PIN:
    raise SystemExit("tarball sha256 differs from the pin " + PIN)
import io
tf = tarfile.open(fileobj=io.BytesIO(raw), mode="r:xz")
def member(n):
    return tf.extractfile("gcc-13.3.0/gcc/" + n).read().decode("utf-8")
sdef, ifnc, bic = member("sync-builtins.def"), member("internal-fn.cc"), member("builtins.cc")
# the atomic internal functions (GCC folds an __atomic builtin into one of them before the order pass): their expander in internal-fn.cc calls
# one function of builtins.cc, which reads each memory order as `get_memmodel (gimple_call_arg (call, N))`
ifn = []
for m in re.finditer(r"^expand_(ATOMIC_\w+) \(internal_fn, gcall \*call\)\n\{\n\s*(\w+) \(call\);", ifnc, re.M):
    name, callee = m.groups()
    fm = re.search(r"^%s \(gcall \*call\)\n\{(.*?)\n\}\n" % re.escape(callee), bic, re.M | re.S)
    if not fm:
        raise SystemExit("no builtins.cc function " + callee)
    mask = 0
    for a in re.finditer(r"get_memmodel \(gimple_call_arg \(call, (\d+)\)\)", fm.group(1)):
        mask |= 1 << int(a.group(1))
    ifn.append((name, mask, bic.count("\n", 0, fm.start()) + 1))
print("// ATOMICS-BEGIN  generated by gen_atomic_order.py from the pinned gcc-13.3.0.tar.xz (sha256 %s)" % PIN)
print("// gcc/sync-builtins.def sha256 %s; do not edit" % hashlib.sha256(sdef.encode()).hexdigest())
print("// the memory-order parameters (bit i = argument i) of the __atomic builtins, sync-builtins.def line")
print("static const struct { built_in_function code; unsigned mask; int line; } atomic_order[] = {")
for m in re.finditer(r'^DEF_SYNC_BUILTIN\s*\(\s*(BUILT_IN_ATOMIC_\w+)\s*,\s*"__atomic_\w+"\s*,\s*(BT_FN_\w+)', sdef, re.M):
    toks = re.findall(r"CONST_VPTR|CONST_PTR|VPTR|PTR|SIZE|BOOL|VOID|INT|I\d+", m.group(2)[len("BT_FN_"):])
    args = toks[1:]
    mask = sum(1 << i for i, a in enumerate(args) if a == "INT")
    if mask:
        print("  {%s, 0x%x, %d}," % (m.group(1), mask, sdef.count("\n", 0, m.start()) + 1))
print("};")
print("// the atomic internal functions: the memory-order arguments (bit i = argument i), builtins.cc line of the expanding function")
print("static const struct { internal_fn code; unsigned mask; int line; } ifn_order[] = {")
for name, mask, ln in ifn:
    print("  {IFN_%s, 0x%x, %d}," % (name, mask, ln))
print("};")
print("// ATOMICS-END")
