#!/usr/bin/env python3
"""Derive the builtin tables of fnvnx_order from the PINNED GCC 13.3.0 source tarball.

usage: gen_foldset.py <gcc-13.3.0.tar.xz>   -> prints the C++ block between the FOLDSET markers of fnvnx_order.cc
The tarball must have the sha256 below (the pin of toolchain/msvcmodel/build.sh); gcc/gimple-fold.cc and gcc/builtins.def
are read from it.
 fold_set    every `case BUILT_IN_*:` label of gimple_fold_builtin (the whole function, up to its `default:;`) and of the
             switch in gimple_fold_builtin_memory_chk: the builtins GCC's folder rewrites into memory accesses or into other
             builtins. Labels and line numbers are read from the source.
 atomic_order  every __atomic_* builtin of sync-builtins.def with the bit mask of its memory-order parameters: the `INT`
             parameters of its BT_FN_ type (in these types every int is a memory order, the values are I1..I16).
 nolib_ptr   every builtin of builtins.def that has NO library function (its DEF_BUILTIN call passes BT_LAST as the
             library type) and takes a pointer argument (its BT_FN_ type name has PTR or VALIST in it), and the typeless DEF_BUILTIN_STUB entries: for these the library-call
             form does not exist, so order decides by GCC's own fnspec (memory-free) or reports a compile error."""
import hashlib, re, sys, tarfile

PIN = "0845e9621c9543a13f484e94584a49ffc0129970e9914624235fc1d061a0c083"
raw = open(sys.argv[1], "rb").read()
if hashlib.sha256(raw).hexdigest() != PIN:
    raise SystemExit("tarball sha256 differs from the pin " + PIN)
import io
tf = tarfile.open(fileobj=io.BytesIO(raw), mode="r:xz")
def member(n):
    return tf.extractfile("gcc-13.3.0/gcc/" + n).read().decode("utf-8")
src, bdef, sdef = member("gimple-fold.cc"), member("builtins.def"), member("sync-builtins.def")
lines = src.split("\n")

def func_range(name):
    for i, l in enumerate(lines):
        if re.match(r"^%s \(" % re.escape(name), l):
            j = i
            while lines[j] != "}":
                j += 1
            return i, j
    raise SystemExit("no function " + name)

seen = {}
for fn in ("gimple_fold_builtin", "gimple_fold_builtin_memory_chk"):
    a, b = func_range(fn)
    for k in range(a, b + 1):
        m = re.match(r"\s*case (BUILT_IN_[A-Z0-9_]+):", lines[k])
        if m:
            seen.setdefault(m.group(1), (fn, k + 1))

# builtins.def: the macros whose DEF_BUILTIN passes BT_LAST as the library type
nolib_macros = set()
for m in re.finditer(r"#define (DEF_\w+)\s*\([^)]*\)\s*\\?\s*\n?\s*DEF_BUILTIN\s*\(([^;]*?)\)\s*\n", bdef, re.S):
    args = [a.strip() for a in re.sub(r"\\\n", " ", m.group(2)).split(",")]
    if len(args) > 4 and args[4] == "BT_LAST":
        nolib_macros.add(m.group(1))
nolib = {}
for m in re.finditer(r"^(DEF_\w+)\s*\(\s*(BUILT_IN_\w+)\s*,\s*([^,]*),\s*(BT_FN_\w+)", bdef, re.M):
    macro, enum, _, ty = m.groups()
    if macro in nolib_macros and re.search(r"PTR|VALIST", ty):
        nolib[enum] = bdef.count("\n", 0, m.start()) + 1

for m in re.finditer(r"^DEF_BUILTIN_STUB\s*\(\s*(BUILT_IN_\w+)\s*,", bdef, re.M):
    nolib.setdefault(m.group(1), bdef.count("\n", 0, m.start()) + 1)   # compiler-internal stubs: no type, no library function

print("// FOLDSET-BEGIN  generated by gen_foldset.py from the pinned gcc-13.3.0.tar.xz (sha256 %s)" % PIN)
print("// gcc/gimple-fold.cc sha256 %s, gcc/builtins.def sha256 %s; do not edit" %
      (hashlib.sha256(src.encode()).hexdigest(), hashlib.sha256(bdef.encode()).hexdigest()))
print("static const struct { built_in_function code; const char *where; } fold_set[] = {")
for name, (fn, ln) in sorted(seen.items(), key=lambda kv: kv[1][1]):
    print('  {%s, "%s gimple-fold.cc:%d"},' % (name, fn, ln))
print("};")
print("// builtins with no library function that take a pointer (builtins.def line)")
print("static const struct { built_in_function code; int line; } nolib_ptr[] = {")
for name, ln in sorted(nolib.items(), key=lambda kv: kv[1]):
    print("  {%s, %d}," % (name, ln))
print("};")
print("// the memory-order parameters (bit i = argument i) of the __atomic builtins, sync-builtins.def line")
print("static const struct { built_in_function code; unsigned mask; int line; } atomic_order[] = {")
for m in re.finditer(r'^DEF_SYNC_BUILTIN\s*\(\s*(BUILT_IN_ATOMIC_\w+)\s*,\s*"__atomic_\w+"\s*,\s*(BT_FN_\w+)', sdef, re.M):
    toks = re.findall(r"CONST_VPTR|CONST_PTR|VPTR|PTR|SIZE|BOOL|VOID|INT|I\d+", m.group(2)[len("BT_FN_"):])
    args = toks[1:]
    mask = sum(1 << i for i, a in enumerate(args) if a == "INT")
    if mask:
        print("  {%s, 0x%x, %d}," % (m.group(1), mask, sdef.count("\n", 0, m.start()) + 1))
print("};")
print("// FOLDSET-END")
