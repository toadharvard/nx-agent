#!/usr/bin/env python3
"""Derive the builtin fold set of fnvnx_order from GCC's gimple-fold.cc (pinned release 13.3.0).

usage: gen_foldset.py <gimple-fold.cc>   -> prints the C++ block between the FOLDSET markers of fnvnx_order.cc
The set is every `case BUILT_IN_*:` label of the two switches that rewrite a call into memory accesses or into another
builtin: gimple_fold_builtin (the dispatcher, the whole function up to its `default:;`) and the switch inside
gimple_fold_builtin_memory_chk that maps the _chk forms to the plain ones. Nothing is picked by hand: the labels are
read from the source, with their line numbers."""
import hashlib, re, sys

src = open(sys.argv[1], encoding="utf-8").read()
lines = src.split("\n")

def func_range(name):
    for i, l in enumerate(lines):
        if re.match(r"^%s \(" % re.escape(name), l):
            j = i
            while lines[j] != "}":
                j += 1
            return i, j
    raise SystemExit("no function " + name)

found = []
for fn in ("gimple_fold_builtin", "gimple_fold_builtin_memory_chk"):
    a, b = func_range(fn)
    for k in range(a, b + 1):
        m = re.match(r"\s*case (BUILT_IN_[A-Z0-9_]+):", lines[k])
        if m:
            found.append((m.group(1), fn, k + 1))
seen = {}
for name, fn, ln in found:
    seen.setdefault(name, (fn, ln))
print("// FOLDSET-BEGIN  generated by gen_foldset.py from GCC 13.3.0 gcc/gimple-fold.cc (sha256 %s); do not edit" %
      hashlib.sha256(src.encode()).hexdigest())
print("static const struct { built_in_function code; const char *where; } fold_set[] = {")
for name, (fn, ln) in sorted(seen.items(), key=lambda kv: kv[1][1]):
    print('  {%s, "%s gimple-fold.cc:%d"},' % (name, fn, ln))
print("};")
print("// FOLDSET-END")
