#!/usr/bin/env python3
"""records.py - the records the compiler build reads, as one shell file (RECORDS_SH). A generator of the toolchain root: the two steps (stage1.sh, stage2.sh) run in a
sandbox with no recipe.py, no python modules and no repo, so everything they take from the records (verify/targets.json, guest_compiler.json, recipe.py's
declarations) is this file, mounted as an input and therefore in the key of exactly the steps that read it. The values are computed by the same functions
that every other reader uses (recipe.runtime_configure, runtime_configure_patch, runtime_cflags, semantics_set, plugin_args, PLUGIN_SOURCES): one source, no copy.

    python3 -I records.py [VERIFY_DIR] > records.sh

Variables (bash): T ABI CPUARCH MLFLAG (the multilib selector) GCC_RT_CONF[] (runtime_configure) CFG_SUBDIRS[] CFG_GUEST_LD CFG_PROTOCOL_SRC
RUNTIME_CFLAGS[] SEMANTICS[] PLUGIN_ORDER[] (the load order = recipe.PLUGIN_SOURCES) and PLUGIN_ARGV_<name>[] (recipe.plugin_args("native"), without the
recipe stage's report path PLUGIN_OUT: a runtime build has no /out report)."""
import json
import os
import shlex
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
verify = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "verify")
sys.path.insert(0, verify)
import recipe  # noqa: E402

t = json.load(open(os.path.join(verify, "targets.json")))
pin = json.load(open(os.path.join(verify, "guest_compiler.json")))
code = t["guest_platform"]["code"]
assert "-fPIC" in code, "targets.json guest_platform.code has no -fPIC"   # the multilib selector: the code model's -fPIC
cfg = recipe.runtime_configure_patch(pin)
q = shlex.quote
arr = lambda name, xs: "%s=(%s)" % (name, " ".join(q(x) for x in xs))
out = ["# generated by toolchain/msvcmodel/records.py; do not edit",
       "T=%s" % q(t["guest_platform"]["triplet"]), "ABI=%s" % q(t["guest_platform"]["abi"]),
       "CPUARCH=%s" % q(t["console_cpu"]["arch"] + "".join("+" + f for f in t["console_cpu"]["features"])), "MLFLAG=-fPIC",
       arr("GCC_RT_CONF", recipe.runtime_configure(pin)), arr("CFG_SUBDIRS", cfg["subdirs"]),
       "CFG_GUEST_LD=%s" % q(cfg["guest_script"]), "CFG_PROTOCOL_SRC=%s" % q(cfg["protocol_source"]),
       arr("RUNTIME_CFLAGS", recipe.runtime_cflags(pin)), arr("SEMANTICS", recipe.semantics_set(None)), arr("PLUGIN_ORDER", list(recipe.PLUGIN_SOURCES))]
want = recipe.plugin_args("native")
for n in recipe.PLUGIN_SOURCES:
    out.append(arr("PLUGIN_ARGV_" + n, ["-fplugin-arg-%s-%s%s" % (n, k, "=" + v if v else "") for k, v in want[n].items()]))
print("\n".join(out))
