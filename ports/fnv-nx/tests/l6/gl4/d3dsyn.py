"""d3dsyn.py: the synthetic D3D9 shaders of part q (hand-assembled, render/shaders/total/sm_hand.py) as a C header of word arrays."""
import struct

VS = {  # one vertex shader of every model class: position from v0, nothing else
    "vs_1_1": "vs_1_1\nmov oPos, v0\n",
    "vs_2_0": "vs_2_0\ndcl_position v0\nmov oPos, v0\n",
    "vs_2_x": "vs_2_x\ndcl_position v0\nmov oPos, v0\n",
    "vs_3_0": "vs_3_0\ndcl_position v0\ndcl_position o0\nmov o0, v0\n",
}
PS = {  # one pixel shader of every model class: c0
    "ps_1_1": "ps_1_1\nmov r0, c0\n", "ps_1_2": "ps_1_2\nmov r0, c0\n", "ps_1_3": "ps_1_3\nmov r0, c0\n", "ps_1_4": "ps_1_4\nmov r0, c0\n",
    "ps_2_0": "ps_2_0\nmov oC0, c0\n", "ps_2_x": "ps_2_x\nmov oC0, c0\n", "ps_3_0": "ps_3_0\nmov oC0, c0\n",
}
EXTRA = {  # variants / link sets: a PS reading TEXCOORD0 (canonical) and POSITION1 (not canonical), a VS writing TEXCOORD0
    "vs_t0": "vs_2_0\ndcl_position v0\nmov oPos, v0\nmov oT0, c0\n",
    "ps_t0": "ps_2_0\ndcl t0\nmov oC0, t0\n",
    "ps_c0": "ps_2_0\ndcl v0\nmov oC0, v0\n",
    "vs_col23": "vs_3_0\ndcl_position v0\ndcl_position o0\ndcl_color2 o1\ndcl_color3 o2\nmov o0, v0\nmov o1, c1\nmov o2, c2\n",
    "ps_col3": "ps_3_0\ndcl_color3 v0\nmov oC0, v0\n",
}


def words(b): return struct.unpack("<%dI" % (len(b) // 4), b)


def header(sm_hand, ops):
    out = ["/* generated by d3dsyn.py (part q): hand-assembled synthetic D3D9 shaders */"]
    names = []
    for group, stage in ((VS, 0), (PS, 1), (EXTRA, None)):
        for name, text in group.items():
            w = words(sm_hand.assemble(text, ops)); st = stage if stage is not None else (0 if name.startswith("vs") else 1)
            out.append("static const uint32_t D3D_%s[] = {%s};" % (name, ",".join("0x%x" % x for x in w))); names.append((name, st))
    out.append("typedef struct { const char* name; const uint32_t* w; uint32_t n; uint8_t stage; } TD3d;")
    out.append("static const TD3d k_d3d[] = {%s};" % ",".join('{"%s", D3D_%s, (uint32_t)(sizeof D3D_%s / 4), %d}' % (n, n, n, s) for n, s in names))
    return "\n".join(out) + "\n"
