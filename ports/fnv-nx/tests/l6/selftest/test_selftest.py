#!/usr/bin/env python3
"""test_selftest.py: the nxgpu v4.1 first-frame self test (render/gl4/selftest) over the GL backend.
  python3 -I tests/l6/selftest/test_selftest.py [--no-mutations]      (after: set -a; . /home/user/work/l6/ENV_READY; set +a)
 a  libnxgl4.so is built by build_gl4.sh; harness.c (a Linux host of nxgpu4_selftest.c) is linked against it
 b  an independent pure-Python rasterizer (exact integer arithmetic) gives the FNV-1a 64 of the scene for 1280x720 and 1920x1080
 c  the harness runs both sizes with the GLSL shaders through the GL shader-create path: 5 stages OK, the logged S3 and S4
    checksums equal the Python value, the on_present hook ran once per presented frame, no address outside an allocation was used
 d  selftest_expect.h is written (or checked) only after c agreed, so the header is never a measurement of the backend alone
 e  mutations: single-line breaks of the selftest, the shader, the checksum and the harness input, each must end in RESULT FAIL
 f  firstframe_main.c compiles with -Wall -Wextra -Werror (aarch64 gcc + libnx headers; compile only, the console run is the owner's)
The scene (S = H/24): triangle (2S,S) (10S,S) (2S,9S), uv (0,0) (2,0) (0,2), 4x4 point-sampled clamp texture
texel(x,y) = (40+50x, 40+50y, 255-16(4x+y), 255), clear 0xFF804020 (R in the low byte). A pixel is in the hash when its centre is
>= 1 px inside the triangle (texel = min(3, floor((c-origin)/S)) per axis) or >= 1 px outside it (clear colour); edge pixels are not hashed."""
import os, re, shutil, subprocess, sys, tempfile
sys.path.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")); import san; san.install()
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
BACK = os.path.join(ROOT, "render", "gl4"); NXB = os.path.normpath(os.path.join(BACK, "..", "backend")); ST = os.path.join(ROOT, "render", "gl4", "selftest")
SIZES = [(1280, 720), (1920, 1080)]
fails = []


def sh(cmd, **kw): return subprocess.run(cmd, capture_output=True, text=True, **kw)


def check(ok, what):
    if not ok: fails.append(what); print("FAIL: " + what)
    return ok


def model_fnv(W, H):
    """independent model: exact integer test of the pixel classes (doubled coordinates: centre = (2p+1)/2)"""
    S = H // 24; x0, y0 = 2 * S, S; f = 0xcbf29ce484222325
    clear = (0x20, 0x40, 0x80, 0xFF)
    for py in range(H):
        cy2 = 2 * py + 1
        for px in range(W):
            cx2 = 2 * px + 1
            t2 = 2 * (x0 + y0 + 8 * S) - cx2 - cy2            # 2*sqrt2*d3
            big = t2 * t2 >= 8                                 # |d3| >= 1
            e1, e2 = cy2 - 2 * y0, cx2 - 2 * x0                # 2*d1, 2*d2
            if e1 >= 2 and e2 >= 2 and t2 >= 0 and big:
                tx, ty = min(3, (cx2 - 2 * x0) // (2 * S)), min(3, (cy2 - 2 * y0) // (2 * S))
                c = ((40 + 50 * tx) & 255, (40 + 50 * ty) & 255, (255 - 16 * (4 * tx + ty)) & 255, 255)
            elif e1 <= -2 or e2 <= -2 or (t2 <= 0 and big): c = clear
            else: continue
            for b in c: f = ((f ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return f


def header(rows): return "/* generated by tests/l6/selftest/test_selftest.py from the independent model; do not edit */\n#define NXST_EXPECT_ROWS %s\n" % ", ".join("{%d,%d,0x%016xull}" % (w, h, v) for (w, h), v in rows)


def compile_harness(srcdir, exe, libdir, extra=()):
    return sh(["gcc", "-std=c11", "-Wall", "-Werror", "-O1", "-rdynamic", *san.flags(), "-I", srcdir, "-I", BACK, "-I", NXB, "-I", ST, os.path.join(HERE, "harness.c"), os.path.join(srcdir, "nxgpu4_selftest.c"),
               "-L", libdir, "-lnxgl4", "-Wl,-rpath," + libdir, "-lm", "-o", exe, *extra])


def run(exe, W, H, vs, fs, frames=3):
    r = sh([exe, str(W), str(H), vs, fs, str(frames)], env=san.env(dict(os.environ, LIBGL_ALWAYS_SOFTWARE="1", GALLIUM_DRIVER="llvmpipe", EGL_PLATFORM="surfaceless")), timeout=300)
    return r, r.stdout.strip().splitlines()[-1:] == ["RESULT PASS"]


def copy_sources(dst, hdr):
    os.makedirs(dst)
    for n in ("nxgpu4_selftest.c", "nxgpu4_selftest.h", "ff_vs.glsl", "ff_fs.glsl"): shutil.copy(os.path.join(ST, n), dst)
    open(os.path.join(dst, "selftest_expect.h"), "w").write(hdr)


MUTATIONS = [   # (name, file, old, new): every `old` must occur exactly once
    ("vertex y flipped", "nxgpu4_selftest.c", "1 - 2 * y0 / H, 0, 0,", "2 * y0 / H - 1, 0, 0,"),
    ("texel formula 51*y (only the checksum sees it)", "nxgpu4_selftest.c", "40 + 50 * y", "40 + 51 * y"),
    ("scene drawn over the other clear colour", "nxgpu4_selftest.c", "pass(s, s->rt, CLEAR_SCENE, 1)", "pass(s, s->rt, CLEAR_OTHER, 1)"),
    ("sampler wraps (repeat) instead of clamp", "nxgpu4_selftest.c", "NxWrap_Clamp | NxWrap_Clamp << 3 | NxWrap_Clamp << 6", "0"),
    ("viewport shifted by 2 px", "nxgpu4_selftest.c", "NxOp_Viewport, 6, fb(0), fb(0)", "NxOp_Viewport, 6, fb(2), fb(2)"),
    ("vertex stride 12", "nxgpu4_selftest.c", "48u, 16u)", "48u, 12u)"),
    ("only 2x2 texels uploaded", "nxgpu4_selftest.c", "0u, 0u, 0u, 0u, 4u, 4u, 1u", "0u, 0u, 0u, 0u, 2u, 2u, 1u"),
    ("the scene is not rendered into the present source", "nxgpu4_selftest.c", "|| pass(s, s->rt, CLEAR_SCENE, 1)) return 1;", ") return 1;"),
    ("fragment shader swizzles", "ff_fs.glsl", "texture(tex, v_uv)", "texture(tex, v_uv).bgra"),
    ("vertex shader drops the uv", "ff_vs.glsl", "v_uv = uv;", "v_uv = vec2(0.0);"),
    ("wrong expected checksum", "selftest_expect.h", "{1280,720,0x0", "{1280,720,0x1"),
    ("no present frames", None, None, None),
]


def mutate(tmp, lib, i, m, hdr):
    name, f, old, new = m
    d = os.path.join(tmp, "m%d" % i); copy_sources(d, hdr)
    frames = 3
    if f is None: frames = 0
    else:
        p = os.path.join(d, f); t = open(p).read()
        if t.count(old) != 1: return check(False, "mutation '%s': the text to break occurs %d times" % (name, t.count(old)))
        open(p, "w").write(t.replace(old, new, 1))
    exe = os.path.join(d, "h")
    r = compile_harness(d, exe, lib)
    if r.returncode: return check(False, "mutation '%s' does not compile: %s" % (name, r.stderr[-400:]))
    r, ok = run(exe, 1280, 720, os.path.join(d, "ff_vs.glsl"), os.path.join(d, "ff_fs.glsl"), frames)
    return check(not ok and "RESULT FAIL" in r.stdout, "mutation '%s' was not caught" % name)


def compile_only():
    dkp = os.environ.get("DEVKITPRO") or os.path.join(os.environ.get("FNVNX_TC", "/nonexistent"), "..", "dkp")
    gcc = shutil.which("aarch64-none-elf-gcc") or os.path.join(os.environ.get("FNVNX_TC", "/nonexistent"), "bin", "aarch64-none-elf-gcc")
    if not check(os.path.isfile(gcc) and os.path.isdir(os.path.join(dkp, "libnx", "include")), "compile check: need aarch64-none-elf-gcc (PATH or FNVNX_TC/bin) and libnx headers (DEVKITPRO or FNVNX_TC/../dkp)"): return
    r = sh([gcc, "-march=armv8-a+crc+crypto", "-mtp=soft", "-fPIE", "-O2", "-Wall", "-Wextra", "-Werror", "-D__SWITCH__", '-DFNV_BUILD_ID="test"', "-I", ST, "-I", BACK, "-I", NXB,
            "-I", os.path.join(dkp, "libnx", "include"), "-c", os.path.join(ST, "firstframe_main.c"), "-o", os.devnull])
    check(r.returncode == 0, "firstframe_main.c does not compile with -Wall -Wextra -Werror (%s): %s" % (gcc, r.stderr[-1200:]))
    print("compile check: %s" % gcc)
    n = len(open(os.path.join(ST, "firstframe_main.c")).read().splitlines()); check(n <= 200, "firstframe_main.c has %d lines (> 200)" % n)
    n = len(open(os.path.join(ST, "nxgpu4_selftest.c")).read().splitlines()); check(n <= 300, "nxgpu4_selftest.c has %d lines (> 300)" % n)


def main():
    mut = "--no-mutations" not in sys.argv[1:]
    tmp = tempfile.mkdtemp(prefix="selftest_")
    try:
        lib = os.path.join(tmp, "lib"); os.makedirs(lib)
        r = sh(["sh", os.path.join(BACK, "build_gl4.sh"), os.path.join(lib, "libnxgl4.so")])
        if not check(r.returncode == 0, "build_gl4.sh failed: " + r.stderr[-800:]): return
        rows = [((w, h), model_fnv(w, h)) for w, h in SIZES]
        for (w, h), v in rows: print("model %dx%d fnv=%016x" % (w, h, v))
        hdr = header(rows); cand = os.path.join(tmp, "cand"); copy_sources(cand, hdr)
        exe = os.path.join(cand, "h"); r = compile_harness(cand, exe, lib)
        if not check(r.returncode == 0, "harness does not compile: " + r.stderr[-800:]): return
        agreed = True
        for (w, h), v in rows:
            r, ok = run(exe, w, h, os.path.join(ST, "ff_vs.glsl"), os.path.join(ST, "ff_fs.glsl"), 3)
            logged = re.findall(r"^(S[34]) fnv=([0-9a-f]{16}) ", r.stdout, re.M)
            good = ok and len(re.findall(r"^STAGE \d \w+ OK rc=0$", r.stdout, re.M)) == 5 and len(logged) == 2 and all(int(x, 16) == v for _, x in logged) and "PRESENT_HOOK calls=3 expected=3" in r.stdout
            agreed &= check(good, "%dx%d: GL run does not match the model:\n%s%s" % (w, h, r.stdout[-700:], r.stderr[-300:]))
            print("%dx%d: %s  S3/S4 fnv %s" % (w, h, "PASS" if good else "FAIL", ",".join(x for _, x in logged)))
        dst = os.path.join(ST, "selftest_expect.h")
        if agreed:
            if not os.path.exists(dst) or open(dst).read() != hdr: open(dst, "w").write(hdr); print("wrote " + dst)
        if mut and agreed:
            for i, m in enumerate(MUTATIONS):
                if mutate(tmp, lib, i, m, hdr): print("mutation caught: " + m[0])
        compile_only()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


main()
if fails: print("%d FAILED" % len(fails)); sys.exit(1)
print("ALL OK")
