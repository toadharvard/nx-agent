#!/usr/bin/env python3
"""test_selftest.py: the independent model of the nxgpu v4.1 first-frame self test (render/d3d9/backend/selftest).
  python3 -I tests/l6/selftest/test_selftest.py [--no-mutations]
 a  an independent pure-Python rasterizer (exact integer arithmetic) gives the FNV-1a 64 of the scene for 1280x720 and 1920x1080
 b  selftest_expect.h equals the header written from that model (the header is never a measurement of a backend)
 c  firstframe_main.c compiles with -Wall -Wextra -Werror (aarch64 gcc + libnx headers; compile only, the console run is the owner's)
The backend run of the self test (deko3d) is the L4 boot machine's job. Regenerate the header: --write.
The scene (S = H/24): triangle (2S,S) (10S,S) (2S,9S), uv (0,0) (2,0) (0,2), 4x4 point-sampled clamp texture
texel(x,y) = (40+50x, 40+50y, 255-16(4x+y), 255), clear 0xFF804020 (R in the low byte). A pixel is in the hash when its centre is
>= 1 px inside the triangle (texel = min(3, floor((c-origin)/S)) per axis) or >= 1 px outside it (clear colour); edge pixels are not hashed."""
import os, shutil, subprocess, sys
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
BACK = os.path.join(ROOT, "render", "d3d9", "backend"); ST = os.path.join(BACK, "selftest")
SIZES = [(1280, 720), (1920, 1080)]
fails = []


def sh(cmd, **kw): return subprocess.run(cmd, capture_output=True, text=True, **kw)


def check(ok, what):
    if not ok: fails.append(what); print("FAIL: " + what)
    return ok


def model_fnv(W, H):
    """independent model: exact integer test of the pixel classes (doubled coordinates: centre = (2p+1)/2)"""
    S = H // 24; x0, y0 = 2 * S, S; f = 0xcbf29ce484222325
    clear = (0x20, 0x40, 0x80, 0xFF)
    for py in range(H):
        cy2 = 2 * py + 1
        for px in range(W):
            cx2 = 2 * px + 1
            t2 = 2 * (x0 + y0 + 8 * S) - cx2 - cy2            # 2*sqrt2*d3
            big = t2 * t2 >= 8                                 # |d3| >= 1
            e1, e2 = cy2 - 2 * y0, cx2 - 2 * x0                # 2*d1, 2*d2
            if e1 >= 2 and e2 >= 2 and t2 >= 0 and big:
                tx, ty = min(3, (cx2 - 2 * x0) // (2 * S)), min(3, (cy2 - 2 * y0) // (2 * S))
                c = ((40 + 50 * tx) & 255, (40 + 50 * ty) & 255, (255 - 16 * (4 * tx + ty)) & 255, 255)
            elif e1 <= -2 or e2 <= -2 or (t2 <= 0 and big): c = clear
            else: continue
            for b in c: f = ((f ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return f


def header(rows): return "/* generated by tests/l6/selftest/test_selftest.py from the independent model; do not edit */\n#define NXST_EXPECT_ROWS %s\n" % ", ".join("{%d,%d,0x%016xull}" % (w, h, v) for (w, h), v in rows)


def header(rows): return "/* generated by tests/l6/selftest/test_selftest.py from the independent model; do not edit */\n#define NXST_EXPECT_ROWS %s\n" % ", ".join("{%d,%d,0x%016xull}" % (w, h, v) for (w, h), v in rows)


def compile_only():
    dkp = os.environ.get("DEVKITPRO") or os.path.join(os.environ.get("FNVNX_TC", "/nonexistent"), "..", "dkp")
    gcc = shutil.which("aarch64-none-elf-gcc") or os.path.join(os.environ.get("FNVNX_TC", "/nonexistent"), "bin", "aarch64-none-elf-gcc")
    if not check(os.path.isfile(gcc) and os.path.isdir(os.path.join(dkp, "libnx", "include")), "compile check: need aarch64-none-elf-gcc (PATH or FNVNX_TC/bin) and libnx headers (DEVKITPRO or FNVNX_TC/../dkp)"): return
    r = sh([gcc, "-march=armv8-a+crc+crypto", "-mtp=soft", "-fPIE", "-O2", "-Wall", "-Wextra", "-Werror", "-D__SWITCH__", '-DFNV_BUILD_ID="test"', "-I", ST, "-I", BACK,
            "-I", os.path.join(dkp, "libnx", "include"), "-c", os.path.join(ST, "firstframe_main.c"), "-o", os.devnull])
    check(r.returncode == 0, "firstframe_main.c does not compile with -Wall -Wextra -Werror (%s): %s" % (gcc, r.stderr[-1200:]))
    print("compile check: %s" % gcc)
    n = len(open(os.path.join(ST, "firstframe_main.c")).read().splitlines()); check(n <= 200, "firstframe_main.c has %d lines (> 200)" % n)
    n = len(open(os.path.join(ST, "nxgpu4_selftest.c")).read().splitlines()); check(n <= 300, "nxgpu4_selftest.c has %d lines (> 300)" % n)


def main():
    rows = [((w, h), model_fnv(w, h)) for w, h in SIZES]
    for (w, h), v in rows: print("model %dx%d fnv=%016x" % (w, h, v))
    hd = header(rows); dst = os.path.join(ST, "selftest_expect.h")
    if "--write" in sys.argv[1:]: open(dst, "w").write(hd); print("wrote " + dst)
    check(open(dst).read() == hd, "selftest_expect.h differs from the model")
    compile_only()


main()
if fails: print("%d FAILED" % len(fails)); sys.exit(1)
print("ALL OK")
