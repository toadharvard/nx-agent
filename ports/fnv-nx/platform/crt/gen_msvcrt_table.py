#!/usr/bin/env python3
"""Generate the msvcrt lookup table from msvcrt_names.tsv (name TAB symbol TAB func|data).

  gen_msvcrt_table.py msvcrt_names.tsv out.cpp      (run with python3 -I)

The generated translation unit holds fnvnx_msvcrt_lookup, the hook fnvnx_win32_lookup_export calls for the dll "msvcrt". Every symbol is bound
opaquely, under a private C++ name with an asm label (`extern char fnvnx_msvcrt_sym_<n>[] __asm__("symbol");`), so that this unit never declares a
name that a header declares (no second, wrong-typed declaration of any shim header's name: the class is closed by construction) and only the link
ties a row to a body: the gate `imports` proves that body in the symbol tables of the product objects. A name twice, a symbol that is not a C identifier or a kind other than func|data is an error (exit 2)."""
import re
import os
import sys

KINDS = ("func", "data")


def read(text):
    rows, seen = [], set()
    lines = text.split("\n")
    if lines[0] != "name\tsymbol\tkind":
        raise ValueError("bad header")
    for i, ln in enumerate(lines[1:], 2):
        if not ln:
            continue
        f = ln.split("\t")
        if len(f) != 3 or not f[0] or f[2] not in KINDS or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", f[1]):
            raise ValueError("line %d: bad row" % i)
        if f[0] in seen:
            raise ValueError("line %d: name %s twice" % (i, f[0]))
        seen.add(f[0])
        rows.append(f)
    return rows


def generate(rows):
    kind = {}
    for _, sym, k in rows:
        if kind.setdefault(sym, k) != k:
            raise ValueError("symbol %s has two kinds" % sym)
    out = ["/* generated by gen_msvcrt_table.py from msvcrt_names.tsv: do not edit */"]
    alias = {sym: "fnvnx_msvcrt_sym_%d" % i for i, sym in enumerate(sorted(kind))}
    for sym in sorted(kind):
        out.append('extern char %s[] __asm__("%s");' % (alias[sym], sym))
    out += ["", "namespace {", "struct row { const char *name; void *fn; };", "const row g_rows[] = {"]
    for n, sym, _ in rows:
        out.append('    { "%s", (void *)%s },' % (n, alias[sym]))
    out += ["};", "}", "",
            "/* the hook fnvnx_win32_lookup_export calls for the dll \"msvcrt\": NULL when the name is not provided here */",
            'extern "C" void *fnvnx_msvcrt_lookup(const char *name)', "{", "    for (const row &r : g_rows)",
            "        if (!__builtin_strcmp(r.name, name))", "            return r.fn;", "    return 0;", "}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    try:
        txt = generate(read(open(sys.argv[1]).read()))
    except (ValueError, OSError, IndexError) as e:
        print("gen_msvcrt_table: %s" % e, file=sys.stderr)
        sys.exit(2)
    os.makedirs(os.path.dirname(os.path.abspath(sys.argv[2])), exist_ok=True)
    open(sys.argv[2], "w").write(txt)
