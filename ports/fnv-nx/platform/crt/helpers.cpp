/* helpers.cpp - MSVC compiler helpers that the decomp source calls by name (see docs/RUNTIME.md):
 * security cookie check, `eh vector constructor/destructor/copy constructor iterator', __RTDynamicCast,
 * _CxxThrowException, and the MSVC C++ library internals std::_Lockit, std::_Xlen, std::_Xran.
 * Helpers the compiler emits implicitly (_ftol2 on casts, _allmul, _alloca_probe, _CIsin, EH handlers, ...)
 * have no counterpart here: GCC generates its own code for those. */
#include "fnvnx_msvcrt.h"

#include <cxxabi.h>
#include <stdlib.h>
#include <exception>
#include <stdexcept>
#include <typeinfo>

#include "../os/os.h"

extern "C" void fnvnx_security_check_cookie(uintptr_t cookie)
{
    (void)cookie; /* /GS frames are not reproduced by GCC; there is nothing to compare against */
}

/* `eh vector constructor iterator'(ptr, size, count, ctor, dtor): constructs count objects; if one throws,
 * destroys the ones already built in reverse order and rethrows. */
extern "C" void fnvnx_eh_vector_ctor(void *ptr, size_t size, int count, void (*ctor)(void *), void (*dtor)(void *))
{
    int i = 0;
    try {
        for (; i < count; i++)
            ctor((char *)ptr + (size_t)i * size);
    } catch (...) {
        if (dtor)
            while (i-- > 0)
                dtor((char *)ptr + (size_t)i * size);
        throw;
    }
}

/* `eh vector destructor iterator'(ptr, size, count, dtor): destroys from the last element to the first */
extern "C" void fnvnx_eh_vector_dtor(void *ptr, size_t size, int count, void (*dtor)(void *))
{
    for (int i = count; i-- > 0;)
        dtor((char *)ptr + (size_t)i * size);
}

extern "C" void fnvnx_eh_vector_copy_ctor(void *dst, void *src, size_t size, int count, void (*cctor)(void *, void *),
                                          void (*dtor)(void *))
{
    int i = 0;
    try {
        for (; i < count; i++)
            cctor((char *)dst + (size_t)i * size, (char *)src + (size_t)i * size);
    } catch (...) {
        if (dtor)
            while (i-- > 0)
                dtor((char *)dst + (size_t)i * size);
        throw;
    }
}

/* ---- __RTDynamicCast through GCC RTTI. The decomp passes the addresses of MSVC TypeDescriptors (in the data
 * image); the classes themselves are compiled by GCC with Itanium RTTI, so each descriptor is mapped to the
 * GCC type_info of the same class (table generated by S2 from the ??_R0 names). */
namespace {
struct rtti_entry { const void *td; const std::type_info *ti; };
rtti_entry *g_rtti;
size_t g_nrtti, g_caprtti;
os_lock_t g_rtti_lock;

const std::type_info *rtti_lookup(const void *td)
{
    const std::type_info *r = nullptr;
    os_lock(&g_rtti_lock);
    for (size_t i = 0; i < g_nrtti; i++)
        if (g_rtti[i].td == td) {
            r = g_rtti[i].ti;
            break;
        }
    os_unlock(&g_rtti_lock);
    return r;
}
} // namespace

void fnvnx_rtti_register(const void *td, const std::type_info *ti)
{
    os_lock(&g_rtti_lock);
    if (g_nrtti == g_caprtti) {
        size_t cap = g_caprtti ? g_caprtti * 2 : 256;
        rtti_entry *n = (rtti_entry *)realloc(g_rtti, cap * sizeof *n);
        if (!n) {
            os_unlock(&g_rtti_lock);
            os_fatal("out of memory in fnvnx_rtti_register");
        }
        g_rtti = n;
        g_caprtti = cap;
    }
    g_rtti[g_nrtti].td = td;
    g_rtti[g_nrtti].ti = ti;
    g_nrtti++;
    os_unlock(&g_rtti_lock);
}

extern "C" void *fnvnx_rt_dynamic_cast(void *inptr, long vfdelta, void *src_type, void *target_type, int is_reference)
{
    (void)vfdelta; /* GCC objects keep the vptr at offset 0 of each polymorphic subobject */
    if (!inptr)
        return nullptr;
    const std::type_info *s = rtti_lookup(src_type), *t = rtti_lookup(target_type);
    void *r = nullptr;
    if (s && t) {
        const abi::__class_type_info *cs = dynamic_cast<const abi::__class_type_info *>(s);
        const abi::__class_type_info *ct = dynamic_cast<const abi::__class_type_info *>(t);
        if (cs && ct)
            r = abi::__dynamic_cast(inptr, cs, ct, -1);
    } else {
        static int warned;
        if (warned++ < 8)
            os_debug_print("[fnvnx] __RTDynamicCast: type descriptor not registered, cast fails");
    }
    if (!r && is_reference)
        throw std::bad_cast();
    return r;
}

/* ---- _CxxThrowException(obj, ThrowInfo): obj == NULL is "throw;" */
extern "C" void fnvnx_cxx_throw_exception(void *obj, void *throw_info)
{
    if (!obj) {
        std::exception_ptr p = std::current_exception();
        if (p)
            std::rethrow_exception(p);
        std::terminate();
    }
    throw fnvnx_msvc_exception{ obj, throw_info };
}

/* ---- std::_Lockit: the MSVC library's global recursive locks, indexed by kind (0..7 in VC9) */
namespace {
struct rlock { os_lock_t l; volatile uint32_t owner; int depth; };
rlock g_lockit[8];
uint32_t self_token()
{
    static __thread uint32_t tok;
    static volatile uint32_t next = 1;
    if (!tok)
        tok = __atomic_fetch_add(&next, 1, __ATOMIC_RELAXED);
    return tok;
}
} // namespace

extern "C" void fnvnx_lockit_ctor(void *self, int kind)
{
    unsigned k = (unsigned)kind & 7;
    *(int *)self = (int)k;
    rlock &r = g_lockit[k];
    uint32_t me = self_token();
    if (__atomic_load_n(&r.owner, __ATOMIC_RELAXED) == me) {
        r.depth++;
        return;
    }
    os_lock(&r.l);
    __atomic_store_n(&r.owner, me, __ATOMIC_RELAXED);
    r.depth = 1;
}

extern "C" void fnvnx_lockit_dtor(void *self)
{
    rlock &r = g_lockit[(unsigned)*(int *)self & 7];
    if (--r.depth == 0) {
        __atomic_store_n(&r.owner, 0u, __ATOMIC_RELAXED);
        os_unlock(&r.l);
    }
}

