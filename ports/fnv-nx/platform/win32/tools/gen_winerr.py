#!/usr/bin/env python3
"""gen_winerr.py - generates platform/win32/winerr_msgs.inc (the system message table of FormatMessageA).

    python3 platform/win32/tools/gen_winerr.py <winerror.mc> <out.inc>

<winerror.mc> is Wine 9.0's dlls/kernelbase/winerror.mc (English message table of the reference environment,
LGPL-2.1-or-later; not part of this repository; mirror: fnv-nx-build tools/mc). Output: g_sysmsg_ids (ascending message
ids), g_sysmsg_off (offsets into g_sysmsg_text) and the text blob; each message ends in "\\r\\n" as a message-table
resource entry does. Python 3 standard library only."""
import re
import sys

FACILITY = {"Null": 0, "Dxgi": 0x87A}   # Null is the compiler's default facility; Dxgi is the DXGI facility code
SEVERITY = {"Success": 0, "Informational": 1, "Warning": 2, "Error": 3}


def main():
    src, out = sys.argv[1], sys.argv[2]
    sev_names = dict(SEVERITY)
    fac_names = dict(FACILITY)
    msgs = {}
    cur = {}
    sev = fac = 0
    text = None
    for raw in open(src, encoding="latin-1").read().split("\n"):
        line = raw.rstrip("\r")
        if text is not None:
            if line == ".":
                if cur["id"] in msgs:
                    raise SystemExit("duplicate message id %#x" % cur["id"])
                msgs[cur["id"]] = "".join(t + "\r\n" for t in text)
                text = None
            else:
                text.append(line)
            continue
        if not line or line.startswith(";"):
            continue
        m = re.match(r"(\w+)=(.*)$", line)
        if not m:
            raise SystemExit("unparsed line: " + line)
        k, v = m.group(1), m.group(2).strip()
        if k == "SeverityNames" or k == "FacilityNames":
            for nm, val in re.findall(r"(\w+)=(0x[0-9a-fA-F]+|\d+)", v):
                (sev_names if k == "SeverityNames" else fac_names)[nm] = int(val, 0)
        elif k == "LanguageNames":
            pass
        elif k == "MessageId":
            cur = {"code": int(v, 0)}
        elif k == "Severity":
            sev = sev_names[v]
        elif k == "Facility":
            fac = fac_names[v]
        elif k == "SymbolicName":
            pass
        elif k == "Language":
            if v != "ENU":
                raise SystemExit("unexpected language " + v)
            # id = severity(2 bits) | facility(12 bits) | code(16 bits); the customer bit stays clear
            cur["id"] = ((sev & 3) << 30) | ((fac & 0xFFF) << 16) | cur["code"]
            text = []
        else:
            raise SystemExit("unknown keyword " + k)
    ids = sorted(msgs)
    blob = bytearray()
    offs = []
    for i in ids:
        offs.append(len(blob))
        blob += msgs[i].encode("latin-1") + b"\0"
    o = ["/* generated by tools/gen_winerr.py from winerror.mc - do not edit */",
         "static const uint32_t g_sysmsg_ids[%d] = {" % len(ids)]
    o += [",".join("0x%x" % v for v in ids[j:j + 8]) + "," for j in range(0, len(ids), 8)]
    o += ["};", "static const uint32_t g_sysmsg_off[%d] = {" % len(ids)]
    o += [",".join(str(v) for v in offs[j:j + 12]) + "," for j in range(0, len(offs), 12)]
    o += ["};", "static const char g_sysmsg_text[%d] = {" % len(blob)]
    o += [",".join(str(b) for b in blob[j:j + 24]) + "," for j in range(0, len(blob), 24)]
    o += ["};", ""]
    open(out, "w").write("\n".join(o))


main()
