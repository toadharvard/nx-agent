/* w32_reach.h - the one place the platform ends in a branch that the reachability gate proves unreachable
 * (contract/include/fnvnx/reach.h has the contract; manifest/reach_requests.tsv the facts this layer asks for).
 * A caller passes a fact of reach_facts.h; it holds no lock and has released what it allocated: the call does not return
 * (platstat.cpp ends the process through the host's exit; the host tests observe it in a child process, tests/s4/host_boundary.cpp). */
#ifndef FNVNX_PLATFORM_WIN32_W32_REACH_H
#define FNVNX_PLATFORM_WIN32_W32_REACH_H
#include <fnvnx/reach.h>
#include "reach_facts.h"   /* generated by contract/gate_reach.py (table-only mode) from manifest/reach_requests.tsv */

static inline __attribute__((noreturn)) void w32_reach(uint32_t fact) { fnvnx_reach_violation(fact); }

/* The reason a caller found for a proven-unreachable branch. The fact id of a call of fnvnx_reach_violation must be a literal at the call (the reach gate
 * reads it there): code that learns the reason first and ends later carries a reason (one enumerator per fact it can name), and w32_reach_if ends in the
 * literal of that fact. W32R_NONE: no violation, w32_reach_if returns. */
enum w32_reach_kind { W32R_NONE = 0, W32R_CFM_HFILE, W32R_CFM_PROT, W32R_CFM_WRITER };

static inline void w32_reach_if(enum w32_reach_kind k)
{
    if (k == W32R_CFM_HFILE)
        w32_reach(FNVNX_REACH_KERNEL32_CreateFileMappingA_HFILE);
    if (k == W32R_CFM_PROT)
        w32_reach(FNVNX_REACH_KERNEL32_CreateFileMappingA_PROT);
    if (k == W32R_CFM_WRITER)
        w32_reach(FNVNX_REACH_KERNEL32_CreateFileMappingA_WRITER);
}
#endif
