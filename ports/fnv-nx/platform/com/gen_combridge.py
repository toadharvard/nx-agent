#!/usr/bin/env python3
"""gen_combridge.py SPEC OUTDIR: the COM bridge of the platform's objects, generated from the interface table (nothing per method).

Same model as the Direct3D 9 bridge of the render lead (render/d3d9/gen/gen_bridge.py, dev/face.h): the game holds a "face" whose
first word is the key table of the interface; the key of slot s is the import key of the thunk nxb_<Interface>_<Method> (dll
`!<Interface>`, name = method, ordinal = slot); the thunk takes the x86 stack words in order (this = the face first), converts the
interface pointers at the boundary in both directions and calls the C++ method. Copied rather than parameterised because that script
is welded to the d3d9 generator (gen_impl, gen_expr, NxObj with the face in front of every object: our objects are plain C++ classes,
so faces here are records per (object, interface), platform/com/combridge.h); the vocabulary of spec and rows is theirs.

  OUTDIR/combridge_rows.tsv   rows of the bridge table (bridge.tsv format, 8 TAB columns, no header): one per method of every
                              non-hidden interface (dll `!<Interface>`, name, ordinal = slot, stdcall, ret v|i, args = slot
                              letters with the `this` first, native symbol nxb_<Interface>_<Method>, bind sym) and one per export
                              (dll, name, ordinal, stdcall, ret, args, nxb_<Export>, sym): the row REPLACES the base row of that export.
  OUTDIR/combridge.gen.cpp    the thunks, the proxy classes of the game's objects, the interface / IID / key tables, and the checks of
                              the spec against the C++ declarations (static_asserts and nxcom::selfcheck).

Spec kinds (the vocabulary of d3d9_spec.json, plus the two this bridge needs):
  value | flags | enum   one 32-bit word `i` (a scalar, a handle value, or a guest address typed by a pointer typedef): word<T>
  float f | double d | int64 q      their own slot classes (a float is one word, a double and an int64 take two stack words)
  struct byref           a pointer to the struct (`i`); REFIID / REFGUID (a C++ reference) are dereferenced
  buffer + members       a struct the callee fills that carries interface pointers (PIN_INFO.pFilter, FILTER_INFO.pGraph): each member
                         is converted like an out handle (face / the game's own pointer)
  struct by value        size/4 words `i` (a GUID passed by value, IFilterMapper)
  buffer                 a guest address `i`, passed on as typed
  handle                 an interface pointer of an object the platform implements.  in: a pointer from the game (the face of a platform
                         object, else a game object: proxied); out (byref): the method stores one, the thunk replaces it by its face
  giface                 the same conversions; documents that a game-implemented object is expected here (DirectShow filters, pins)
  callback               a game code address `i`, handed to the C++ method as its fnvnx_guestfn typedef
  handle_array           (Next of an enumerator) an array of interface pointers the method fills, count from `count` = [n, fetched]
  iface "$param"         the interface of an out handle is the one the IID passed in `param` names (QueryInterface); an IID that is not
                         an interface of this spec is not implemented: the object is released and E_NOINTERFACE returned
A spec item without a rule stops the generator (exit 2). The spec's own claims are checked by the C++ compiler (static_assert on the
method's type, on the word class of every argument) and by nxcom::selfcheck (the slot number of every method, probed in the
compiler's vtable layout)."""
import json, os, re, sys

HEAD = '''// generated by gen_combridge.py from com_spec.json; do not edit
'''
E_NOINTERFACE, E_POINTER, E_OUTOFMEMORY = "0x80004002u", "0x80004003u", "0x8007000Eu"


def die(msg):
    sys.stderr.write("gen_combridge: " + msg + "\n")
    sys.exit(2)


def words_of(p, what):
    """the x86 stack words of a parameter: list of letters"""
    k = p["kind"]
    if k in ("value", "flags", "enum", "buffer", "callback", "handle", "giface", "handle_array"):
        return ["i"]
    if k == "struct":
        if p["byref"]:
            return ["i"]
        if p["size"] % 4:
            die(f"{what}: struct {p['name']} by value of {p['size']} bytes has no rule")
        return ["i"] * (p["size"] // 4)
    if k == "float":
        return ["f"]
    if k == "double":
        return ["d"]
    if k == "int64":
        return ["q"]
    die(f"{what}: kind {k} has no rule")


def ret_letter(what, m):
    rk = m["ret_kind"]
    if rk == "void":
        return "v"
    if rk in ("hresult", "value"):
        return "i"
    die(f"{what}: return kind {rk} has no rule")


FAMILY = {"ds": 1, "di": 1, "dsh": 2}


class Gen:
    def __init__(self, spec):
        self.spec = spec
        self.names = sorted(spec["interfaces"])
        self.ix = {n: i for i, n in enumerate(self.names)}
        self.by = {}
        for m in spec["methods"]:
            self.by.setdefault(m["iface"], []).append(m)
        for n in self.names:
            ms = sorted(self.by.get(n, []), key=lambda m: m["slot"])
            self.by[n] = ms
            if [m["slot"] for m in ms] != list(range(spec["interfaces"][n]["slots"])):
                die(f"{n}: methods do not cover slots 0..{spec['interfaces'][n]['slots'] - 1}")
        off = 0
        self.keyoff = {}
        for n in self.names:
            self.keyoff[n] = off
            if not spec["interfaces"][n]["hidden"]:
                off += spec["interfaces"][n]["slots"]
        self.nkeys = off

    # ---- how the IID a `$param` names is read: GUID layout (reference / const GUID *) or the raw 16 bytes
    def canon(self, params, pname, var_of, what):
        for k, p in enumerate(params):
            if p["name"] == pname:
                v = var_of(k)
                if p["ctype"] in ("REFIID", "REFGUID", "REFCLSID"):
                    return f"nxcom_canon_guid((const ::GUID *){v}, c)" if var_of.raw else f"nxcom_canon_guid(&{v}, c)"
                if "GUID" in p["ctype"] and "Guid" not in p["ctype"]:
                    return f"nxcom_canon_guid((const ::GUID *){v}, c)" if var_of.raw else f"nxcom_canon_guid({v}, c)"
                return f"nxcom_canon_raw((const void *){v}, c)"
        die(f"{what}: iface ${pname} names no parameter")

    # ---- a thunk: game -> platform
    def thunk(self, what, sym, m, callee, this_if):
        fam = FAMILY[self.spec["interfaces"][this_if]["family"]] if this_if else 0
        P = m["params"]
        decl, args, pre, post = [], [], [], []
        letters = ["i"] if this_if else []
        if this_if:
            decl.append("uintptr_t t")
        nin = 0

        class V:
            raw = True

            def __call__(s, k):
                return f"a{k}"
        var_of = V()
        for k, p in enumerate(P):
            ws = words_of(p, what)
            letters += ws
            kd, ct, a = p["kind"], p["ctype"], f"a{k}"
            if kd in ("float",):
                decl.append(f"float {a}")
                pre.append(f"static_assert(std::is_same<std::remove_cv<{ct}>::type, float>::value, \"{what}: {p['name']} is not a float\");")
                args.append(a)
                continue
            if kd == "double":
                decl.append(f"double {a}")
                pre.append(f"static_assert(std::is_same<std::remove_cv<{ct}>::type, double>::value, \"{what}: {p['name']} is not a double\");")
                args.append(a)
                continue
            if kd == "int64":
                decl.append(f"uint64_t {a}")
                pre.append(f"static_assert(sizeof({ct}) == 8 && std::is_integral<{ct}>::value, \"{what}: {p['name']} is not a 64-bit integer\");")
                args.append(f"({ct}){a}")
                continue
            if kd == "struct" and not p["byref"]:
                n = p["size"] // 4
                for j in range(n):
                    decl.append(f"uintptr_t {a}_{j}")
                pre.append(f"static_assert(sizeof({ct}) == {p['size']}, \"{what}: {p['name']} size\");")
                pre.append(f"{ct} v{k}; {{ uint32_t w[{n}] = {{" + ", ".join(f"(uint32_t){a}_{j}" for j in range(n)) + f"}}; memcpy(&v{k}, w, {p['size']}); }}")
                args.append(f"v{k}")
                continue
            decl.append(f"uintptr_t {a}")
            if kd == "struct":   # by reference
                if ct in ("REFIID", "REFGUID", "REFCLSID"):
                    args.append(f"*(const ::GUID *){a}")
                else:
                    args.append(f"({ct}){a}")
            elif kd in ("value", "flags", "enum"):
                pre.append(f"static_assert(std::is_integral<{ct}>::value || std::is_pointer<{ct}>::value || std::is_enum<{ct}>::value, \"{what}: {p['name']} is not a word\");")
                args.append(f"nxcom::word<{ct}>({a})")
            elif kd == "buffer":
                pre.append(f"static_assert(std::is_pointer<{ct}>::value, \"{what}: {p['name']} is not a pointer\");")
                args.append(f"({ct}){a}")
                for mem in p.get("members", []):   # a struct the method fills with interface pointers: each becomes a face
                    if m["ret_kind"] != "hresult" or mem["iface"] not in self.ix:
                        die(f"{what}: struct member {mem['name']} has no rule")
                    pre.append(f"if ({a}) (({p['struct']} *){a})->{mem['name']} = nullptr;")
                    post.append(f"if ({a}) (({p['struct']} *){a})->{mem['name']} = (int32_t)r >= 0 ? nxcom::to_game((void *)(({p['struct']} *){a})->{mem['name']}, NXIF_{mem['iface']}) : nullptr;")
            elif kd == "callback":
                args.append(f"{ct}((uintptr_t){a})")
            elif kd in ("handle", "giface") and not p["byref"]:
                if p["dir"] != "in":
                    die(f"{what}: handle {p['name']} by value with dir {p['dir']} has no rule")
                if p["iface"] not in self.ix:
                    die(f"{what}: interface {p['iface']} of {p['name']} is not in the spec")
                nin += 1
                args.append(f"({ct})nxcom::from_game((const void *){a}, NXIF_{p['iface']})")
            elif kd in ("handle", "giface"):
                if p["dir"] != "out" or m["ret_kind"] != "hresult":
                    die(f"{what}: handle {p['name']} by reference needs dir out and an HRESULT method")
                pre.append(f"if ({a}) *(void **){a} = nullptr;   /* an out pointer the method does not write stays null */")
                args.append(f"({ct}){a}")
                ifc = p["iface"]
                if ifc.startswith("$"):
                    cexp = self.canon(P, ifc[1:], var_of, what)
                    post.append(f"if ({a} && *(void **){a}) {{ void *p_ = *(void **){a}; uint8_t c[16]; {cexp}; int ix = nxcom::iface_for_iid(c, {fam});\n"
                                f"        if ((int32_t)r >= 0 && ix >= 0) *(void **){a} = nxcom::to_game(p_, (unsigned)ix);\n"
                                f"        else {{ if ((int32_t)r >= 0) {{ ((::IUnknown *)p_)->Release(); r = ({m['ret']}){E_NOINTERFACE}; }} *(void **){a} = nullptr; }} }}")
                else:
                    if ifc not in self.ix:
                        die(f"{what}: interface {ifc} of {p['name']} is not in the spec")
                    post.append(f"if ({a}) *(void **){a} = (int32_t)r >= 0 ? nxcom::to_game(*(void **){a}, NXIF_{ifc}) : nullptr;")
            elif kd == "handle_array":
                if p["dir"] != "out" or m["ret_kind"] != "hresult" or len(p.get("count", [])) != 2:
                    die(f"{what}: handle_array {p['name']} shape has no rule")
                names = [q["name"] for q in P]
                ni, fi = (names.index(p["count"][0]), names.index(p["count"][1]))
                if p["iface"] not in self.ix:
                    die(f"{what}: interface {p['iface']} of {p['name']} is not in the spec")
                args.append(f"({ct}){a}")
                post.append(f"if ((int32_t)r >= 0 && {a}) {{ uint32_t cnt = a{fi} ? *(uint32_t *)a{fi} : (r == 0 ? (uint32_t)a{ni} : 0);\n"
                            f"        for (uint32_t i = 0; i < cnt; i++) ((void **){a})[i] = nxcom::to_game(((void **){a})[i], NXIF_{p['iface']}); }}")
            else:
                die(f"{what}: kind {kd} has no rule")
        if nin > 4:
            die(f"{what}: more than 4 borrowed interface arguments")
        rl = ret_letter(what, m)
        L = [f"{'void' if rl == 'v' else 'uintptr_t'} {sym}({', '.join(decl) or 'void'}) {{"]
        bad = "" if rl == "v" else f"{E_POINTER}"
        if this_if:
            L.append("    nxcom::Face *f_ = nxcom::face_from((const void *)t);")
            L.append(f"    if (!f_) return{(' ' + bad) if bad else ''};   /* a platform key called with a pointer that is not a face of ours */")
            L.append("    void *o = f_->obj;")
        L += ["    " + x for x in pre]
        call = f"{callee}({', '.join(args)})"
        if rl == "v":
            L.append(f"    {call};")
            L += ["    " + x for x in post]
        else:
            L.append(f"    {m['ret']} r = {call};")
            L += ["    " + x for x in post]
            L.append("    return nxcom::ret_word((uint32_t)r);")
        L.append("}")
        return "\n".join(L), "".join(letters), rl

    # ---- the proxy of a game object: platform -> game
    def proxy_method(self, iname, m):
        what = f"{iname}::{m['name']}"
        P = m["params"]
        ret = m["ret"]
        rk = m["ret_kind"]
        sig = ", ".join(f"{p['ctype']} a{k}" for k, p in enumerate(P))
        attr = "STDMETHODCALLTYPE " if self.spec["interfaces"][iname]["family"] != "dsh" else ""
        head = f"    {ret} {attr}{m['name']}({sig}) override"
        role = m.get("role")
        if role == "qi":
            p0 = P[0]
            if p0["ctype"] in ("REFIID", "REFGUID"):
                cexp, ptr = "nxcom_canon_guid(&a0, c)", "(const void *)&a0"
            else:
                cexp, ptr = "nxcom_canon_raw((const void *)a0, c)", "(const void *)a0"
            return f"{head} {{ uint8_t c[16]; {cexp}; return ({ret})nxcom::px_qi(rec, c, {ptr}, (void **)a1, {FAMILY[self.spec['interfaces'][iname]['family']]}); }}"
        if role == "addref":
            return f"{head} {{ return ({ret})nxcom::px_addref(rec); }}"
        if role == "release":
            return f"{head} {{ return ({ret})nxcom::px_release(rec); }}"
        pre, post, args, nin = [], [], [], 0
        for k, p in enumerate(P):
            kd, ct, a = p["kind"], p["ctype"], f"a{k}"
            if kd in ("float", "double", "int64", "value", "flags", "enum", "buffer"):
                args.append(a)
                for mem in p.get("members", []):   # the game fills the struct: its interface pointers become the platform's references
                    pre.append(f"if ({a}) {a}->{mem['name']} = nullptr;")
                    post.append(f"if ({a}) {a}->{mem['name']} = (int32_t)r >= 0 ? nxcom::adopt_game((void *){a}->{mem['name']}, NXIF_{mem['iface']}) : nullptr;")
            elif kd == "struct" and p["byref"]:
                args.append(f"(const void *)&{a}" if ct in ("REFIID", "REFGUID", "REFCLSID") else a)
            elif kd == "struct":
                n = p["size"] // 4
                pre.append(f"uint32_t w{k}[{n}]; memcpy(w{k}, &{a}, {p['size']});")
                args += [f"w{k}[{j}]" for j in range(n)]
            elif kd == "callback":
                args.append(f"(uintptr_t){a}")
            elif kd in ("handle", "giface") and not p["byref"]:
                nin += 1
                args.append(f"nxcom::borrow_to_game((void *){a}, NXIF_{p['iface']})")
            elif kd in ("handle", "giface"):
                pre.append(f"void *g{k} = nullptr; if ({a}) *(void **){a} = nullptr;")
                args.append(f"{a} ? (void **)&g{k} : (void **)nullptr")
                ifc = p["iface"]
                if ifc.startswith("$"):
                    cexp = self.canon(P, ifc[1:], type("V", (), {"raw": False, "__call__": lambda s, kk: f"a{kk}"})(), what)
                    pre.insert(0, f"uint8_t c[16]; {cexp}; int ix = nxcom::iface_for_iid(c, {FAMILY[self.spec['interfaces'][iname]['family']]}); if (ix < 0) return ({ret}){E_NOINTERFACE};")
                    post.append(f"if ({a}) *(void **){a} = ((int32_t)r >= 0 && g{k}) ? nxcom::adopt_game(g{k}, (unsigned)ix) : nullptr;")
                else:
                    post.append(f"if ({a}) *(void **){a} = ((int32_t)r >= 0 && g{k}) ? nxcom::adopt_game(g{k}, NXIF_{ifc}) : nullptr;")
            elif kd == "handle_array":
                names = [q["name"] for q in P]
                ni, fi = (names.index(p["count"][0]), names.index(p["count"][1]))
                args.append(a)
                post.append(f"if ((int32_t)r >= 0 && {a}) {{ uint32_t cnt = a{fi} ? *(uint32_t *)a{fi} : (r == 0 ? (uint32_t)a{ni} : 0);\n"
                            f"        for (uint32_t i = 0; i < cnt; i++) ((void **){a})[i] = nxcom::adopt_game(((void **){a})[i], NXIF_{p['iface']}); }}")
            else:
                die(f"{what}: kind {kd} has no rule")
        body = []
        body += pre
        call = f"fnvnx_guest_com_call<{ret}>(rec->gp, {m['slot']}{''.join(', ' + x for x in args)})"
        if rk == "void":
            body += [call + ";"] + post
        else:
            body += [f"{ret} r = {call};"] + post + ["return r;"]
        return head + " {\n        " + "\n        ".join(body) + "\n    }"


def main():
    spec_path, out = sys.argv[1], sys.argv[2]
    spec = json.load(open(spec_path))
    os.makedirs(out, exist_ok=True)
    g = Gen(spec)
    rows, cpp, hdr, exp = [], [], [], []
    hdr.append(HEAD)
    hdr.append("#ifndef FNVNX_COMBRIDGE_IF_GEN_H\n#define FNVNX_COMBRIDGE_IF_GEN_H")
    for h in spec["headers"]:
        hdr.append(f"#include <{h}>" if h in ("dsound.h", "dinput.h") else f'#include "../audio/{h}"')
    hdr += ['#include "combridge.h"', '#include "fnvnx_guestfn.h"', "#include <new>", "#include <string.h>", "#include <type_traits>", "using namespace dsh;", ""]
    hdr.append("enum : unsigned { " + ", ".join(f"NXIF_{n} = {i}" for i, n in enumerate(g.names)) + " };")
    hdr.append("""
static inline void nxcom_canon_guid(const ::GUID *g, uint8_t o[16]) { uint32_t d1 = (uint32_t)g->Data1; memcpy(o, &d1, 4); memcpy(o + 4, &g->Data2, 2); memcpy(o + 6, &g->Data3, 2); memcpy(o + 8, g->Data4, 8); }
static inline void nxcom_canon_raw(const void *p, uint8_t o[16]) { memcpy(o, p, 16); }
static inline void nxcom_canon_sym(const ::GUID &g, uint8_t o[16]) { nxcom_canon_guid(&g, o); }
static inline void nxcom_canon_sym(const dsh::Guid &g, uint8_t o[16]) { nxcom_canon_raw(&g, o); }
static_assert(sizeof(void *) == sizeof(uintptr_t), "one pointer, one boundary word");
#endif""")
    cpp += [HEAD, '#include "combridge_if.gen.h"']
    exp += [HEAD, "/* the exports of the COM-creating functions: DirectSoundCreate*, DirectInput8Create, CoCreateInstance */", '#include "combridge_if.gen.h"']
    cpp.append("""
namespace {
template <class M> struct mf;
template <class C, class R, class... A> struct mf<R (C::*)(A...)> { typedef R sig(A...); };
/* the vtable slot of a virtual member function (Itanium C++ ABI: the pointer is 1 + the byte offset of the slot, adjustment 0) */
template <class MP> int vslot(MP mp)
{
    static_assert(sizeof(MP) == 2 * sizeof(uintptr_t), "member pointer layout");
    uintptr_t w[2];
    memcpy(w, &mp, sizeof w);
    if (!(w[0] & 1)) return -1;   /* not virtual */
    if (w[1]) return -2;          /* this adjustment: not the first base */
    return (int)((w[0] - 1) / sizeof(void *));
}
}   // namespace
""")
    # ---- checks of the spec against the declarations
    chk = ["namespace nxcom {", "unsigned selfcheck()", "{", "    unsigned bad = 0;"]
    sa = []
    for n in g.names:
        info = spec["interfaces"][n]
        C = info["cxx"]
        for m in g.by[n]:
            what = f"{n}::{m['name']}"
            args = ", ".join(p["ctype"] for p in m["params"])
            sa.append(f'static_assert(std::is_same<mf<decltype(&{C}::{m["name"]})>::sig, {m["ret"]}({args})>::value, "{what}: the spec and the declaration disagree");')
            chk.append(f"    bad += vslot(&{C}::{m['name']}) != {m['slot']};")
    for e in spec["exports"]:
        exp.append(f'static_assert(std::is_same<decltype(&{e["name"]}), {e["decl"]}>::value, "export {e["name"]}: the spec and the declaration disagree");')
    chk += ["    return bad;", "}", "}   // namespace nxcom", ""]
    cpp += sa + [""]
    # ---- thunks
    tmeta = {}
    for n in g.names:
        info = spec["interfaces"][n]
        if info["hidden"]:
            continue
        for m in g.by[n]:
            what = f"{n}::{m['name']}"
            sym = f"nxb_{n}_{m['name']}"
            C = info["cxx"]
            role = m.get("role")
            if role in ("addref", "release"):
                body = (f'uintptr_t {sym}(uintptr_t t) {{\n'
                        f'    nxcom::Face *f_ = nxcom::face_from((const void *)t);\n'
                        f'    if (!f_) return 0;\n')
                if role == "addref":
                    body += f'    nxcom::face_ref(f_);\n    return nxcom::ret_word((uint32_t)(({C} *)f_->obj)->AddRef());\n}}'
                else:
                    body += f'    void *o = f_->obj;\n    nxcom::face_unref(f_);   /* the face goes with the last reference the game holds; the object\'s count is the object\'s */\n    return nxcom::ret_word((uint32_t)(({C} *)o)->Release());\n}}'
                text, letters, rl = body, "i", "i"
            else:
                text, letters, rl = g.thunk(what, sym, m, f"(({C} *)o)->{m['name']}", n)
            cpp.append('extern "C" ' + text)
            rows.append((f"!{n}", m["name"], str(m["slot"]), "stdcall", rl, letters, sym, "sym"))
    for e in spec["exports"]:
        what = e["name"]
        sym = f"nxb_{what}"
        text, letters, rl = g.thunk(what, sym, e, what, None)
        exp.append('extern "C" ' + text)
        rows.append((e["dll"], e["name"], str(e["ordinal"]), "stdcall", rl, letters, sym, "sym"))
    # ---- proxies: a method of a game object is one boundary call of at most FNVNX_BND_MAX_WORDS words (this included); an
    # interface with a wider method (IFilterMapper::EnumMatchingFilters: 22 words) is the platform's own service object, no game
    # object implements it, and the runtime consumes no game object of it (px_get: no maker)
    no_proxy = set()
    for n in g.names:
        if any(1 + sum(len(words_of(p, n)) for p in m["params"]) > 16 for m in g.by[n]):
            no_proxy.add(n)
    for n in g.names:
        info = spec["interfaces"][n]
        if n in no_proxy:
            continue
        cpp.append(f"namespace {{\nstruct Px_{n} final : {info['cxx']} {{\n    nxcom::ProxyRec *rec;\n    explicit Px_{n}(nxcom::ProxyRec *r) : rec(r) {{}}")
        for m in g.by[n]:
            cpp.append(g.proxy_method(n, m))
        cpp.append(f"}};\nvoid *mk_{n}(nxcom::ProxyRec *r) {{ return static_cast<{info['cxx']} *>(new (std::nothrow) Px_{n}(r)); }}\n"
                   f"void fr_{n}(void *p) {{ delete (Px_{n} *)({info['cxx']} *)p; }}\n}}")
    # ---- tables
    for n in g.names:
        info = spec["interfaces"][n]
        if info["hidden"]:
            continue
        cpp.append(f"static const char *const names_{n}[] = {{" + ", ".join(f'"{m["name"]}"' for m in g.by[n]) + "};")
        cpp.append(f"static const void *const thunks_{n}[] = {{" + ", ".join(f"(const void *)&nxb_{n}_{m['name']}" for m in g.by[n]) + "};")
    cpp.append(f"static uintptr_t g_keys[{max(g.nkeys, 1)}];")
    cpp.append("static const nxcom::Iface g_ifaces[] = {")
    for n in g.names:
        info = spec["interfaces"][n]
        par = info.get("parent", info["base"])
        base = g.ix[par] if par else -1
        al = g.ix[info["alias"]] if info.get("alias") else -1
        mk = "&mk_%s, &fr_%s" % (n, n) if n not in no_proxy else "nullptr, nullptr"
        if info["hidden"]:
            cpp.append(f'    {{"{n}", {info["slots"]}, 0, {base}, true, {al}, {FAMILY[info["family"]]}, nullptr, nullptr, {mk}}},')
        else:
            cpp.append(f'    {{"{n}", {info["slots"]}, {g.keyoff[n]}, {base}, false, {al}, {FAMILY[info["family"]]}, names_{n}, thunks_{n}, {mk}}},')
    cpp.append("};")
    iids = []   # (iface, symbol or literal)
    for n in g.names:
        for s in spec["interfaces"][n]["iids"]:
            iids.append((n, s))
    cpp.append(f"static nxcom::Iid g_iids[{len(iids)}];")
    cpp.append("namespace nxcom {")
    cpp.append("const Tables g_tables = {%d, g_ifaces, %d, g_keys, %d, g_iids};" % (len(g.names), g.nkeys, len(iids)))
    cpp.append("void gen_init()\n{")
    for i, (n, s) in enumerate(iids):
        if re.fullmatch(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}", s):
            h = s.replace("-", "")
            b = [int(h[0:8], 16).to_bytes(4, "little"), int(h[8:12], 16).to_bytes(2, "little"), int(h[12:16], 16).to_bytes(2, "little"), bytes.fromhex(h[16:])]
            bs = b"".join(b)
            cpp.append(f"    {{ static const uint8_t v[16] = {{" + ", ".join(str(x) for x in bs) + f"}}; memcpy(g_iids[{i}].bytes, v, 16); }}")
        else:
            cpp.append(f"    nxcom_canon_sym({s}, g_iids[{i}].bytes);")
        cpp.append(f"    g_iids[{i}].iface = NXIF_{n};")
    cpp.append("}\n}   // namespace nxcom")
    cpp += chk
    open(os.path.join(out, "combridge.gen.cpp"), "w").write("\n".join(cpp) + "\n")
    open(os.path.join(out, "combridge_exports.gen.cpp"), "w").write("\n".join(exp) + "\n")
    open(os.path.join(out, "combridge_if.gen.h"), "w").write("\n".join(hdr) + "\n")
    open(os.path.join(out, "combridge_rows.tsv"), "w").write("".join("\t".join(r) + "\n" for r in rows))
    nm = sum(1 for r in rows if r[0][0] == "!")
    print(f"gen_combridge: {len(rows)} rows ({nm} methods of {sum(1 for n in g.names if not spec['interfaces'][n]['hidden'])} interfaces, {len(rows) - nm} exports)")


