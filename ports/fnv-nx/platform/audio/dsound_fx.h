struct FxCompressor { float gain, attack, release, threshold, ratio, predelay; };
struct FxDistortion { float gain, edge, eqcenter, eqbw, lowpass; };
struct FxEcho { float wet, fb, ldelay, rdelay; LONG pan; };
struct FxGargle { DWORD rate, shape; };
struct FxParamEq { float center, bandwidth, gain; };
