#!/usr/bin/env python3
"""gen_osrec - the constants header of the declared operating system, from platform/declared/os.json alone.

    gen_osrec.py --os os.json --header out.h

os.json holds the fields of the record (major, minor, build, platform_id, csd, sp_major, sp_minor, product_type, suite_mask, native_arch,
process_wow64), each {"value", "source"}. Errors: an unknown, missing or duplicate field, a value of the wrong type, an empty source. The
header is a pure function of the record (fields in the fixed order below); every constant is cited with its source in a comment."""
import argparse
import json
import sys

FIELDS = [("major", int), ("minor", int), ("build", int), ("platform_id", int), ("csd", str), ("sp_major", int), ("sp_minor", int),
          ("product_type", int), ("suite_mask", int), ("native_arch", int), ("process_wow64", int)]


def load(path):
    with open(path) as f:
        rec = json.load(f)
    err = []
    if rec.get("format") != "fnvnx-declared-os/1":
        err.append("format must be fnvnx-declared-os/1")
    fl = rec.get("fields")
    if not isinstance(fl, dict):
        raise SystemExit("gen_osrec: %s has no fields" % path)
    names = [n for n, _ in FIELDS]
    err += ["unknown field %r" % n for n in sorted(set(fl) - set(names))]
    for n, ty in FIELDS:
        e = fl.get(n)
        if not isinstance(e, dict) or set(e) != {"value", "source"}:
            err.append("field %s needs exactly value and source" % n)
        elif type(e["value"]) is not ty or (ty is int and e["value"] < 0):
            err.append("field %s: value must be a %s" % (n, "non-negative integer" if ty is int else "string"))
        elif not isinstance(e["source"], str) or not e["source"].strip():
            err.append("field %s: empty source" % n)
    if err:
        raise SystemExit("gen_osrec: " + "; ".join(err))
    return fl


def header(fl):
    out = ["/* generated by platform/declared/gen_osrec.py from platform/declared/os.json: the declared operating system. Do not edit. */",
           "#ifndef FNVNX_DECLARED_OS_H", "#define FNVNX_DECLARED_OS_H", ""]
    for n, ty in FIELDS:
        v = fl[n]["value"]
        val = json.dumps(v) if ty is str else "%du" % v
        out.append("/* %s */" % fl[n]["source"].replace("*/", "* /"))
        out.append("#define FNVNX_OS_%s %s" % (n.upper(), val))
    out += ["", "#endif", ""]
    return "\n".join(out)


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--os", required=True)
    ap.add_argument("--header", required=True)
    a = ap.parse_args(argv)
    h = header(load(a.os))
    with open(a.header, "w") as f:
        f.write(h)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
