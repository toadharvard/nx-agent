#!/usr/bin/env python3
"""gen_pfh - the IsProcessorFeaturePresent table (win32/declared_pf.h) from x86sys.json, `processor_features`. One value per PF index 0..63: the decided
value, or the documented `others` value above the WDK's last index. An UNDECIDED row has no value and none is chosen: the generator exits with the
rows, so the platform root's generated stage is red until each is decided (the owner's rule: a missing fact is a build error, never a value).
    gen_pfh.py --x86sys x86sys.json --header OUT.h"""
import argparse
import json
import sys


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--x86sys", required=True)
    ap.add_argument("--header", required=True)
    a = ap.parse_args(argv)
    pf = json.load(open(a.x86sys))["processor_features"]
    rows = pf["records"]
    bad = sorted((int(k), v["name"], v["why"]) for k, v in rows.items() if "value" not in v)
    if bad:
        sys.stderr.write("gen_pfh: %d undecided processor-feature rows (no value is chosen):\n" % len(bad) + "".join("  %d %s: %s\n" % b for b in bad))
        return 1
    last = max(int(k) for k in rows)
    vals = [int(rows[str(i)]["value"]) if i <= last else int(pf["others"]["value"]) for i in range(64)]
    with open(a.header, "w") as f:
        f.write("/* generated by platform/declared/gen_pfh.py from x86sys.json processor_features: do not edit */\n#pragma once\n")
        f.write("static const unsigned char fnvnx_pf_table[64] = {%s};\n" % ", ".join(map(str, vals)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
