/* fnv-nx host <-> guest ABI, BSD sockets: the wire constants and structs of the SOCK_* host services (hostapi.h)
 * (hostapi.h documents the services; toolchain/guest/sock_guest.c is the guest side, toolchain/host/host_sock.inc the host side).
 *
 * Every number that crosses the boundary is a number of THIS header. The guest speaks newlib + libnx's (FreeBSD style)
 * headers, the host speaks libnx on the device and glibc in tests: their errno, AF_INET6, option, flag and event numbers
 * differ. So both sides translate by NAME through the X-macro lists below (each X(NAME, wire...) is expanded with that
 * side's own spelling of NAME), and nothing depends on two systems' numbers agreeing. The wire numbering is the Linux one.
 * Protocol numbers (IPPROTO_*) are IANA's and travel as they are. Compiles in both data models. */
#ifndef FNVNX_SOCKWIRE_H
#define FNVNX_SOCKWIRE_H

#include <stdint.h>

/* errno: FNVNX_WIRE_ERRNO_LIST (sockwire_errno.h) is GENERATED by manifest/gen_wire_errno.py: every errno name of the guest libc's
 * sys/errno.h that Linux also defines, with the Linux number. ENOTSUP shares EOPNOTSUPP's number (the first name of a number is
 * the one the wire->local translation picks). The translation is total over that domain by construction; a number outside it
 * cannot come from the bsd service while ASM-004 holds, and ends the process through fnvnx_assume_violation (reach.h). */
#include "fnvnx/sockwire_errno.h"
#define FNVNX_WE_INVAL 22
#define FNVNX_WE_INPROGRESS 115
#define FNVNX_WE_AGAIN 11

/* address families. Other families have no wire form: socket() and addresses of another family fail EAFNOSUPPORT,
 * as the OS's own bsd service answers for them. */
#define FNVNX_WAF_UNSPEC 0
#define FNVNX_WAF_INET 2
#define FNVNX_WAF_INET6 10
#define FNVNX_WIRE_AF_LIST(X) X(AF_UNSPEC, 0) X(AF_INET, 2) X(AF_INET6, 10)
/* socket types; SOCK_NONBLOCK / SOCK_CLOEXEC are applied by the guest (SETFL / descriptor flag) */
#define FNVNX_WSOCK_STREAM 1
#define FNVNX_WSOCK_DGRAM 2
#define FNVNX_WSOCK_RAW 3
#define FNVNX_WIRE_SOCKTYPE_LIST(X) X(SOCK_STREAM, 1) X(SOCK_DGRAM, 2) X(SOCK_RAW, 3)
/* levels: wire 1 is SOL_SOCKET; the others are the IANA protocol numbers (IPPROTO_IP 0, _TCP 6, _IPV6 41) */
#define FNVNX_WLVL_SOCKET 1
/* option value shapes */
#define FNVNX_WOPT_INT 0        /* int32 */
#define FNVNX_WOPT_LINGER 1     /* FnvnxWireLinger */
#define FNVNX_WOPT_TIMEVAL 2    /* FnvnxWireTimeval */
#define FNVNX_WOPT_TYPE 3       /* int32 holding a wire socket type (SO_TYPE; read only) */
#define FNVNX_WOPT_ERRNO 4      /* int32 holding a wire errno (SO_ERROR; read only; reading clears it) */
/* X(NAME, wire option, shape). Options outside these lists are ENOPROTOOPT (POSIX: "the option is not supported
 * by the protocol"): the lists are the POSIX.1 option set plus the integer-valued IP/IPv6/TCP ones of the same
 * headers; ip_mreq-style structure options are not carried. */
#define FNVNX_WIRE_SO_OPT_LIST(X) \
    X(SO_DEBUG, 1, FNVNX_WOPT_INT) X(SO_REUSEADDR, 2, FNVNX_WOPT_INT) X(SO_TYPE, 3, FNVNX_WOPT_TYPE) \
    X(SO_ERROR, 4, FNVNX_WOPT_ERRNO) X(SO_DONTROUTE, 5, FNVNX_WOPT_INT) X(SO_BROADCAST, 6, FNVNX_WOPT_INT) \
    X(SO_SNDBUF, 7, FNVNX_WOPT_INT) X(SO_RCVBUF, 8, FNVNX_WOPT_INT) X(SO_KEEPALIVE, 9, FNVNX_WOPT_INT) \
    X(SO_OOBINLINE, 10, FNVNX_WOPT_INT) X(SO_LINGER, 13, FNVNX_WOPT_LINGER) X(SO_REUSEPORT, 15, FNVNX_WOPT_INT) \
    X(SO_RCVLOWAT, 18, FNVNX_WOPT_INT) X(SO_SNDLOWAT, 19, FNVNX_WOPT_INT) X(SO_RCVTIMEO, 20, FNVNX_WOPT_TIMEVAL) \
    X(SO_SNDTIMEO, 21, FNVNX_WOPT_TIMEVAL) X(SO_ACCEPTCONN, 30, FNVNX_WOPT_INT)
#define FNVNX_WIRE_TCP_OPT_LIST(X) X(TCP_NODELAY, 1, FNVNX_WOPT_INT)          /* level IPPROTO_TCP */
#define FNVNX_WIRE_IP_OPT_LIST(X) \
    X(IP_TOS, 1, FNVNX_WOPT_INT) X(IP_TTL, 2, FNVNX_WOPT_INT) X(IP_MULTICAST_TTL, 33, FNVNX_WOPT_INT) \
    X(IP_MULTICAST_LOOP, 34, FNVNX_WOPT_INT)                                    /* level IPPROTO_IP */
#define FNVNX_WIRE_IPV6_OPT_LIST(X) \
    X(IPV6_UNICAST_HOPS, 16, FNVNX_WOPT_INT) X(IPV6_MULTICAST_HOPS, 18, FNVNX_WOPT_INT) \
    X(IPV6_MULTICAST_LOOP, 19, FNVNX_WOPT_INT) X(IPV6_V6ONLY, 26, FNVNX_WOPT_INT)   /* level IPPROTO_IPV6 */
/* message flags (sendto/recvfrom); a flag outside this list is EOPNOTSUPP, as POSIX says */
#define FNVNX_WIRE_MSG_LIST(X) \
    X(MSG_OOB, 0x1) X(MSG_PEEK, 0x2) X(MSG_DONTROUTE, 0x4) X(MSG_WAITALL, 0x100) X(MSG_DONTWAIT, 0x40) \
    X(MSG_NOSIGNAL, 0x4000)
/* poll events (the guest's POLLWRNORM is its POLLOUT bit, its POLLINIGNEOF has no wire form and is dropped) */
#define FNVNX_WPOLLIN 0x001
#define FNVNX_WPOLLPRI 0x002
#define FNVNX_WPOLLOUT 0x004
#define FNVNX_WPOLLERR 0x008
#define FNVNX_WPOLLHUP 0x010
#define FNVNX_WPOLLNVAL 0x020
#define FNVNX_WPOLLRDNORM 0x040
#define FNVNX_WPOLLRDBAND 0x080
#define FNVNX_WPOLLWRNORM 0x100
#define FNVNX_WPOLLWRBAND 0x200
#define FNVNX_WIRE_POLL_LIST(X) \
    X(POLLIN, 0x1) X(POLLPRI, 0x2) X(POLLOUT, 0x4) X(POLLERR, 0x8) X(POLLHUP, 0x10) X(POLLNVAL, 0x20) \
    X(POLLRDNORM, 0x40) X(POLLRDBAND, 0x80) X(POLLWRBAND, 0x200)
/* file status flags of SOCK_GETFL/SETFL (the Linux values) */
#define FNVNX_WO_RDWR 2
#define FNVNX_WO_NONBLOCK 0x800
/* ---- structs (fixed width, little endian, no padding surprises; numbers are values, never byte-swapped fields) */
typedef struct FnvnxWireSockaddr {
    uint16_t family;       /* FNVNX_WAF_*; WAF_UNSPEC = no address */
    uint16_t port;         /* INET/INET6: the port number */
    uint8_t addr[16];      /* INET: addr[0..3] = the octets a.b.c.d in this order; INET6: the 16 octets */
    uint32_t flowinfo;     /* INET6 sin6_flowinfo (value) */
    uint32_t scope_id;     /* INET6 sin6_scope_id */
    uint32_t reserved;     /* 0 */
} FnvnxWireSockaddr;
typedef struct FnvnxWirePollfd {
    int32_t fd;            /* a socket handle */
    uint16_t events;       /* FNVNX_WPOLL* */
    uint16_t revents;
} FnvnxWirePollfd;
typedef struct FnvnxWireLinger {
    int32_t onoff, linger_s;
} FnvnxWireLinger;
typedef struct FnvnxWireTimeval {
    int64_t sec, usec;
} FnvnxWireTimeval;

#if defined(__cplusplus)
#define FNVNX_SA static_assert
#else
#define FNVNX_SA _Static_assert
#endif
FNVNX_SA(sizeof(FnvnxWireSockaddr) == 32 && sizeof(FnvnxWirePollfd) == 8 && sizeof(FnvnxWireLinger) == 8 &&
         sizeof(FnvnxWireTimeval) == 16, "socket wire struct sizes");
FNVNX_SA(__builtin_offsetof(FnvnxWireSockaddr, port) == 2 && __builtin_offsetof(FnvnxWireSockaddr, addr) == 4 &&
         __builtin_offsetof(FnvnxWireSockaddr, flowinfo) == 20 && __builtin_offsetof(FnvnxWireSockaddr, scope_id) == 24 &&
         __builtin_offsetof(FnvnxWirePollfd, events) == 4 && __builtin_offsetof(FnvnxWirePollfd, revents) == 6 &&
         __builtin_offsetof(FnvnxWireTimeval, usec) == 8, "socket wire struct offsets");

#endif /* FNVNX_SOCKWIRE_H */
