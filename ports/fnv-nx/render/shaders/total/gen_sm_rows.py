#!/usr/bin/env python3
"""Generate render/shaders/total/fnvnx_sm_rows.h from sm_table.json (the SM1-3 language definition): one row per command (stage, opcode form).
    python3 -I render/shaders/total/gen_sm_rows.py [--check]      --check: exit 1 if the committed header differs
    python3 -I render/shaders/total/gen_sm_rows.py TABLE OUT      recipe step: write OUT from TABLE
build.sh copies the header into the MojoShader clone, where fnvnx_sm_check.h (part of mojoshader.patch) turns every row into static asserts.
Name mapping: the MojoShader identifier of an opcode is the upper-cased table name, except the two opcodes MojoShader names differently from
the D3D9 header (D3DSIO_TEXCOORD = TEXCRD, D3DSIO_TEX = TEXLD); the static assert on the opcode value guards the mapping.
Comparison controls are D3DSHADER_COMPARISON (d3d9types.h): GT 1, EQ 2, GE 3, LT 4, NE 5, LE 6.
Tokens >= 0xFFF0 (the D3D9 non-instruction tokens COMMENT 0xFFFE, PHASE 0xFFFD, END 0xFFFF) are token rows; the translator consumes PHASE only,
any other token row is an error here."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ALIAS = {"TEXCOORD": "TEXCRD", "TEX": "TEXLD"}
CMP = {"gt": 1, "eq": 2, "ge": 3, "lt": 4, "ne": 5, "le": 6}
STAGE = {"ps": "MOJOSHADER_TYPE_PIXEL", "vs": "MOJOSHADER_TYPE_VERTEX"}
TOKENS = {"PHASE"}


def render(table=None):
    ops = json.load(open(table or os.path.join(HERE, "sm_table.json")))["opcodes"]
    out = ["/* generated by render/shaders/total/gen_sm_rows.py from sm_table.json; do not edit. %d rows. */" % len(ops)]
    for k in sorted(ops):
        stage, form = k.split(":")
        r = ops[k]
        n, v = r["num"], r["opnum"]
        if v >= 0xFFF0:
            if n not in TOKENS:
                raise SystemExit("token row %s has no consumer in the translator" % k)
            out.append('FNVNX_SM_TOKEN("%s", %s, %s, 0x%08X)' % (k, STAGE[stage], n, v))
            continue
        name = ALIAS.get(n, n.upper())
        out.append('FNVNX_SM_OP("%s", %s, %d, %s)' % (k, STAGE[stage], v, name))
        if "cmp" in r:
            out.append('FNVNX_SM_CMP("%s", %s, %s, %d)' % (k, name, r["cmp"], CMP[r["cmp"]]))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) == 2:   # recipe step: TABLE OUT (the sandbox mounts this tool read-only)
        text = render(args[0])
        open(args[1], "w").write(text)
        sys.exit(0)
    text = render()
    path = os.path.join(HERE, "fnvnx_sm_rows.h")
    if "--check" in sys.argv:
        sys.exit(0 if open(path).read() == text else 1)
    open(path, "w").write(text)
