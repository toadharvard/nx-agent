#!/usr/bin/env python3
"""gen_enums.py: the C enums of the D3D9 enumerations the state translation consumes (RD-front, rule "total by construction").

    python3 -I gen_enums.py OUT_HEADER [OUT_JSON]

Membership of every enumeration comes from the interface table render/d3d9/spec/d3d9_spec.json ("enums": enumerator names, in
header order). The numeric values are not read from C text: the generator compiles a probe program against the shim headers
(shim/include/d3d9types.h, g++ -m32) that prints (name, value) for every enumerator, so a value is what the compiler computes.
The one extension is VENDOR_FOURCC: D3DFORMAT is an open FOURCC space and the D3D9 headers have no enumerator for the vendor
codes the reference implementation (Wine 9.0, wined3d_private.h enum wined3d_format_id, the members made with
WINEMAKEFOURCC) gives a format id; they are added to D3DFORMAT here, with the value of their four bytes.

Output header: for each enumeration `typedef enum NxD3D<name> {NX_<enumerator> = value, ...} NxD3D<name>;` and
`static inline int nxd3d_in_<enum>(uint32_t v)` (<enum> = D3DCMPFUNC, ...), true iff v is one of its enumerators (a switch over the enum type without
a default, compiled with -Werror=switch-enum: it cannot go out of step with the enum). The translation functions are switches
over these types with no default branch and are compiled with -Werror=switch -Werror=switch-enum, so an enumerator of the
spec without a case is a compile error. The optional JSON lists the enumerations for the gate and the test."""
import json, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SPEC = os.path.join(PORT, "render", "d3d9", "spec", "d3d9_spec.json")
SHIM = os.path.join(PORT, "shim", "include")
# the enumerations the translation reads (switch over the enum type) or indexes by (state-type enums)
SWITCHED = ["D3DBLEND", "D3DBLENDOP", "D3DCMPFUNC", "D3DCULL", "D3DFILLMODE", "D3DFOGMODE", "D3DFORMAT", "D3DSHADEMODE",
            "D3DSTENCILOP", "D3DTEXTUREADDRESS", "D3DTEXTUREFILTERTYPE", "D3DZBUFFERTYPE"]
INDEXED = ["D3DRENDERSTATETYPE", "D3DSAMPLERSTATETYPE"]
# Wine 9.0 wined3d_private.h enum wined3d_format_id: FOURCC members that have no enumerator in d3d9types.h
VENDOR_FOURCC = ["YV12", "ATI1", "ATI2", "INST", "NVDB", "NVHU", "NVHS", "INTZ", "RESZ", "NULL", " R16", "AL16", "NV12",
                 "DF16", "DF24", "ATOC"]
fcc = lambda s: sum(ord(c) << (8 * i) for i, c in enumerate(s))
ident = lambda s: "D3DFMT_" + s.strip()


def values(spec_enums, names):
    """{enum: [(enumerator, value)]} computed by the compiler from the shim headers."""
    src = ['#include "d3d9types.h"', "#include <stdio.h>", "int main(void) {"]
    for e in names:
        for n in spec_enums[e]:
            src.append('printf("%s %s %%lld\\n", (long long)%s);' % (e, n, n))
    src.append("return 0; }")
    with tempfile.TemporaryDirectory() as t:
        c, x = os.path.join(t, "probe.cpp"), os.path.join(t, "probe")
        open(c, "w").write("\n".join(src))
        subprocess.run(["g++", "-m32", "-std=c++17", "-w", "-I", SHIM, c, "-o", x], check=True, capture_output=True)
        out = subprocess.run([x], check=True, capture_output=True, text=True).stdout
    res = {e: [] for e in names}
    for ln in out.splitlines():
        e, n, v = ln.split()
        res[e].append((n, int(v)))
    return res


def build():
    spec = json.load(open(SPEC))["enums"]
    names = SWITCHED + INDEXED
    vals = values(spec, names)
    vals["D3DFORMAT"] += [(ident(s), fcc(s)) for s in VENDOR_FOURCC]
    return vals


def render(vals):
    o = ["/* generated by gen_enums.py from render/d3d9/spec/d3d9_spec.json (+ values computed from shim/include/d3d9types.h);",
         " * do not edit. See gen_enums.py for the rule. */", "#ifndef FNVNX_D3D9_ENUMS_GEN_H", "#define FNVNX_D3D9_ENUMS_GEN_H",
         "#include <stdint.h>", ""]
    for e, lst in vals.items():
        seen = {}
        for n, v in lst:
            if v in seen:
                raise SystemExit("gen_enums: %s: %s and %s have the value %d" % (e, seen[v], n, v))
            seen[v] = n
        o.append("typedef enum NxD3D%s {" % e[3:])
        o += ["    NX_%s = %d," % (n, v) for n, v in lst]
        o.append("} NxD3D%s;" % e[3:])
        if e in SWITCHED:
            o.append("static inline int nxd3d_in_%s(uint32_t v) {" % e)
            o.append("    switch ((NxD3D%s)v) {" % e[3:])
            o += ["    case NX_%s:" % n for n, _ in lst]
            o += ["        return 1;", "    }", "    return 0;", "}"]
        o.append("")
    o.append("#endif")
    return "\n".join(o) + "\n"


def main(argv):
    vals = build()
    open(argv[0], "w").write(render(vals))
    if len(argv) > 1:
        json.dump({"switched": SWITCHED, "indexed": INDEXED, "enums": {e: vals[e] for e in vals}, "vendor_fourcc": VENDOR_FOURCC},
                  open(argv[1], "w"), sort_keys=True, indent=0)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
