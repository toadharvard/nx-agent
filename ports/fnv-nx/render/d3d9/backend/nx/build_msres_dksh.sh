#!/bin/sh
# Builds dk_msres_dksh.h (the multisample-resolve primitive's DKSH programs) with uam: build_msres_dksh.sh [out.h]   UAM = the uam binary (pinned by bootstrap_dk.sh).
# The first line of the header carries the sha256 of the sources, so a stale header is recognisable; tests/l6/dkmsres builds the header twice and requires
# identical bytes (the build is deterministic) and equal to the committed one.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${1:-$HERE/dk_msres_dksh.h}
UAM=${UAM:?set UAM to the uam binary}
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
cd "$HERE"
"$UAM" -s vert -o "$T/vs.dksh" dk_msres_vs.glsl 2> /dev/null
for n in avg depth stencil; do "$UAM" -s frag -o "$T/$n.dksh" dk_msres_fs_$n.glsl 2> /dev/null; done
SRC=$(cat dk_msres_vs.glsl dk_msres_fs_avg.glsl dk_msres_fs_depth.glsl dk_msres_fs_stencil.glsl | sha256sum | cut -c1-16)
{
    echo "/* generated by build_msres_dksh.sh: sources $SRC; do not edit */"
    for n in vs avg depth stencil; do
        f=$T/$n.dksh
        # DKSH header: u32 magic, header_sz, control_sz, code_sz (little endian)
        ctl=$(od -An -tu4 -j8 -N4 "$f" | tr -d ' '); code=$(od -An -tu4 -j12 -N4 "$f" | tr -d ' ')
        echo "enum { MR_${n}_CTL = $ctl, MR_${n}_CODE = $code };"
        echo "static const uint8_t mr_$n[] = {"
        od -An -v -tu1 -w32 "$f" | sed 's/^ *//; s/  */,/g; s/$/,/'
        echo "};"
    done
} > "$OUT"
