#!/bin/sh
# Builds dk_scale_dksh.h (the scale primitive's DKSH programs) with uam: build_scale_dksh.sh [out.h]   UAM = the uam binary (pinned by bootstrap_dk.sh).
# The first line of the header carries the uam pin (git revision of $UAM's tree when known, else its sha256) and the sha256 of the three sources, so a stale
# header is recognisable; tests/l6/dkscale builds the header twice and requires identical bytes (the build is deterministic) and equal to the committed one.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${1:-$HERE/dk_scale_dksh.h}
UAM=${UAM:?set UAM to the uam binary}
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
cd "$HERE"
for k in 0 1 2; do { sed -n 1p dk_scale_fs.glsl; echo "#define KIND $k"; sed 1d dk_scale_fs.glsl; } > "$T/fs$k.glsl"; done
"$UAM" -s vert -o "$T/vs.dksh" dk_scale_vs.glsl 2> /dev/null
for k in 0 1 2; do "$UAM" -s frag -o "$T/fs$k.dksh" "$T/fs$k.glsl" 2> /dev/null; done
PIN=$(sha256sum "$UAM" | cut -c1-16)
SRC=$(cat dk_scale_vs.glsl dk_scale_fs.glsl | sha256sum | cut -c1-16)
{
    echo "/* generated by build_scale_dksh.sh: uam $PIN, sources $SRC; do not edit */"
    for n in vs fs0 fs1 fs2; do
        f=$T/$n.dksh
        # DKSH header: u32 magic, header_sz, control_sz, code_sz (little endian)
        ctl=$(od -An -tu4 -j8 -N4 "$f" | tr -d ' '); code=$(od -An -tu4 -j12 -N4 "$f" | tr -d ' ')
        echo "enum { SC_${n}_CTL = $ctl, SC_${n}_CODE = $code };"
        echo "static const uint8_t sc_$n[] = {"
        od -An -v -tu1 -w32 "$f" | sed 's/^ *//; s/  */,/g; s/$/,/'
        echo "};"
    done
} > "$OUT"
