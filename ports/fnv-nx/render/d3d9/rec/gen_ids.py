#!/usr/bin/env python3
"""gen_ids.py SPEC.json OUTDIR: derives from the spec (no hand lists) d9rec_ids.h (the (iface, slot) of every presenting method, for the
sink's flush rule) and d9rec.def (all exports of the spec, by name)."""
import json, os, sys
spec = json.load(open(sys.argv[1])); out = sys.argv[2]; os.makedirs(out, exist_ok=True)
names = sorted(spec["interfaces"])
pres = sorted((names.index(m["iface"]), m["slot"], m["iface"] + "::" + m["name"]) for m in spec["methods"] if m["name"] in ("Present", "PresentEx"))
with open(os.path.join(out, "d9rec_ids.h"), "w") as f:
    f.write("// generated by gen_ids.py; do not edit\nstatic const struct { unsigned iface, slot; } d9rec_present[] = {\n")
    f.write("".join(f"  {{ {i}, {s} }},  // {n}\n" for i, s, n in pres) + "};\n")
with open(os.path.join(out, "d9rec.def"), "w") as f:
    f.write("LIBRARY d3d9.dll\nEXPORTS\n" + "".join(f"    {e['name']}\n" for e in spec["exports"]))
