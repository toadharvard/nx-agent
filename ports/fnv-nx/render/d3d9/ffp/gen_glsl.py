#!/usr/bin/env python3
"""gen_glsl.py OUT_DIR: embed the fixed-function programs in the product (draw_ffp / ffp_prog.cpp).
Writes OUT_DIR/ffp_glsl.gen.h: the GLSL text of ffp.vert.glsl / ffp.frag.glsl with every #include expanded, in the two variants of the
programs (smooth, and flat = NX_FFP_FLAT, selected by D3DRS_SHADEMODE), each as a byte array, its size and its sha256 (NxShaderDesc.key,
gpu_abi.h), computed here at generation time. The front end sends GLSL and the key to every backend, never DKSH (a backend that needs DKSH
compiles the GLSL itself)."""
import hashlib, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = (("vs", "ffp.vert.glsl"), ("ps", "ffp.frag.glsl"))
VARIANTS = (("smooth", None), ("flat", "NX_FFP_FLAT"))


def expand(path, seen=()):
    """the file with every `#include "x"` replaced by the text of x (relative to the including file), recursively"""
    out = []
    for line in open(path).read().split("\n"):
        m = re.match(r'\s*#include\s+"([^"]+)"\s*$', line)
        if m:
            inc = os.path.normpath(os.path.join(os.path.dirname(path), m.group(1)))
            if inc in seen: raise SystemExit("gen_glsl: include cycle at " + inc)
            out.append(expand(inc, seen + (inc,)))
        else:
            out.append(line)
    return "\n".join(out)


def variant(text, define):
    """`#define <define> 1` right after the #version line"""
    if define is None: return text
    i = text.index("\n", text.index("#version")) + 1
    return text[:i] + "#define %s 1\n" % define + text[i:]


def carray(name, data):
    return "static const unsigned char %s[%d] = {%s};\n" % (name, len(data), ",".join(str(b) for b in data))


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    g = "// generated by render/d3d9/ffp/gen_glsl.py from ffp.vert.glsl / ffp.frag.glsl (includes expanded); do not edit\n"
    for stage, f in SOURCES:
        text = expand(os.path.join(HERE, f))
        for vname, d in VARIANTS:
            b = variant(text, d).encode(); n = "nx_ffp_glsl_%s_%s" % (stage, vname)
            g += carray(n, b) + "static const unsigned %s_size = %d;\n" % (n, len(b)) + carray(n + "_key", hashlib.sha256(b).digest())
    open(os.path.join(out, "ffp_glsl.gen.h"), "w").write(g)


if __name__ == "__main__":
    sys.dont_write_bytecode = True
    main()
