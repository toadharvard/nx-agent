#!/usr/bin/env python3
"""gen_glsl.py OUT_DIR [--uam PATH_TO_uam]: embed the fixed-function programs in the product (draw_ffp / ffp_prog.cpp).
Writes OUT_DIR/ffp_glsl.gen.h: the GLSL text of ffp.vert.glsl / ffp.frag.glsl with every #include expanded, in the two variants of the
programs (smooth, and flat = NX_FFP_FLAT, selected by D3DRS_SHADEMODE), as byte arrays. With --uam the same four sources are compiled by uam
(the deko3d GLSL compiler, `uam -s vert|frag`) and OUT_DIR/ffp_dksh.gen.h holds the DKSH images; without it that header states NX_FFP_DKSH_BUILT 0
(host builds on the GL backend, which takes GLSL; the guest build requires uam: build_guest.sh)."""
import os, re, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = (("vs", "ffp.vert.glsl", "vert"), ("ps", "ffp.frag.glsl", "frag"))
VARIANTS = (("smooth", None), ("flat", "NX_FFP_FLAT"))


def expand(path, seen=()):
    """the file with every `#include "x"` replaced by the text of x (relative to the including file), recursively"""
    out = []
    for line in open(path).read().split("\n"):
        m = re.match(r'\s*#include\s+"([^"]+)"\s*$', line)
        if m:
            inc = os.path.normpath(os.path.join(os.path.dirname(path), m.group(1)))
            if inc in seen: raise SystemExit("gen_glsl: include cycle at " + inc)
            out.append(expand(inc, seen + (inc,)))
        else:
            out.append(line)
    return "\n".join(out)


def variant(text, define):
    """`#define <define> 1` right after the #version line"""
    if define is None: return text
    i = text.index("\n", text.index("#version")) + 1
    return text[:i] + "#define %s 1\n" % define + text[i:]


def carray(name, data):
    body = ",".join(str(b) for b in data) if data else "0"
    return "static const unsigned char %s[%d] = {%s};\nstatic const unsigned %s_size = %d;\n" % (name, max(len(data), 1), body, name, len(data))


def main():
    out = sys.argv[1]; uam = sys.argv[sys.argv.index("--uam") + 1] if "--uam" in sys.argv else None
    os.makedirs(out, exist_ok=True)
    srcs = {}
    for stage, f, _ in SOURCES:
        text = expand(os.path.join(HERE, f))
        for vname, d in VARIANTS: srcs[(stage, vname)] = variant(text, d)
    g = "// generated by render/d3d9/ffp/gen_glsl.py from ffp.vert.glsl / ffp.frag.glsl (includes expanded); do not edit\n"
    for (stage, vname), t in sorted(srcs.items()): g += carray("nx_ffp_glsl_%s_%s" % (stage, vname), t.encode())
    open(os.path.join(out, "ffp_glsl.gen.h"), "w").write(g)
    h = "// generated by render/d3d9/ffp/gen_glsl.py: DKSH images of the fixed-function programs (uam); do not edit\n"
    if uam:
        h += "#define NX_FFP_DKSH_BUILT 1\n"
        with tempfile.TemporaryDirectory() as tmp:
            for (stage, vname), t in sorted(srcs.items()):
                st = dict((s, k) for s, _, k in SOURCES)[stage]; src = os.path.join(tmp, "%s_%s.glsl" % (stage, vname)); dk = src + ".dksh"
                open(src, "w").write(t)
                r = subprocess.run([uam, "-s", st, "-o", dk, src], capture_output=True, text=True)
                if r.returncode or not os.path.exists(dk):
                    raise SystemExit("gen_glsl: uam failed on %s %s:\n%s" % (stage, vname, (r.stdout + r.stderr)[-1500:]))
                h += carray("nx_ffp_dksh_%s_%s" % (stage, vname), open(dk, "rb").read())
    else:
        h += "#define NX_FFP_DKSH_BUILT 0\n"
        for (stage, vname), _ in sorted(srcs.items()): h += carray("nx_ffp_dksh_%s_%s" % (stage, vname), b"")
    open(os.path.join(out, "ffp_dksh.gen.h"), "w").write(h)


if __name__ == "__main__":
    sys.dont_write_bytecode = True
    main()
