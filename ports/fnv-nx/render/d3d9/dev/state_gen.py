"""state_gen.py: engine of state_model.py. emit(model, outdir, spec) -> state.gen.h, state.gen.cpp (not checked in).
Every device method of a family is generated from the family's SHAPE (kv, kv2, objat, obj0, stream, freq, val0, mat, vecat, range) with the signature read from the spec;
a model entry whose method is missing from the spec, or has a parameter list the shape does not fit, stops the generator (exit 2)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "..", "spec", "d3d9_spec.json")
CONSTS = [("NX_D3D_MAX_CLIP_PLANES", "6"), ("NX_D3D_MAX_STREAMS", "16"), ("NX_D3D_MAX_RTS", "4"), ("NX_VS_CONST_F", "256"), ("NX_PS_CONST_F", "224"),
          ("NX_CONST_I", "16"), ("NX_CONST_B", "16"), ("NX_RS_COUNT", "D3DRS_BLENDOPALPHA + 1"), ("NX_SAMP_SLOTS", "21"), ("NX_SAMP_TYPES", "D3DSAMP_DMAPOFFSET + 1"),
          ("NX_TSS_STAGES", "8"), ("NX_TSS_TYPES", "D3DTSS_CONSTANT + 1"), ("NX_XF_COUNT", "266")]
DEV_IFACES = ("IDirect3DDevice9", "IDirect3DDevice9Ex")


def parse(txt, pre):
    rows = []
    for l in txt.strip().split("\n"):
        n, d, b, g = l.split(); rows.append((pre + n, d, b, g))
    return rows


def dexpr(d, kind):
    if d == "F0": return "nx_f(0.0f)"
    if d == "F1": return "nx_f(1.0f)"
    if d == "@zenable": return "(cp->auto_depth ? D3DZB_TRUE : D3DZB_FALSE)"
    if d == "@viewport": return "nx_vp(cp)"
    if d == "@scissor": return "nx_sc(cp)"
    return d


def emit(M, out, specpath):
    spec = json.load(open(specpath or SPEC)); os.makedirs(out, exist_ok=True)
    meth = {m["name"]: m for m in spec["methods"] if m["iface"] == "IDirect3DDevice9"}
    tabs = {"rs": parse(M.RS, "D3DRS_"), "samp": parse(M.SAMP, "D3DSAMP_"), "tss": parse(M.TSS, "D3DTSS_")}
    groups = []
    for t in tabs.values():
        for r in t:
            if r[3] not in groups: groups.append(r[3])
    for f in M.FAMILIES:
        if f["group"] not in groups: groups.append(f["group"])
    for x in M.GROUPS_EXTRA:
        if x not in groups: groups.append(x)
    fams = M.FAMILIES
    H = ["// generated by state_model.py; do not edit", "#pragma once", '#include "../dev/obj.h"', "#include <string.h>", "#include <stdint.h>", "enum : uint32_t {"]
    H += [f"    {n} = {v}," for n, v in CONSTS] + ["};"]
    H += ["enum NxGroup : uint64_t {"] + [f"    NX_G_{g} = 1ull << {i}," for i, g in enumerate(groups)] + ["};", "enum : uint32_t {  // slots: one per independently settable / recordable unit"]
    order = [("rs", "NX_RS_COUNT"), ("samp", "NX_SAMP_SLOTS * NX_SAMP_TYPES"), ("tss", "NX_TSS_STAGES * NX_TSS_TYPES")] + [(f["name"], f["n"]) for f in fams]
    prev = None
    for n, c in order:
        H.append(f"    NX_S_{n} = {('NX_S_' + prev[0] + ' + ' + prev[1]) if prev else '0'},"); prev = (n, c)
    H += [f"    NX_SLOTS = NX_S_{prev[0]} + {prev[1]},", "    NX_MASK_WORDS = (NX_SLOTS + 31) / 32, NX_FAMS = %d," % len(order), "};"]
    H += ["struct NxF4 { float v[4] = {}; }; struct NxI4 { int v[4] = {}; }; struct NxPlane { float p[4] = {}; };",
          "struct NxStream { IDirect3DVertexBuffer9* vb = nullptr; UINT offset = 0, stride = 0; };  // vb first: object element",
          "struct NxDeviceState {"]
    H += ["    uint32_t rs[NX_RS_COUNT]; uint32_t samp[NX_SAMP_SLOTS][NX_SAMP_TYPES]; uint32_t tss[NX_TSS_STAGES][NX_TSS_TYPES];"]
    H += [f"    {f['ct']} {f['name']}[{f['n']}];" for f in fams] + ["};"]
    H += ["struct NxCreateParams { uint32_t auto_depth, width, height, behavior; };  // what CreateDevice/Reset fix: ZENABLE default, viewport, scissor, software-VP legality",
          "void nx_state_defaults(NxDeviceState* s, const NxCreateParams* cp);  // drops object references, then every state to its documented default",
          "struct NxFam { uint32_t first, n; uint32_t esz; uint32_t off; uint8_t obj; };  // slot families (object families: pointer first in the element)",
          "extern const NxFam nx_fams[NX_FAMS]; extern const char* const nx_fam_names[NX_FAMS];",
          "struct NxTables { uint8_t slot_fam[NX_SLOTS], slot_group[NX_SLOTS], rs[NX_RS_COUNT], samp[NX_SAMP_TYPES], tss[NX_TSS_TYPES]; uint32_t mask[3][NX_MASK_WORDS]; constexpr NxTables(); };",
          "// mask[0] D3DSBT_ALL, [1] D3DSBT_PIXELSTATE, [2] D3DSBT_VERTEXSTATE; rs/samp/tss: bit0 = named state, bit1 pixel, bit2 vertex",
          "extern const NxTables nx_tab;"]
    # ---- constexpr tables
    C = ["constexpr NxTables::NxTables() : slot_fam(), slot_group(), rs(), samp(), tss(), mask() {"]
    fi = {n: i for i, (n, _) in enumerate(order)}
    C.append("    auto add = [&](int t, uint32_t s) { mask[t][s / 32] |= 1u << (s % 32); };")
    C.append("    for (uint32_t s = 0; s < NX_SLOTS; s++) { uint32_t f = 0;")
    C.append("        " + " ".join(f"if (s >= NX_S_{n}) f = {i};" for n, i in fi.items()) + " slot_fam[s] = (uint8_t)f; }")
    for nm, rows in tabs.items():
        for r in rows:
            fl = 1 | (2 if "P" in r[2] else 0) | (4 if "V" in r[2] else 0)
            C.append(f"    {nm}[{r[0]}] = {fl};")
    gi = {g: i for i, g in enumerate(groups)}
    C.append("    for (uint32_t k = 0; k < NX_RS_COUNT; k++) slot_group[NX_S_rs + k] = 255;")
    for r in tabs["rs"]: C.append(f"    slot_group[NX_S_rs + {r[0]}] = {gi[r[3]]};")
    for nm, cnt in (("samp", "NX_SAMP_SLOTS"), ("tss", "NX_TSS_STAGES")):
        ty = "NX_SAMP_TYPES" if nm == "samp" else "NX_TSS_TYPES"
        C.append(f"    for (uint32_t a = 0; a < {cnt}; a++) {{")
        for r in tabs[nm]: C.append(f"        slot_group[NX_S_{nm} + a * {ty} + {r[0]}] = {gi[r[3]]};")
        C.append(f"        for (uint32_t t = 0; t < {ty}; t++) if ({nm}[t] & 1) {{ uint32_t s = NX_S_{nm} + a * {ty} + t; add(0, s); if ({nm}[t] & 2) add(1, s); if ({nm}[t] & 4) add(2, s); }} }}")
    C.append("    for (uint32_t k = 0; k < NX_RS_COUNT; k++) if (rs[k] & 1) { add(0, NX_S_rs + k); if (rs[k] & 2) add(1, NX_S_rs + k); if (rs[k] & 4) add(2, NX_S_rs + k); }")
    for f in fams:
        C.append(f"    for (uint32_t k = 0; k < {f['n']}; k++) {{ slot_group[NX_S_{f['name']} + k] = {gi[f['group']]};")
        b = f["blocks"]
        if b != "-":
            C.append(f"        add(0, NX_S_{f['name']} + k);" + (" add(1, NX_S_%s + k);" % f["name"] if "P" in b else "") + (" add(2, NX_S_%s + k);" % f["name"] if "V" in b else "") + " }")
        else: C.append("    }")
    C.append("}")
    # ---- domain functions
    H += ["struct NxRange { uint32_t lo, hi, first; };",
          "inline int nx_rng(uint32_t k, const NxRange* r, int n) { for (int i = 0; i < n; i++) if (k >= r[i].lo && k < r[i].hi) return (int)(r[i].first + k - r[i].lo); return -1; }",
          "enum { NX_DOM_INVALID = -1, NX_DOM_IGNORE = -2 };  // INVALID -> D3DERR_INVALIDCALL; IGNORE: a number naming no state: D3D_OK, nothing stored, Get returns 0 (README)",
          "inline HRESULT nx_dom_hr(int d) { return d == NX_DOM_IGNORE ? D3D_OK : D3DERR_INVALIDCALL; }"]
    for nm, rr in (("samp", M.SAMP_RANGES), ("xf", M.XF_RANGES)):
        H.append(f"inline int nx_d{nm}(uint32_t k) {{ static const NxRange r[] = {{" + ", ".join(f"{{(uint32_t)({a}), (uint32_t)({b}), {c}}}" for a, b, c in rr) + f"}}; return nx_rng(k, r, {len(rr)}); }}")
    H += ["inline int nx_drs(uint32_t k) { return k < NX_RS_COUNT && (nx_tab.rs[k] & 1) ? (int)(NX_S_rs + k) : NX_DOM_IGNORE; }",
          "inline int nx_dsampst(uint32_t a, uint32_t t) { int i = nx_dsamp(a); if (i < 0) return i; return t < NX_SAMP_TYPES && (nx_tab.samp[t] & 1) ? (int)(NX_S_samp + i * NX_SAMP_TYPES + t) : NX_DOM_IGNORE; }",
          "inline int nx_dtss(uint32_t a, uint32_t t) { if (a >= NX_TSS_STAGES) return NX_DOM_INVALID; return t < NX_TSS_TYPES && (nx_tab.tss[t] & 1) ? (int)(NX_S_tss + a * NX_TSS_TYPES + t) : NX_DOM_IGNORE; }"]
    # ---- methods
    decl, body, fwd = [], [], []
    def sig(m, q=""): return f"{m['ret']} {q}{m['name']}(" + ", ".join(f"{p['ctype']} {p['name']}" for p in m["params"]) + ")"
    def add(name, code):
        if name not in meth: sys.stderr.write(f"state_gen: spec has no IDirect3DDevice9::{name}\n"); sys.exit(2)
        m = meth[name]; decl.append(sig(m) + ";"); body.append(sig(m, "NxDeviceCore::") + " {" + code + "}")
        for i in DEV_IFACES: fwd.append((i, m, 'NxDeviceCore'))
    INV = "return D3DERR_INVALIDCALL;"
    def need(name, n, shape):
        if len(meth[name]["params"]) != n: sys.stderr.write(f"state_gen: {name} has {len(meth[name]['params'])} params, shape {shape} needs {n}\n"); sys.exit(2)
    for nm, dom, ty in (("rs", "nx_drs({0})", "uint32_t"),):
        pass
    kv = [("SetRenderState", "GetRenderState", "nx_drs({0})", 2), ("SetSamplerState", "GetSamplerState", "nx_dsampst({0}, {1})", 3), ("SetTextureStageState", "GetTextureStageState", "nx_dtss({0}, {1})", 3)]
    for s, g, dom, n in kv:
        need(s, n, "kv"); need(g, n, "kv"); ps = [p["name"] for p in meth[s]["params"]]; pg = [p["name"] for p in meth[g]["params"]]
        add(s, f" int s = {dom.format(*ps)}; if (s < 0) return nx_dom_hr(s); put((uint32_t)s, &{ps[-1]}); return D3D_OK; ")
        add(g, f" if (!{pg[-1]}) {INV} int s = {dom.format(*pg)}; if (s == NX_DOM_IGNORE) {{ *{pg[-1]} = 0; return D3D_OK; }} if (s < 0) {INV} *{pg[-1]} = *(const uint32_t*)cur_at((uint32_t)s); return D3D_OK; ")
    for f in fams:
        sh = f["shape"]; N = f["name"]; S = f"NX_S_{N}"
        if sh == "none": continue
        s, g = f["set"], f.get("get")
        ps = [p["name"] for p in meth[s]["params"]]; pg = [p["name"] for p in meth[g]["params"]] if g else []
        if sh == "objat":
            need(s, 2, sh); need(g, 2, sh)
            add(s, f" int a = nx_dsamp({ps[0]}); if (a < 0) {INV} if (!nx_chk_{f['chk']}({ps[1]})) {INV} put({S} + a, &{ps[1]}); return D3D_OK; ")
            add(g, f" if (!{pg[1]}) {INV} int a = nx_dsamp({pg[0]}); if (a < 0) {INV} auto* t = cur.{N}[a]; *{pg[1]} = t; if (t) t->AddRef(); return D3D_OK; ")
            add_xf = None
        elif sh == "obj0":
            need(s, 1, sh); need(g, 1, sh)
            add(s, f" if (!nx_chk_{f['chk']}({ps[0]})) {INV} put({S}, &{ps[0]}); return D3D_OK; ")
            add(g, f" if (!{pg[0]}) {INV} auto* t = cur.{N}[0]; *{pg[0]} = t; if (t) t->AddRef(); return D3D_OK; ")
        elif sh == "stream":
            need(s, 4, sh); need(g, 4, sh)
            add(s, f" if ({ps[0]} >= NX_D3D_MAX_STREAMS || !nx_chk_obj({ps[1]})) {INV} NxStream e = cur.stream[{ps[0]}]; if ({ps[1]}) {{ e.offset = {ps[2]}; e.stride = {ps[3]}; }} e.vb = {ps[1]}; put({S} + {ps[0]}, &e); return D3D_OK; ")
            add(g, f" if ({pg[0]} >= NX_D3D_MAX_STREAMS || !{pg[1]} || !{pg[2]} || !{pg[3]}) {INV} const NxStream& e = cur.stream[{pg[0]}]; *{pg[1]} = e.vb; if (e.vb) e.vb->AddRef(); *{pg[2]} = e.offset; *{pg[3]} = e.stride; return D3D_OK; ")
        elif sh == "freq":
            need(s, 2, sh); need(g, 2, sh)  # rules: Wine wined3d_stateblock_set_stream_source_freq (tested against Windows): both flags, flag on stream 0, divider 0 -> INVALIDCALL
            add(s, f" if ({ps[0]} >= NX_D3D_MAX_STREAMS || !{ps[1]} || (({ps[1]} & 0x40000000u) && ({ps[1]} & 0x80000000u)) || (({ps[1]} & 0x80000000u) && !{ps[0]})) {INV} uint32_t v = {ps[1]} & 0xC07FFFFFu; put({S} + {ps[0]}, &v); return D3D_OK; ")
            add(g, f" if ({pg[0]} >= NX_D3D_MAX_STREAMS || !{pg[1]}) {INV} *{pg[1]} = cur.freq[{pg[0]}]; return D3D_OK; ")
        elif sh == "val0":
            need(s, 1, sh); need(g, 1 if not f.get("retval") else 0, sh)
            if f.get("retval"):
                add(s, f" put({S}, &{ps[0]}); return D3D_OK; "); add(g, f" return cur.{N}[0]; ")
            else:
                add(s, f" if (!{ps[0]}) {INV} put({S}, {ps[0]}); return D3D_OK; " if f["arg"] != "UINT" else f" put({S}, &{ps[0]}); return D3D_OK; ")
                add(g, f" if (!{pg[0]}) {INV} *{pg[0]} = cur.{N}[0]; return D3D_OK; ")
        elif sh == "mat":
            need(s, 2, sh); need(g, 2, sh); mu = f["mul"]; pm = [p["name"] for p in meth[mu]["params"]]
            add(s, f" int a = nx_dxf({ps[0]}); if (a < 0 || !{ps[1]}) {INV} put({S} + a, {ps[1]}); return D3D_OK; ")
            add(g, f" int a = nx_dxf({pg[0]}); if (a < 0 || !{pg[1]}) {INV} *{pg[1]} = cur.xf[a]; return D3D_OK; ")
            add(mu, f" int a = nx_dxf({pm[0]}); if (a < 0 || !{pm[1]}) {INV} D3DMATRIX r = nx_mul(*{pm[1]}, cur.xf[a]); put({S} + a, &r); return D3D_OK; ")
        elif sh == "vecat":
            need(s, 2, sh); need(g, 2, sh)
            add(s, f" if ({ps[0]} >= NX_D3D_MAX_CLIP_PLANES || !{ps[1]}) {INV} put({S} + {ps[0]}, {ps[1]}); return D3D_OK; ")
            add(g, f" if ({pg[0]} >= NX_D3D_MAX_CLIP_PLANES || !{pg[1]}) {INV} memcpy({pg[1]}, cur.{N}[{pg[0]}].p, 16); return D3D_OK; ")
        elif sh == "range":
            need(s, 3, sh); need(g, 3, sh); n = f["n"]
            add(s, f" if (!{ps[1]}) {INV} if ({ps[0]} > {n} || {ps[2]} > {n} - {ps[0]}) {INV} for (UINT i = 0; i < {ps[2]}; i++) put({S} + {ps[0]} + i, (const char*){ps[1]} + i * sizeof({f['ct']})); return D3D_OK; ")
            add(g, f" if (!{pg[1]}) {INV} if ({pg[0]} > {n} || {pg[2]} > {n} - {pg[0]}) {INV} memcpy({pg[1]}, &cur.{N}[{pg[0]}], {pg[2]} * sizeof({f['ct']})); return D3D_OK; ")
        else: sys.stderr.write(f"state_gen: unknown shape {sh}\n"); sys.exit(2)
    hd, hf = [], []
    for n in M.HAND:
        m = meth[n]; hd.append(sig(m) + ";")
        for i in DEV_IFACES: fwd.append((i, m, "NxDeviceCore"))
    sbm = {m["name"]: m for m in spec["methods"] if m["iface"] == "IDirect3DStateBlock9"}
    for n in M.HAND_SB: fwd.append(("IDirect3DStateBlock9", sbm[n], "NxStateBlockCore"))
    H += ["#define NX_DEVICE_HAND_METHODS \\"] + [f"    {d} \\" for d in hd] + [""]
    H += ["#define NX_STATEBLOCK_METHODS \\", "    HRESULT Capture(); HRESULT Apply();", ""]
    H += ["#define NX_DEVICE_STATE_METHODS \\"] + [f"    {d} \\" for d in decl] + [""]
    H += ["// NX_STATE_METHODS lists the spec names generated here (gate bookkeeping)"]
    # ---- defaults
    D = ["void nx_state_defaults(NxDeviceState* s, const NxCreateParams* cp) {", "    nx_state_drop(s); memset((void*)s, 0, sizeof *s);"]
    for r in tabs["rs"]: D.append(f"    s->rs[{r[0]}] = (uint32_t)({dexpr(r[1], 'rs')});")
    D.append("    for (uint32_t j = 0; j < NX_SAMP_SLOTS; j++) {")
    for r in tabs["samp"]: D.append(f"        s->samp[j][{r[0]}] = (uint32_t)({dexpr(r[1], 'samp')});")
    D.append("    }\n    for (uint32_t i = 0; i < NX_TSS_STAGES; i++) {")
    for r in tabs["tss"]: D.append(f"        s->tss[i][{r[0]}] = (uint32_t)({dexpr(r[1], 'tss')});")
    D.append("    }")
    for f in fams:
        if "default" in f: D.append(f"    for (uint32_t k = 0; k < {f['n']}; k++) s->{f['name']}[k] = {dexpr(f['default'], 'x')};")
    D.append("}")
    ft = ["const NxFam nx_fams[NX_FAMS] = {"]
    for n, c in order:
        f = next((x for x in fams if x["name"] == n), None); obj = 1 if f and f["ct"].endswith("*") or (f and f["ct"] == "NxStream") else 0
        esz = "4" if n in ("rs", "samp", "tss") else "sizeof(((NxDeviceState*)0)->%s[0])" % n
        ft.append(f"    {{NX_S_{n}, {c}, {esz}, offsetof(NxDeviceState, {n}), {obj}}},")
    ft += ["};", "const char* const nx_fam_names[NX_FAMS] = {" + ", ".join(f'"{n}"' for n, _ in order) + "};", "const NxTables nx_tab;"]
    open(os.path.join(out, "state.gen.h"), "w").write("\n".join(H) + "\n")
    F = ["// generated by state_model.py; do not edit", '#include "../dev/state_rt.h"', '#include "d9impl.gen.h"', "#include <stddef.h>"] + C + ft + D + body
    for i, m, core in fwd:
        c = "Nx" + i[len("IDirect3D"):]  # same rule as gen_impl.cname (device/state-block interfaces only)
        F.append(sig(m, f"STDMETHODCALLTYPE {c}::").replace(f"{m['ret']} STDMETHODCALLTYPE", f"{m['ret']} STDMETHODCALLTYPE", 1) + " { " + ("" if m["ret"] == "void" else "return ") + f"{core}::{m['name']}(" + ", ".join(p["name"] for p in m["params"]) + "); }")
    open(os.path.join(out, "state.gen.cpp"), "w").write("\n".join(F) + "\n")
    open(os.path.join(out, "state_methods.txt"), "w").write("\n".join(sorted({m["name"] for _, m, _c in fwd})) + "\n")
    print(f"state_gen: {len({m['name'] for _, m, _c in fwd})} methods, {len(order)} families, slots computed by the compiler")
