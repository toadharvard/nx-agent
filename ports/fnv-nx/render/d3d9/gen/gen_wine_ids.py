#!/usr/bin/env python3
"""gen_wine_ids.py OUTDIR [TABLE]: gen/wine_fixme_ids.gen.h, the ids of verify/wine_fixme.tsv as named constants.
The table verify/wine_fixme.tsv (id, contract_name, wine_ref, kind, value) is the ONLY place where an id, its Wine 9.0 function, its kind and its value are
written. The code names an id as NXW_<wine function> (the last component of wine_ref), so an id in the code is the table's row by construction: a name
without a row does not compile, a row renamed in the table renames the constant. The wine function names of the rows must be unique (checked here: a clash is an error).
Rows are read with the same fields as verify/objstub.py read_wine_table (which validates the full format in the gate); this tool only needs id and wine_ref."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TABLE = os.path.join(HERE, "..", "..", "..", "verify", "wine_fixme.tsv")


def main(argv):
    out = argv[1]; table = argv[2] if len(argv) > 2 else DEFAULT_TABLE
    rows, names = [], {}
    for l in open(table).read().split("\n"):
        if not l or l.startswith("#"): continue
        f = l.split("\t")
        if len(f) != 5 or not f[0].isdigit(): raise SystemExit("gen_wine_ids: bad row %r" % l[:80])
        m = re.fullmatch(r"wine-9\.0:[A-Za-z0-9_./+-]+:([A-Za-z_][A-Za-z0-9_@]*)", f[2])
        if not m: raise SystemExit("gen_wine_ids: bad wine_ref %r" % f[2])
        n = "NXW_" + m.group(1)
        if n in names: raise SystemExit("gen_wine_ids: wine function %s of ids %d and %s" % (m.group(1), names[n], f[0]))
        names[n] = int(f[0]); rows.append((int(f[0]), n, f[1], f[2]))
    ids = [r[0] for r in rows]
    if len(set(ids)) != len(ids): raise SystemExit("gen_wine_ids: duplicate id")
    os.makedirs(out, exist_ok=True)
    s = ["// wine_fixme_ids.gen.h: GENERATED by gen/gen_wine_ids.py from verify/wine_fixme.tsv (the only table of ids). Do not edit.", "#pragma once", "#include <stdint.h>", "enum : uint32_t {"]
    s += ["    %s = %d,   // %s: %s" % (n, i, c, w) for i, n, c, w in sorted(rows)]
    s.append("};")
    open(os.path.join(out, "wine_fixme_ids.gen.h"), "w").write("\n".join(s) + "\n")


if __name__ == "__main__":
    main(sys.argv)
