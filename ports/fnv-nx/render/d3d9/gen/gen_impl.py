#!/usr/bin/env python3
"""gen_impl.py OUTDIR [spec.json]: one concrete class per spec interface (Nx<Iface> : I<Iface>), declarations only.
Outputs (not checked in):
  d9impl.gen.h          class declarations: EVERY spec method of every interface (inherited slots repeated, as the spec lists them), `override`
                        against the shim header so a wrong signature is a compile error. A method with no definition is an undefined symbol (gate G-METHOD).
  d9impl_methods.txt    one `Class::Method` line per spec method (the gate's denominator; the numerator comes from `nm` of the built objects).
  d9impl_unk.gen.cpp    class infos (IID lattice from the spec's `base` chain, resource type) and the definitions that are one rule for all classes:
                        IUnknown, GetDevice, GetContainer, GetDirect3D, private data, priority, PreLoad, GetType -> NxObj (dev/obj.h).
Hooks (dev/d9impl_hooks.h): `NX_BASES_<Class>` = the one non-interface base of a class (default NxObj).
Exit 2 naming the item when a spec method listed in COMMON has a signature other than the one NxObj implements."""
import json, os, re, sys
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "..", "spec", "d3d9_spec.json")
RES_TYPES = {"IDirect3DSurface9": "SURFACE", "IDirect3DVolume9": None, "IDirect3DTexture9": "TEXTURE", "IDirect3DVolumeTexture9": "VOLUMETEXTURE",
             "IDirect3DCubeTexture9": "CUBETEXTURE", "IDirect3DVertexBuffer9": "VERTEXBUFFER", "IDirect3DIndexBuffer9": "INDEXBUFFER"}
DEV = ["struct IDirect3DDevice9**"]
NO_COMMON = {"IDirect3DShaderValidator9"}   # Wine 9.0 d3d9_main.c: one static stub object whose IUnknown is not the reference-counted NxObj model; dev/x1_validator.cpp defines every method
# spec method name -> (NxObj member, ret, [ctypes]); checked against the spec, never guessed
COMMON = {"QueryInterface": ("qi", "HRESULT", ["REFIID", "void**"]), "AddRef": ("addref", "ULONG", []), "Release": ("release", "ULONG", []),
          "GetDevice": ("getDevice", "HRESULT", DEV), "GetContainer": ("getContainer", "HRESULT", ["REFIID", "void**"]),
          "GetDirect3D": ("getDirect3D", "HRESULT", ["IDirect3D9**"]),
          "SetPrivateData": ("setPrivateData", "HRESULT", ["REFGUID", "const void *", "DWORD", "DWORD"]),
          "GetPrivateData": ("getPrivateData", "HRESULT", ["REFGUID", "void*", "DWORD*"]), "FreePrivateData": ("freePrivateData", "HRESULT", ["REFGUID"]),
          "SetPriority": ("setPriority", "DWORD", ["DWORD"]), "GetPriority": ("getPriority", "DWORD", []), "PreLoad": ("preLoad", "void", []),
          "GetType": ("getType", "D3DRESOURCETYPE", [])}


def cname(i):
    if i == "IUnknown": return "NxUnknown"
    r = i[len("IDirect3D"):]  # IDirect3DDevice9 -> NxDevice9; the factory IDirect3D9(Ex) keeps its name (NxDirect3D9)
    return "Nx" + (i[1:] if r[:1].isdigit() else r)


def guid(s):
    p = s.split("-"); b = p[3] + p[4]
    return "{0x%s, 0x%s, 0x%s, {%s}}" % (p[0], p[1], p[2], ", ".join("0x" + b[k:k + 2] for k in range(0, 16, 2)))


def main():
    out = sys.argv[1]; spec = json.load(open(sys.argv[2] if len(sys.argv) > 2 else SPEC)); os.makedirs(out, exist_ok=True)
    ifs = spec["interfaces"]; by = {}
    for m in spec["methods"]: by.setdefault(m["iface"], []).append(m)
    h = ['// generated by gen_impl.py; do not edit', '#pragma once', '#include "../dev/d9impl_hooks.h"', '']
    cpp = ['// generated by gen_impl.py; do not edit', '#include "d9impl.gen.h"', '']
    names = []
    order = [i for i in ifs]
    for i in order:
        c = cname(i); ms = by.get(i, [])
        h.append(f"extern const NxClassInfo nx_ci_{c};")
        h.append(f"#ifndef NX_BASES_{c}\n#define NX_BASES_{c} NxObj\n#endif")
        h.append(f"struct {c} : {i}, NX_BASES_{c} {{")
        ce = "constexpr " if i in NO_COMMON else ""   # a static object of such a class is constant-initialised (no first-use construction)
        h.append(f"    {ce}{c}() {{ nx_obj_init(static_cast<NxObj*>(this), static_cast<IUnknown*>(this), &nx_ci_{c}); }}")
        for m in ms:
            ps = ", ".join(f"{p['ctype']} {p['name']}" for p in m["params"])
            h.append(f"    virtual {m['ret']} STDMETHODCALLTYPE {m['name']}({ps}) override;  // slot {m['slot']}")
            names.append(f"{c}::{m['name']}")
        h.append("};")
        # class info: IID chain self -> IUnknown
        chain = []; k = i
        while k: chain.append(k); k = ifs[k]["base"]
        chain = [k for k in chain if ifs[k]["iid"]]   # an interface whose IID no source gives (`iid: null`, IDirect3DShaderValidator9) is not in the lattice: QueryInterface answers its bases only
        cpp.append(f"static const GUID nx_g_{c}[] = {{ " + ", ".join(guid(ifs[k]["iid"]) for k in chain) + " };")
        t = RES_TYPES.get(i)
        cpp.append(f"static void nx_destroy_{c}(NxObj* o) {{ delete static_cast<{c}*>(o); }}")
        cpp.append(f"const NxClassInfo nx_ci_{c} = {{\"{i}\", nx_g_{c}, {len(chain)}, {'D3DRTYPE_' + t if t else 0}, &nx_destroy_{c}}};")
        for m in ms:
            if m["name"] not in COMMON or i in NO_COMMON: continue
            mem, ret, cts = COMMON[m["name"]]
            if m["name"] == "GetType" and m["ret"] != "D3DRESOURCETYPE": continue
            nz = lambda x: x.replace(" ", "")
            if m["ret"] != ret or [nz(p["ctype"]) for p in m["params"]] != [nz(c) for c in cts]:
                sys.stderr.write(f"gen_impl: {i}::{m['name']} signature {m['ret']}({[p['ctype'] for p in m['params']]}) differs from NxObj::{mem}\n"); sys.exit(2)
            ps = ", ".join(f"{p['ctype']} {p['name']}" for p in m["params"]); args = ", ".join(p["name"] for p in m["params"])
            cpp.append(f"{ret} STDMETHODCALLTYPE {c}::{m['name']}({ps}) {{ {'' if ret == 'void' else 'return '}NxObj::{mem}({args}); }}")
        cpp.append("")
    open(os.path.join(out, "d9impl.gen.h"), "w").write("\n".join(h) + "\n")
    open(os.path.join(out, "d9impl_unk.gen.cpp"), "w").write("\n".join(cpp) + "\n")
    open(os.path.join(out, "d9impl_methods.txt"), "w").write("\n".join(names) + "\n")
    print(f"gen_impl: {len(order)} classes, {len(names)} methods")


if __name__ == "__main__":
    main()
