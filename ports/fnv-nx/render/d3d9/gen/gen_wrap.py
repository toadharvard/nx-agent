#!/usr/bin/env python3
"""gen_wrap.py OUTDIR [SPEC.json]: generates the D3D9 journaling wrapper (RD1) from d3d9_spec.json:
   OUTDIR/d9wrap.gen.h, d9wrap.gen.cpp, d9wrap.manifest.txt.  Exits 2 naming the item when the spec has a kind, rule function, effect or
   field kind that has no emitter (no fallbacks).  See README.md."""
import hashlib, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.dont_write_bytecode = True
from gen_expr import GenError                                  # noqa: E402
from gen_meth import Meth                                      # noqa: E402
import gen_tab as T                                            # noqa: E402


def generate(spec, raw, out):
    names = sorted(spec["interfaces"]); by = {n: sorted([m for m in spec["methods"] if m["iface"] == n], key=lambda m: m["slot"]) for n in names}
    for n in names:
        if [m["slot"] for m in by[n]] != list(range(spec["interfaces"][n]["slots"])): raise GenError(f"{n}: methods do not cover slots 0..{spec['interfaces'][n]['slots'] - 1}")
    sha = hashlib.sha256(raw).digest(); used = set(); man = []
    ids = T.ids(spec, names)
    H = ["// generated by gen_wrap.py from d3d9_spec.json; do not edit", "#ifndef D9WRAP_GEN_H", "#define D9WRAP_GEN_H", '#include "d9stream.h"', ids[0],
         "extern const unsigned char d9wrap_spec_sha256[32];   /* pass to d9s_open */"]
    C = ['#include "d9wrap.gen.h"', "static inline uint64_t d9x_min(uint64_t a, uint64_t b) { return a < b ? a : b; }", "static inline uint64_t d9x_max(uint64_t a, uint64_t b) { return a > b ? a : b; }",
         "uint64_t d9g_rows(uint64_t, uint64_t); uint64_t d9g_rowbytes(uint64_t, uint64_t); uint64_t d9g_verts(uint64_t, uint64_t); uint64_t d9g_index_size(uint64_t); uint64_t d9g_sm_bytes(const void *);",
         "const unsigned char d9wrap_spec_sha256[32] = {" + ",".join(str(b) for b in sha) + "};", ids[1]]
    C += ids[2:] + T.structs(spec)
    body = []
    for n in names:
        H.append(f"class W_{n} final : public {n} {{ public: D9Obj *o; {n} *r; W_{n}(D9Obj *o_) : o(o_), r(({n} *)o_->real) {{}}")
        for m in by[n]:
            H.append(f"  {m['ret']} STDMETHODCALLTYPE {m['name']}({', '.join(q['ctype'] + ' ' + q['name'] for q in m['params'])}) override;")
            L, u = Meth(spec, names, m).emit(); body += L; used |= {(n, p) for p in u}; man.append(f"M {n} {m['slot']} {m['name']}")
        H.append("};")
    unw = []
    for i, e in enumerate(spec["exports"]):
        if "params" not in e or "ret_kind" not in e: unw.append(i); man.append(f"U {i} {e['name']}"); continue
        L, u = Meth(spec, names, e, export=i).emit(); body += L; man.append(f"E {i} {e['name']}")
        H.append(f"{e['ret']} d9wrap_{e['name']}({', '.join([e['ret'] + ' (WINAPI *d9_real)(' + (', '.join(q['ctype'] for q in e['params']) or 'void') + ')'] + [q['ctype'] + ' ' + q['name'] for q in e['params']])});")
    if unw: H.append("/* exports without a signature in the spec (cannot be wrapped): " + ", ".join(spec["exports"][i]["name"] for i in unw) + " */")
    H.append("#endif")
    C += T.tables(spec) + T.props(spec, names, used) + body
    C.append("void *d9g_make(int iface, D9Obj *o, void (**del)(void *)) { switch (iface) {")
    for n in names: C.append(f"case D9I_{n}: {{ W_{n} *w = new W_{n}(o); *del = [](void *p) {{ delete (W_{n} *)p; }}; return (void *)({n} *)w; }}")
    C.append("default: return 0; } }")
    os.makedirs(out, exist_ok=True)
    for f, lines in (("d9wrap.gen.h", H), ("d9wrap.gen.cpp", C), ("d9wrap.manifest.txt", man)):
        with open(os.path.join(out, f), "w") as fh: fh.write("\n".join(lines) + "\n")
    return len(H) + len(C)


def main():
    if len(sys.argv) < 2: sys.exit("usage: gen_wrap.py OUTDIR [d3d9_spec.json]")
    path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "spec", "d3d9_spec.json")
    raw = open(path, "rb").read()
    try:
        n = generate(json.loads(raw), raw, sys.argv[1])
    except GenError as ex:
        print(f"gen_wrap: FAIL: {ex}", file=sys.stderr); sys.exit(2)
    print(f"gen_wrap: wrote {n} lines to {sys.argv[1]}")


if __name__ == "__main__":
    main()
