#!/bin/bash
# Gallium Nine (Mesa st/nine) static libraries (stream S6c-nine).
#
#   DEVKITPRO=<S5 dkp tree> render/nine/build.sh <work dir> [jobs] [switch|host]
#
#   switch (default)  LP64 Switch host-module side: st/nine + nouveau on nvdrv, fnvnx-a64 + libnx  -> <work>/out
#   host              x86-64 Linux, for the host gate (test/gate.py): st/nine + softpipe, system gcc -> <work>/out-host
#                     (DEVKITPRO is not needed for this target)
#
# Sources (cloned into <work>/src if missing; both targets share the patched tree):
#   devkitPro/mesa        branch switch-20.1.0-rc3  (Mesa 20.1.0-rc3 + devkitPro's Switch patch: nouveau
#                         winsys on nvdrv, EGL "switch" platform; st/nine is present in 20.1)
#   devkitPro/libdrm_nouveau  master             (libdrm_nouveau API over libnx nvdrv/nvmap; switch only)
# Our patches (patches/, regenerated by patches/make_patches.py): meson option -Dnine-nx (st/nine without the
# DRM/dri3 d3dadapter9 target, defines NINE_NX) and the window-buffer handle in swapchain9.c.
set -euo pipefail
WORK=$(mkdir -p "$1" && cd "$1" && pwd); JOBS=${2:-4}; TARGET=${3:-switch}
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=$WORK/src; mkdir -p "$SRC"

[ -d "$SRC/mesa" ] || git clone --depth 1 -b switch-20.1.0-rc3 https://github.com/devkitPro/mesa "$SRC/mesa"
# our patches, in order, each applied once (one marker per patch number). 0005 = nvc0 precompiled shader cache (S6d).
for p in "$HERE"/patches/*.patch; do
	m=$SRC/mesa/.fnvnx-$(basename "$p" | cut -c1-4)
	[ -e "$m" ] && continue
	patch -d "$SRC/mesa" -p1 < "$p"
	touch "$m"
done

COMMON=(--default-library static --buildtype release -Db_ndebug=true -Ddri-drivers= -Dvulkan-drivers=
	-Dgallium-nine=true -Dnine-nx=true -Ddri3=false -Dglx=disabled -Dllvm=false -Dgles1=false -Dgles2=false
	-Dgbm=false -Dvalgrind=false -Dlibunwind=false -Dzstd=false -Dgallium-xa=false -Dgallium-vdpau=false
	-Dgallium-va=false -Dgallium-omx=disabled -Dgallium-xvmc=false -Dgallium-opencl=disabled -Dbuild-tests=false)
LIBS=(src/gallium/state_trackers/nine/libnine_st.a src/gallium/auxiliary/libgallium.a src/util/libmesa_util.a
	src/compiler/nir/libnir.a src/compiler/libcompiler.a src/gallium/drivers/softpipe/libsoftpipe.a
	src/util/format/libmesa_format.a src/gallium/auxiliary/libgalliumvl_stub.a src/gallium/winsys/sw/wrapper/libwsw.a)

if [ "$TARGET" = switch ]; then
	: "${DEVKITPRO:?set DEVKITPRO (toolchain/devkita64/setup.sh output)}"
	export PATH=$DEVKITPRO/tools/bin:$DEVKITPRO/devkitA64/bin:$PATH
	OUT=$WORK/out; BUILD=build-nine; AR=aarch64-none-elf-ar
	mkdir -p "$OUT/lib" "$OUT/include"
	[ -d "$SRC/libdrm_nouveau" ] || git clone --depth 1 https://github.com/devkitPro/libdrm_nouveau "$SRC/libdrm_nouveau"
	# libdrm_nouveau (its Makefile uses libnx's switch_rules, i.e. devkitA64 = fnvnx-a64 LP64 multilib)
	make -C "$SRC/libdrm_nouveau" -j"$JOBS" lib/libdrm_nouveau.a
	cp "$SRC/libdrm_nouveau/lib/libdrm_nouveau.a" "$OUT/lib/"
	cp -r "$SRC/libdrm_nouveau/include/." "$OUT/include/"
	mkdir -p "$OUT/lib/pkgconfig"
	sed -e "s,^prefix=.*,prefix=$OUT," "$SRC/libdrm_nouveau/libdrm_nouveau.pc" > "$OUT/lib/pkgconfig/libdrm_nouveau.pc"
	# meson cross file for the fnvnx-a64 LP64 host side (devkitPro's meson-cross.sh equivalent).
	# HAVE_TIMESPEC_GET: newlib 4.6 declares timespec_get, which Mesa 20.1's c11/threads.h would redefine.
	LIBNX=$DEVKITPRO/libnx
	ARCH="-march=armv8-a+crc+crypto -mtune=cortex-a57 -mtp=soft -fPIE -ffunction-sections -fdata-sections"
	cat > "$WORK/cross.txt" <<EOF
[binaries]
c = 'aarch64-none-elf-gcc'
cpp = 'aarch64-none-elf-g++'
ar = 'aarch64-none-elf-gcc-ar'
strip = 'aarch64-none-elf-strip'
pkgconfig = 'pkg-config'

[properties]
needs_exe_wrapper = true
pkg_config_libdir = '$OUT/lib/pkgconfig'

[built-in options]
c_args = [$(printf "'%s'," $ARCH) '-D__SWITCH__', '-DHAVE_TIMESPEC_GET', '-I$LIBNX/include', '-I$OUT/include']
cpp_args = [$(printf "'%s'," $ARCH) '-D__SWITCH__', '-DHAVE_TIMESPEC_GET', '-I$LIBNX/include', '-I$OUT/include']
c_link_args = ['-specs=$LIBNX/switch.specs', '-L$LIBNX/lib', '-L$OUT/lib']
cpp_link_args = ['-specs=$LIBNX/switch.specs', '-L$LIBNX/lib', '-L$OUT/lib']

[host_machine]
system = 'horizon'
cpu_family = 'aarch64'
cpu = 'cortex-a57'
endian = 'little'
EOF
	cd "$SRC/mesa"
	[ -d $BUILD ] || meson setup $BUILD --cross-file "$WORK/cross.txt" --prefix "$OUT" "${COMMON[@]}" \
		-Dplatforms=switch -Dgallium-drivers=nouveau,swrast -Dshared-glapi=true -Degl=true
	LIBS+=(src/gallium/winsys/nouveau/switch/libnouveauwinsys.a src/gallium/drivers/nouveau/libnouveau.a)
elif [ "$TARGET" = host ]; then
	OUT=$WORK/out-host; BUILD=build-host; AR=ar
	mkdir -p "$OUT/lib"
	cd "$SRC/mesa"
	[ -d $BUILD ] || meson setup $BUILD --prefix "$OUT" "${COMMON[@]}" \
		-Db_staticpic=true -Dplatforms= -Dgallium-drivers=swrast -Degl=false -Dshared-glapi=false
else
	echo "unknown target $TARGET (switch|host)" >&2; exit 2
fi

ninja -C $BUILD -j"$JOBS" ${NINJA_KEEP_GOING:+-k 0} "${LIBS[@]}"
# meson writes thin archives (member paths only): repack as ordinary archives so they can leave the tree
for a in "${LIBS[@]}"; do
	d=$BUILD/$(dirname "$a"); n=$(basename "$a"); rm -f "$OUT/lib/$n"
	(cd "$d" && $AR t "$n" | xargs $AR rcs "$OUT/lib/$n")
done
echo "nine ($TARGET): $OUT/lib"
