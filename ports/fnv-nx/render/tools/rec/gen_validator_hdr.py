#!/usr/bin/env python3
"""gen_validator_hdr.py SHIM_D3D9_H OUT.h: extracts the D3DSHADERVALIDATORCALLBACK typedef and the IDirect3DShaderValidator9 struct, verbatim, from shim/include/d3d9.h
(the one place of that declaration) into OUT.h, for the recorder build: the mingw-w64 <d3d9.h> does not declare them and d9wrap.gen.h wraps every interface of the spec.
FNVNX_D3D_METHOD is taken from the same file (its untraced definition); FNVNX_D3D_TRACED is empty. Fails (exit 1) when anything is not found exactly once."""
import re, sys
src = open(sys.argv[1], encoding="utf-8").read().splitlines()
def one(pred, what):
    r = [i for i, l in enumerate(src) if pred(l)]
    if len(r) != 1: sys.exit("gen_validator_hdr: %s: found %d times in %s" % (what, len(r), sys.argv[1]))
    return r[0]
m = one(lambda l: re.match(r"#define FNVNX_D3D_METHOD\(ret, name\) FNVNX_D3D_TRACED virtual ret STDMETHODCALLTYPE name$", l), "FNVNX_D3D_METHOD define")
t = one(lambda l: l.startswith("typedef HRESULT (STDMETHODCALLTYPE *D3DSHADERVALIDATORCALLBACK)"), "D3DSHADERVALIDATORCALLBACK typedef")
s = one(lambda l: l.startswith("struct IDirect3DShaderValidator9 : public IUnknown"), "IDirect3DShaderValidator9 struct")
e = next((i for i in range(s, len(src)) if src[i] == "};"), None)
if e is None or s != t + 1: sys.exit("gen_validator_hdr: struct does not directly follow the typedef or has no closing brace")
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write(
    "/* generated by gen_validator_hdr.py from shim/include/d3d9.h lines %d-%d (do not edit) */\n#include <windows.h>\n#include <d3d9.h>\n#define FNVNX_D3D_TRACED\n%s\n%s\n" % (t + 1, e + 1, src[m], "\n".join(src[t:e + 1])))
