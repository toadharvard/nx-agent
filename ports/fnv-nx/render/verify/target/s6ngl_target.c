/* V6n TARGET 2: v6n_target.h on S6n's own GL 4.5 reference backend (render/native/gl/nxgl.c) through its
 * NxGpuApi and command stream (render/native/include/nx/gpu_abi.h), with S6n's translator for every state and
 * S6n's shared D3D9 epilogue (render/native/shaders/d3d9_epilogue.glsl, fog + alpha test).
 *
 * V6n supplies only what S6n has no code for yet: the fixed-function vertex/pixel model (the same model as
 * gl_target.c, written as deko3d-flavour GLSL against S6n's binding rules) and the mapping of D3D9 calls onto
 * S6n's stream (one DefineState per draw, BeginPass for each Clear).
 * Limits of S6n's API that this adapter reports as errors instead of emulating: Clear restricted to a viewport /
 * scissor sub-rectangle (BeginPass clears the whole target), read-back of depth/stencil and of float targets
 * (NxReadback is RGBA8 colour only). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "v6n_target.h"
#include "d3d9_state.h"
#include "nx/gpu_abi.h"
#include "nxgl.h"
#include "s6n_epilogue.h"   /* generated by build.sh: the expanded text of d3d9_epilogue.glsl as S6N_EPILOGUE */

static const char* VS =
    "#version 460\n"
    "layout(location=0) in vec4 aPos; layout(location=1) in vec4 aDiff; layout(location=2) in vec4 aSpec;\n"
    "layout(location=3) in vec2 aUV;\n"
    "layout(std140, binding=0) uniform V { vec4 vp; mat4 proj; ivec4 mode; vec4 fogp; };\n"
    "layout(location=0) out vec2 vUV; layout(location=1) out vec4 vDiff; layout(location=2) out float vFog;\n"
    "layout(location=3) flat out vec4 vDiffF; layout(location=4) out vec4 vSpec; layout(location=5) flat out vec4 vSpecF;\n"
    "void main() {\n"
    "  vec4 d = aDiff.bgra, s = aSpec.bgra;\n"   /* D3DCOLOR bytes B,G,R,A */
    "  if (mode.x != 0) {\n"
    "    float w = 1.0 / aPos.w;\n"
    "    vec2 ndc = vec2((aPos.x - vp.x) * 2.0 / vp.z - 1.0, 1.0 - (aPos.y - vp.y) * 2.0 / vp.w);\n"
    "    gl_Position = vec4(ndc * w, aPos.z * w, w);\n"
    "    vFog = s.a;\n"
    "  } else {\n"
    "    gl_Position = proj * vec4(aPos.xyz, 1.0);\n"
    "    float z = abs(aPos.z);\n"
    "    if (mode.y == 1) vFog = exp2(-(z * fogp.z) * 1.442695);\n"
    "    else if (mode.y == 2) { float t = z * fogp.z; vFog = exp2(-(t * t) * 1.442695); }\n"
    "    else if (mode.y == 3) vFog = clamp((fogp.x - z) * fogp.y, 0.0, 1.0);\n"
    "    else vFog = s.a;\n"
    "  }\n"
    "  vDiff = d; vDiffF = d; vSpec = s; vSpecF = s; vUV = aUV;\n"
    "}\n";
static const char* FS_HEAD =
    "#version 460\n";
static const char* FS_BODY =
    "layout(location=0) in vec2 vUV; layout(location=1) in vec4 vDiff; layout(location=2) in float vFog;\n"
    "layout(location=3) flat in vec4 vDiffF; layout(location=4) in vec4 vSpec; layout(location=5) flat in vec4 vSpecF;\n"
    "layout(binding=0) uniform sampler2D uTex0; layout(binding=1) uniform sampler2D uTex1;\n"
    "layout(std140, binding=0) uniform F { ivec4 st[2]; ivec4 stb[2]; vec4 tfactor; vec4 cst[2]; ivec4 flags; };\n"
    "layout(location=0) out vec4 oCol;\n"
    "vec4 D, S, T[2], CUR, TMP;\n"
    "vec4 arg(int a, int s) {\n"
    "  int src = a & 15; vec4 v;\n"
    "  if (src == 0) v = D; else if (src == 1) v = CUR; else if (src == 2) v = T[s]; else if (src == 3) v = tfactor;\n"
    "  else if (src == 4) v = S; else if (src == 5) v = TMP; else v = cst[s];\n"
    "  if ((a & 0x10) != 0) v = 1.0 - v;\n"
    "  if ((a & 0x20) != 0) v = v.aaaa;\n"
    "  return v;\n"
    "}\n"
    "vec4 op(int o, vec4 a1, vec4 a2, vec4 a0, int s) {\n"
    "  if (o == 2) return a1; if (o == 3) return a2; if (o == 4) return a1 * a2; if (o == 5) return 2.0 * a1 * a2;\n"
    "  if (o == 6) return 4.0 * a1 * a2; if (o == 7) return a1 + a2; if (o == 8) return a1 + a2 - 0.5;\n"
    "  if (o == 9) return 2.0 * (a1 + a2 - 0.5); if (o == 10) return a1 - a2; if (o == 11) return a1 + a2 - a1 * a2;\n"
    "  if (o == 12) return mix(a2, a1, D.a); if (o == 13) return mix(a2, a1, T[s].a);\n"
    "  if (o == 14) return mix(a2, a1, tfactor.a); if (o == 16) return mix(a2, a1, CUR.a);\n"
    "  if (o == 24) return vec4(clamp(4.0 * dot(a1.rgb - 0.5, a2.rgb - 0.5), 0.0, 1.0));\n"
    "  if (o == 25) return a0 + a1 * a2; if (o == 26) return mix(a2, a1, a0);\n"
    "  return a1;\n"
    "}\n"
    "vec4 sat(int o, vec4 v) {\n"
    "  if (o == 2 || o == 3 || o == 4 || o == 17 || o == 12 || o == 13 || o == 14 || o == 16 || o == 22 || o == 23 || o == 26) return v;\n"
    "  return clamp(v, 0.0, 1.0);\n"
    "}\n"
    "void main() {\n"
    "  D = flags.x != 0 ? vDiffF : vDiff; S = flags.x != 0 ? vSpecF : vSpec;\n"
    "  T[0] = texture(uTex0, vUV); T[1] = texture(uTex1, vUV);\n"
    "  CUR = D; TMP = vec4(0.0);\n"
    "  for (int s = 0; s < 2; s++) {\n"
    "    if (st[s].x == 1) break;\n"
    "    vec3 c = sat(st[s].x, op(st[s].x, arg(st[s].y, s), arg(st[s].z, s), arg(st[s].w, s), s)).rgb;\n"
    "    float a = st[s].x == 24 ? c.r : stb[s].x == 1 ? CUR.a : sat(stb[s].x, op(stb[s].x, arg(stb[s].y, s), arg(stb[s].z, s), arg(stb[s].w, s), s)).a;\n"
    "    CUR = vec4(c, a);\n"
    "  }\n"
    "  if (flags.y != 0) CUR.rgb += S.rgb;\n"
    "  oCol = nx_d3d9_epilogue(CUR, vFog);\n"
    "}\n";

#define CALL1(f, a) ((uint64_t (*)(uint64_t))(uintptr_t)(f))((uint64_t)(uintptr_t)(a))
#define BLOCK (4u << 20)
#define MAXW (1u << 18)

struct V6nTarget {
    const NxGpuApi* api;
    int w, h; uint32_t rtf, dsf;
    uint32_t colorImg, depthImg, vs, fs, mem, nextState;
    uint8_t* block; uint32_t used;
    uint32_t cmd[MAXW]; uint32_t nw;
    uint32_t rs[NXD3D_RS_COUNT]; uint32_t samp[2][NXD3D_SAMP_COUNT]; uint32_t tss[2][33];
    uint32_t tex[2];      /* image id (0 = none) */
    uint32_t texfmt[2];
    NxD3D9Viewport vp; NxD3D9Rect sc; float proj[16];
    int err; uint32_t white;
    V6nReadback rb;
};
static int g_live;

static void emit(V6nTarget* t, uint32_t op, const uint32_t* a, uint32_t n) {
    if (t->nw + 1 + n > MAXW) { t->err = 1; return; }
    t->cmd[t->nw++] = op | n << 16;
    memcpy(t->cmd + t->nw, a, n * 4); t->nw += n;
}
static uint32_t fb(float f) { uint32_t u; memcpy(&u, &f, 4); return u; }
static uint32_t put(V6nTarget* t, const void* p, uint32_t n) {   /* 256-aligned allocation in the memory block */
    uint32_t off = (t->used + 255) & ~255u;
    if (off + n > BLOCK) { t->err = 1; return 0; }
    memcpy(t->block + off, p, n); t->used = off + n;
    return off;
}
static void begin_pass(V6nTarget* t, uint32_t flags, uint32_t argb, float z, uint32_t s) {
    uint32_t rgba = ((argb >> 16) & 0xFF) | (argb & 0xFF00) | (argb & 0xFF) << 16 | (argb & 0xFF000000u);
    uint32_t a[8] = {t->colorImg, t->depthImg, flags, rgba, fb(z), s, (uint32_t)t->w, (uint32_t)t->h};
    emit(t, NxOp_BeginPass, a, 8);
}
static uint32_t shader(const NxGpuApi* api, uint32_t stage, const char* src) {
    NxShaderDesc d; memset(&d, 0, sizeof d);
    d.stage = stage; d.glsl = (uint64_t)(uintptr_t)src; d.glsl_size = (uint32_t)strlen(src);
    return (uint32_t)CALL1(api->shader_create, &d);
}

static V6nTarget* s_begin2(int w, int h, uint32_t rtf, uint32_t dsf, char* err, int errlen);
static V6nTarget* s_begin(int w, int h, uint32_t rtf, uint32_t dsf, char* err, int errlen) {
    V6nTarget* t = s_begin2(w, h, rtf, dsf, err, errlen);
    if (!t && g_live) { nxgl_destroy(); g_live = 0; }
    return t;
}
static V6nTarget* s_begin2(int w, int h, uint32_t rtf, uint32_t dsf, char* err, int errlen) {
    if (g_live) { snprintf(err, errlen, "one target at a time"); return NULL; }
    V6nTarget* t = calloc(1, sizeof *t);
    t->api = nxgl_create(0, 0, err, (size_t)errlen);
    if (!t->api) { free(t); return NULL; }
    g_live = 1;
    t->w = w; t->h = h; t->rtf = rtf; t->dsf = dsf; t->nextState = 1;
    NxFormatInfo fi = nx_d3d9_format(rtf);
    if (!fi.format || !(fi.flags & NXFMT_RENDER) || fi.format == NxFmt_RGBA16F || fi.format == NxFmt_RGBA32F) {
        snprintf(err, errlen, "rt format %u: S6n read-back is RGBA8 only", rtf); return NULL;
    }
    NxImageDesc d; memset(&d, 0, sizeof d);
    d.width = (uint16_t)w; d.height = (uint16_t)h; d.format = fi.format; d.flags = NxImg_RenderTarget;
    t->colorImg = (uint32_t)CALL1(t->api->image_create, &d);
    if (dsf) {
        NxFormatInfo di = nx_d3d9_format(dsf);
        d.format = di.format; d.flags = NxImg_Depth;
        t->depthImg = (uint32_t)CALL1(t->api->image_create, &d);
        if (!t->depthImg) { snprintf(err, errlen, "depth image %u", dsf); return NULL; }
    }
    uint8_t white[4] = {255, 255, 255, 255};   /* Nine's unbound texture reads (1,1,1,1) */
    memset(&d, 0, sizeof d); d.width = 1; d.height = 1; d.format = NxFmt_RGBA8; d.data = (uint64_t)(uintptr_t)white; d.data_size = 4;
    t->white = (uint32_t)CALL1(t->api->image_create, &d);
    t->vs = shader(t->api, NxStage_Vertex, VS);
    size_t n = strlen(FS_HEAD) + strlen(S6N_EPILOGUE) + strlen(FS_BODY) + 1;
    char* fs = malloc(n); snprintf(fs, n, "%s%s%s", FS_HEAD, S6N_EPILOGUE, FS_BODY);
    t->fs = shader(t->api, NxStage_Fragment, fs); free(fs);
    if (!t->vs || !t->fs) { snprintf(err, errlen, "shader: %s", nxgl_last_error()); return NULL; }
    if (posix_memalign((void**)&t->block, 4096, BLOCK)) return NULL;
    NxMemBlockDesc m = {(uint64_t)(uintptr_t)t->block, BLOCK, NxMem_Generic};
    t->mem = (uint32_t)CALL1(t->api->mem_create, &m);
    NxVtxLayout L; memset(&L, 0, sizeof L);
    L.count = 4; L.stride = sizeof(V6nVertex);
    L.attr[0].offset = 0; L.attr[0].type = NxAttr_Float32; L.attr[0].components = 4;
    L.attr[1].offset = 16; L.attr[1].type = NxAttr_Unorm8; L.attr[1].components = 4;
    L.attr[2].offset = 20; L.attr[2].type = NxAttr_Unorm8; L.attr[2].components = 4;
    L.attr[3].offset = 24; L.attr[3].type = NxAttr_Float32; L.attr[3].components = 2;
    uint32_t la[10]; la[0] = 1; memcpy(la + 1, &L, sizeof L);
    emit(t, NxOp_DefineLayout, la, 10);
    nx_d3d9_default_rs(t->rs);
    for (int s = 0; s < 2; s++) {
        nx_d3d9_default_samp(t->samp[s]);
        t->tss[s][1] = s == 0 ? 4 : 1; t->tss[s][2] = 2; t->tss[s][3] = 1;
        t->tss[s][4] = s == 0 ? 2 : 1; t->tss[s][5] = 2; t->tss[s][6] = 1;
        t->tss[s][26] = 1; t->tss[s][27] = 1; t->tss[s][11] = s;
    }
    t->vp = (NxD3D9Viewport){0, 0, (uint32_t)w, (uint32_t)h, 0.0f, 1.0f};
    t->sc = (NxD3D9Rect){0, 0, w, h};
    for (int i = 0; i < 16; i++) t->proj[i] = (i % 5 == 0) ? 1.0f : 0.0f;
    begin_pass(t, 0, 0, 1.0f, 0);
    return t;
}
static void s_end(V6nTarget* t) {
    nxgl_destroy(); g_live = 0;
    free(t->block); free(t->rb.color); free(t);
}
static void s_clear(V6nTarget* t, uint32_t flags, uint32_t color, float z, uint32_t s) {
    /* D3D9 (Nine device9.c user_assert): ZBUFFER without a depth surface, or STENCIL without a stencil format,
     * make the whole Clear D3DERR_INVALIDCALL: nothing is cleared */
    if ((flags & 2) && !t->dsf) return;
    if ((flags & 4) && !(t->dsf && (nx_d3d9_format(t->dsf).flags & NXFMT_STENCIL))) return;
    int full = t->vp.X == 0 && t->vp.Y == 0 && (int)t->vp.Width >= t->w && (int)t->vp.Height >= t->h;
    if (t->rs[174] && (t->sc.left > 0 || t->sc.top > 0 || t->sc.right < t->w || t->sc.bottom < t->h)) full = 0;
    if (!full) { fprintf(stderr, "s6n-gl: Clear of a sub-rectangle has no S6n op (BeginPass clears the target)\n"); t->err = 1; return; }
    emit(t, NxOp_EndPass, NULL, 0);
    begin_pass(t, flags & 7, color, z, s);
}
static void s_rs(V6nTarget* t, uint32_t st, uint32_t v) { if (st < NXD3D_RS_COUNT) t->rs[st] = v; }
static void s_samp(V6nTarget* t, uint32_t s, uint32_t ty, uint32_t v) { if (s < 2 && ty < NXD3D_SAMP_COUNT) t->samp[s][ty] = v; }
static void s_tss(V6nTarget* t, uint32_t s, uint32_t ty, uint32_t v) { if (s < 2 && ty < 33) t->tss[s][ty] = v; }
int v6n_level_bytes(uint32_t fmt, int w, int h);
static int s_tex(V6nTarget* t, uint32_t stage, uint32_t fmt, int w, int h, int levels, const uint8_t* const* data) {
    if (stage > 1) return 0;
    NxFormatInfo fi = nx_d3d9_format(fmt);
    if (!fi.format) return 0;
    size_t total = 0;
    for (int l = 0; l < levels; l++) total += v6n_level_bytes(fmt, w >> l > 0 ? w >> l : 1, h >> l > 0 ? h >> l : 1);
    uint8_t* buf = malloc(total), *p = buf;
    for (int l = 0; l < levels; l++) { int n = v6n_level_bytes(fmt, w >> l > 0 ? w >> l : 1, h >> l > 0 ? h >> l : 1); memcpy(p, data[l], n); p += n; }
    if (fi.flags & NXFMT_CONVERT) {   /* nx/state.h: NXFMT_CONVERT texels go through nx_d3d9_convert() */
        uint32_t cap = nx_d3d9_converted_size(fmt, w, h, levels, 1);
        uint8_t* conv = malloc(cap ? cap : 1);
        uint32_t got = nx_d3d9_convert(fmt, w, h, levels, 1, buf, (uint32_t)total, conv, cap);
        free(buf);
        if (!got) { free(conv); return 0; }
        buf = conv; total = got;
    }
    NxImageDesc d; memset(&d, 0, sizeof d);
    d.width = (uint16_t)w; d.height = (uint16_t)h; d.format = fi.format; d.mips = (uint8_t)levels;
    d.swizzle = NXIMG_SWIZZLE(fi.swizzle[0], fi.swizzle[1], fi.swizzle[2], fi.swizzle[3]);
    d.data = (uint64_t)(uintptr_t)buf; d.data_size = (uint32_t)total;
    t->tex[stage] = (uint32_t)CALL1(t->api->image_create, &d);
    t->texfmt[stage] = fmt;
    free(buf);
    return t->tex[stage] != 0;
}
static void s_notex(V6nTarget* t, uint32_t stage) { if (stage < 2) t->tex[stage] = 0; }
static void s_vp(V6nTarget* t, uint32_t x, uint32_t y, uint32_t w, uint32_t h, float mn, float mx) { t->vp = (NxD3D9Viewport){x, y, w, h, mn, mx}; }
static void s_scissor(V6nTarget* t, int32_t l, int32_t tp, int32_t r, int32_t b) { t->sc = (NxD3D9Rect){l, tp, r, b}; }
static void s_proj(V6nTarget* t, const float m[16]) { memcpy(t->proj, m, sizeof t->proj); }
static uint32_t nxprim(uint32_t p) {
    switch (p) { case 1: return NxPrim_Points; case 2: return NxPrim_Lines; case 3: return NxPrim_LineStrip;
                 case 5: return NxPrim_TriStrip; case 6: return NxPrim_TriFan; default: return NxPrim_Triangles; }
}
static uint32_t vcount(uint32_t p, uint32_t n) {
    switch (p) { case 1: return n; case 2: return 2 * n; case 3: return n + 1; case 4: return 3 * n; default: return n + 2; }
}
static int s_draw(V6nTarget* t, uint32_t prim, uint32_t count, int rhw, const V6nVertex* v, int nv) {
    uint32_t n = vcount(prim, count);
    if ((int)n > nv || t->err) return 0;
    NxD3D9Input in; memset(&in, 0, sizeof in);
    in.rs = t->rs; in.ps_version = 0; in.depth_format = t->dsf; in.viewport = t->vp; in.scissor = t->sc;
    NxRenderState st; NxDynamicState dyn; uint32_t sb;
    nx_d3d9_translate(&in, &st, &dyn, &sb);
    uint32_t id = t->nextState++;
    uint32_t ds[12] = {id, t->vs, t->fs, 1};
    for (int i = 0; i < 4; i++) { ds[4 + 2 * i] = (uint32_t)st.w[i]; ds[5 + 2 * i] = (uint32_t)(st.w[i] >> 32); }
    if (!rhw || 1) emit(t, NxOp_DefineState, ds, 12);
    emit(t, NxOp_BindState, &id, 1);
    if (rhw) { dyn.viewport.x = 0.5f; dyn.viewport.y = 0.5f; dyn.viewport.w = (float)t->w; dyn.viewport.h = (float)t->h; }
    uint32_t vpw[6] = {fb(dyn.viewport.x), fb(dyn.viewport.y), fb(dyn.viewport.w), fb(dyn.viewport.h),
                       fb(rhw ? 0.0f : dyn.viewport.minZ), fb(rhw ? 1.0f : dyn.viewport.maxZ)};
    emit(t, NxOp_Viewport, vpw, 6);
    uint32_t scw[4] = {(uint32_t)dyn.scissor.x, (uint32_t)dyn.scissor.y, (uint32_t)dyn.scissor.w, (uint32_t)dyn.scissor.h};
    emit(t, NxOp_Scissor, scw, 4);
    uint32_t bc[4] = {fb(dyn.blendConstant[0]), fb(dyn.blendConstant[1]), fb(dyn.blendConstant[2]), fb(dyn.blendConstant[3])};
    emit(t, NxOp_BlendConst, bc, 4);
    uint32_t db[3] = {fb(dyn.depthBiasUnits), fb(dyn.depthBiasSlope), 0};
    emit(t, NxOp_DepthBias, db, 3);
    struct { float vp[4]; float proj[16]; int32_t mode[4]; float fogp[4]; } vu;
    vu.vp[0] = rhw ? 0.0f : (float)t->vp.X; vu.vp[1] = rhw ? 0.0f : (float)t->vp.Y;
    vu.vp[2] = rhw ? (float)t->w : (float)t->vp.Width; vu.vp[3] = rhw ? (float)t->h : (float)t->vp.Height;
    memcpy(vu.proj, t->proj, sizeof vu.proj);
    int fogmode = (sb >> NXSB_FOG) & 7;
    vu.mode[0] = rhw; vu.mode[1] = (!rhw && t->rs[28] && fogmode == NxFog_Vertex && t->rs[140] <= 3) ? (int)t->rs[140] : 0;
    vu.mode[2] = vu.mode[3] = 0;
    vu.fogp[0] = dyn.fogEnd; vu.fogp[1] = dyn.fogScale; vu.fogp[2] = dyn.fogDensity; vu.fogp[3] = 0;
    struct { int32_t st[2][4]; int32_t stb[2][4]; float tf[4]; float cst[2][4]; int32_t flags[4]; } fu;
    for (int s = 0; s < 2; s++) {
        fu.st[s][0] = t->tss[s][1]; fu.st[s][1] = t->tss[s][2]; fu.st[s][2] = t->tss[s][3]; fu.st[s][3] = t->tss[s][26];
        fu.stb[s][0] = t->tss[s][4]; fu.stb[s][1] = t->tss[s][5]; fu.stb[s][2] = t->tss[s][6]; fu.stb[s][3] = t->tss[s][27];
        nx_d3d9_color(t->tss[s][32], fu.cst[s]);
    }
    nx_d3d9_color(t->rs[60], fu.tf);
    fu.flags[0] = NXRS_GET(st.w[2], NXRS_R_FLAT, 1); fu.flags[1] = t->rs[29] != 0; fu.flags[2] = fu.flags[3] = 0;
    struct { float fogColor[4]; float fogParams[4]; uint32_t modes[4]; } ep;   /* nx/epilogue (d3d9_epilogue.glsl) */
    memcpy(ep.fogColor, dyn.fogColor, 16);
    ep.fogParams[0] = dyn.fogEnd; ep.fogParams[1] = dyn.fogScale; ep.fogParams[2] = dyn.fogDensity; ep.fogParams[3] = dyn.alphaRef;
    ep.modes[0] = (sb >> NXSB_ALPHAFUNC) & 7; ep.modes[1] = fogmode; ep.modes[2] = (sb >> NXSB_ALPHATEST) & 1; ep.modes[3] = 0;
    uint32_t o;
    o = put(t, &vu, sizeof vu); { uint32_t a[5] = {1, 0, t->mem, o, sizeof vu}; emit(t, NxOp_BindUbo, a, 5); }
    o = put(t, &fu, sizeof fu); { uint32_t a[5] = {2, 0, t->mem, o, sizeof fu}; emit(t, NxOp_BindUbo, a, 5); }
    o = put(t, &ep, sizeof ep); { uint32_t a[5] = {2, 2, t->mem, o, sizeof ep}; emit(t, NxOp_BindUbo, a, 5); }
    o = put(t, v, n * sizeof *v); { uint32_t a[3] = {t->mem, o, n * (uint32_t)sizeof *v}; emit(t, NxOp_BindVtx, a, 3); }
    uint32_t th[5] = {NxStage_Fragment, 0, 2, 0, 0};
    for (int s = 0; s < 2; s++) {
        uint32_t img = t->tex[s] ? t->tex[s] : t->white;
        NxD3D9Texture ti = {t->tex[s] ? t->texfmt[s] : 0, 0, 0, 0, 0};
        NxSamplerState ss; nx_d3d9_sampler(t->samp[s], &ti, &ss);
        if ((ss.filter & NXSMP_SRGB) && t->tex[s]) img += 1;   /* gpu_abi.h: id + 1 = the sRGB view */
        uint32_t smp = (uint32_t)CALL1(t->api->sampler_create, &ss);
        th[3 + s] = NX_TEX_HANDLE(img, smp);
    }
    emit(t, NxOp_BindTextures, th, 5);
    uint32_t dr[5] = {nxprim(prim), n, 1, 0, 0};
    emit(t, NxOp_Draw, dr, 5);
    return !t->err;
}
static int s_readback(V6nTarget* t, V6nReadback* out) {
    if (t->err) return 0;
    emit(t, NxOp_EndPass, NULL, 0);
    emit(t, NxOp_End, NULL, 0);
    NxSubmit sub; memset(&sub, 0, sizeof sub);
    sub.stream = (uint64_t)(uintptr_t)t->cmd; sub.words = t->nw; sub.frame = 1;
    if (CALL1(t->api->submit, &sub)) return 0;
    uint8_t* px = malloc((size_t)t->w * t->h * 4);
    NxReadback r; memset(&r, 0, sizeof r);
    r.image = t->colorImg; r.w = t->w; r.h = t->h; r.dst_size = t->w * t->h * 4; r.dst = (uint64_t)(uintptr_t)px;
    if (CALL1(t->api->readback, &r)) { free(px); return 0; }
    V6nReadback* o = &t->rb;
    o->w = t->w; o->h = t->h; o->color = calloc((size_t)t->w * t->h * 4, sizeof(float));
    for (int i = 0; i < t->w * t->h * 4; i++) o->color[i] = px[i];
    free(px);
    NxFormatInfo fi = nx_d3d9_format(t->rtf);
    o->color_channels = (fi.format == NxFmt_BGRX8 || fi.format == NxFmt_RGBX8) ? 3 : 4;
    if (o->color_channels == 3) for (int i = 0; i < t->w * t->h; i++) o->color[4 * i + 3] = 0;
    *out = *o;
    return 1;
}
