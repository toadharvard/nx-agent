#!/usr/bin/env python3
"""Generator of gl4_funcs.h (recipe stage `generated`).

RULE: the entry set is exactly { gl* : the identifier p_gl* occurs in the code (comments and string literals removed) of a
tracked *.c unit of render/gl4 }. The type of an entry is the Khronos function-pointer typedef of that name,
PFN<UPPERCASE NAME>PROC (the naming of glcorearb.h); the compiler proves that the typedef exists. No list is kept by hand:
a new GL call adds its entry, a removed call removes it.

usage: gen_funcs.py <out> <gl4 dir>   (the dir is the mounted /in/... copy of render/gl4)"""
import os, re, sys

out, d = sys.argv[1], sys.argv[2]
names = set()
for f in sorted(os.listdir(d)):
    if f.endswith(".c"):
        s = open(os.path.join(d, f)).read()
        s = re.sub(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'', " ", s, flags=re.S)
        names |= set(re.findall(r"\bp_(gl[A-Za-z0-9_]*)\b", s))
rows = ["X(PFN%sPROC, %s)" % (n.upper(), n) for n in sorted(names)]
with open(out, "w") as o:
    o.write("/* GENERATED by render/gl4/gen_funcs.py: the GL entry points the gl4 units reference (p_gl*), loaded with eglGetProcAddress.\n"
            " * %d entries, sorted by name; type = PFN<NAME>PROC. */\n#ifndef FNVNX_GL4_FUNCS_H\n#define FNVNX_GL4_FUNCS_H\n#define NXGL4_FUNCS(X) \\\n" % len(rows))
    o.write(" \\\n".join("    " + " ".join(rows[i:i + 3]) for i in range(0, len(rows), 3)) + "\n#endif\n")
