#!/usr/bin/env python3
"""Generator of gl4_funcs.h (recipe stage `generated`).

RULE: the entry set is the command set of the OpenGL 4.5 core profile, read from the pinned Khronos registry (external
khronos-glxml, xml/gl.xml): over the <feature api="gl"> elements with number <= 4.5 in file order, the commands of every <require>
that is not limited to another profile, minus the commands of every <remove profile="core">. By the specification this is complete: it needs no
knowledge of which commands gl4 calls, and every conforming 4.5 core context provides all of them. The type of an entry is the
function-pointer typedef PFN<UPPERCASE NAME>PROC of glcorearb.h (the Khronos naming); the compiler proves that the typedef exists.

usage: gen_funcs.py <out> <gl.xml>"""
import sys
import xml.etree.ElementTree as ET

out, xml = sys.argv[1], sys.argv[2]
LIMIT = (4, 5)
cmds = set()
for f in ET.parse(xml).getroot().iter("feature"):
    if f.get("api") != "gl" or tuple(int(x) for x in f.get("number").split(".")) > LIMIT:
        continue
    for e in f:
        names = {c.get("name") for c in e.iter("command")}
        if e.tag == "require" and e.get("profile") in (None, "core"):
            cmds |= names
        elif e.tag == "remove" and e.get("profile") == "core":
            cmds -= names
rows = ["X(PFN%sPROC, %s)" % (n.upper(), n) for n in sorted(cmds)]
with open(out, "w") as o:
    o.write("/* GENERATED by render/gl4/gen_funcs.py from khronos-glxml xml/gl.xml: the %d commands of the OpenGL %d.%d core profile, loaded with eglGetProcAddress.\n"
            " * Sorted by name; type = PFN<NAME>PROC (glcorearb.h). */\n#ifndef FNVNX_GL4_FUNCS_H\n#define FNVNX_GL4_FUNCS_H\n#define NXGL4_FUNCS(X) \\\n" % (len(rows), LIMIT[0], LIMIT[1]))
    o.write(" \\\n".join("    " + " ".join(rows[i:i + 3]) for i in range(0, len(rows), 3)) + "\n#endif\n")
