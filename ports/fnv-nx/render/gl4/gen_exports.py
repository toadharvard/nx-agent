#!/usr/bin/env python3
"""Generator of the linker version script of libnxgl4.so (recipe stage `generated`).

RULE: the exports of the library are the functions declared in gl4.h with the marker NXGL4_EXPORT in front of the declaration; nothing else is
exported (`local: *`). The header is read as C tokens: comments, string and character literals and preprocessor lines (the #define of the marker
itself) are skipped, then a declaration is the tokens from an NXGL4_EXPORT up to the first `;`, and its name is the identifier directly before the
first `(`. A marker that is not followed by such a declaration is an error (the stage fails, no output). Declarations the embedder provides
(nxgl4_guest_ptr, nxgl4_on_present) carry no marker: the library imports them. The order is the order of the header.

usage: gen_exports.py <out> <gl4.h>"""
import sys

MARK = "NXGL4_EXPORT"


def tokens(src):
    i, n, line_start = 0, len(src), True
    while i < n:
        c = src[i]
        if c == "\n":
            line_start = True; i += 1; continue
        if c in " \t\r\f\v":
            i += 1; continue
        if src.startswith("/*", i):
            j = src.find("*/", i + 2)
            if j < 0:
                raise SystemExit("unterminated comment")
            line_start = line_start and "\n" not in src[i:j]; i = j + 2; continue
        if src.startswith("//", i):
            j = src.find("\n", i)
            i = n if j < 0 else j; continue
        if c == "#" and line_start:   # a preprocessor line, with its backslash continuations
            while i < n and src[i] != "\n":
                i = i + 2 if src[i] == "\\" and i + 1 < n else i + 1
            continue
        line_start = False
        if c in "\"'":
            j = i + 1
            while j < n and src[j] != c:
                j += 2 if src[j] == "\\" else 1
            i = j + 1; yield "lit"; continue
        if c.isalpha() or c == "_":
            j = i
            while j < n and (src[j].isalnum() or src[j] == "_"):
                j += 1
            yield src[i:j]; i = j; continue
        if c.isdigit():
            j = i
            while j < n and (src[j].isalnum() or src[j] in "._"):
                j += 1
            yield "lit"; i = j; continue
        yield c; i += 1


out, hdr = sys.argv[1], sys.argv[2]
toks, names, k = list(tokens(open(hdr).read())), [], 0
while k < len(toks):
    if toks[k] != MARK:
        k += 1; continue
    j = k + 1
    while j < len(toks) and toks[j] not in ("(", ";"):
        j += 1
    if j >= len(toks) or toks[j] != "(" or j == k + 1 or not (toks[j - 1][0].isalpha() or toks[j - 1][0] == "_"):
        raise SystemExit("%s is not followed by a function declaration" % MARK)
    names.append(toks[j - 1]); k = j
if not names or len(set(names)) != len(names):
    raise SystemExit("exports: none, or a name twice: %r" % names)
with open(out, "w") as o:
    o.write("/* GENERATED by render/gl4/gen_exports.py from gl4.h: the functions declared with %s. */\n{\n  global: %s;\n  local: *;\n};\n" % (MARK, "; ".join(names)))
