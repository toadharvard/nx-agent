#!/usr/bin/env bash
# firstframe.nro: build_nro.sh <outdir>  ->  <outdir>/firstframe.nro, firstframe.elf  (modelled on toolchain/nro/build.sh)
# Inputs (environment):
#   DEVKITPRO   devkitPro-layout directory with libnx/{include,lib,switch.specs} (e.g. <toolchain>/dkp)
#   DEKO3D      directory with lib/libdeko3d.a
#   NXDK_LIB    libnxdk.a, produced by render/backend/nx/build_dk.sh (the deko3d nxgpu backend; exports nxdk_ext)
#   GCC         aarch64 compiler (default: aarch64-none-elf-gcc on PATH or in $FNVNX_TC/bin)
#   UAM         uam binary for build_dksh.sh (default $FNVNX_SHADERS_DEPS/uam/build/uam)
# Also needs selftest_expect.h in this directory: generated by tests/l6/selftest/test_selftest.py, never written by hand.
set -euo pipefail
OUT=$(mkdir -p "${1:?usage: build_nro.sh <outdir>}" && realpath "$1")
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd); BACK=$(cd "$HERE/.." && pwd); P=$(cd "$BACK/../../.." && pwd); TC=$P/toolchain
: "${DEVKITPRO:?set DEVKITPRO}"; : "${DEKO3D:?set DEKO3D (directory with lib/libdeko3d.a)}"
: "${NXDK_LIB:?set NXDK_LIB to libnxdk.a, produced by render/backend/nx/build_dk.sh}"
[[ -f $NXDK_LIB ]] || { echo "build_nro.sh: NXDK_LIB file is missing: $NXDK_LIB (run render/backend/nx/build_dk.sh first)" >&2; exit 1; }
[[ -f $DEKO3D/lib/libdeko3d.a ]] || { echo "build_nro.sh: missing $DEKO3D/lib/libdeko3d.a" >&2; exit 1; }
[[ -f $HERE/selftest_expect.h ]] || { echo "build_nro.sh: missing $HERE/selftest_expect.h (run tests/l6/selftest/test_selftest.py)" >&2; exit 1; }
GCC=${GCC:-$(command -v aarch64-none-elf-gcc || echo "${FNVNX_TC:-/nonexistent}/bin/aarch64-none-elf-gcc")}
[[ -x $GCC ]] || { echo "build_nro.sh: aarch64-none-elf-gcc not found (set GCC)" >&2; exit 1; }
SHA=$(git -C "$P" rev-parse --short=12 HEAD)
"$HERE/build_dksh.sh" "$OUT"
python3 -I - "$OUT" <<'PY'
import sys
o = sys.argv[1]; src = []
for n in ("ff_vs", "ff_fs"):
    b = open("%s/%s.dksh" % (o, n), "rb").read()
    src.append("#include <stdint.h>\nconst uint8_t %s_dksh[] __attribute__((aligned(8))) = {%s};\nconst uint32_t %s_dksh_len = %d;\n" % (n, ",".join(map(str, b)), n, len(b)))
open(o + "/ff_dksh.c", "w").write("".join(src))
PY
ARCH="-march=armv8-a+crc+crypto -mtune=cortex-a57 -mtp=soft -fPIE"
CF="$ARCH -O2 -g -Wall -Wextra -Werror -ffunction-sections -fdata-sections -D__SWITCH__"
"$GCC" $CF -DFNV_BUILD_ID="\"$SHA\"" -I"$HERE" -I"$BACK" -I"$DEVKITPRO/libnx/include" -c "$HERE/firstframe_main.c" -o "$OUT/firstframe_main.o"
"$GCC" $CF -I"$HERE" -I"$BACK" -c "$HERE/nxgpu4_selftest.c" -o "$OUT/nxgpu4_selftest.o"
"$GCC" $CF -c "$OUT/ff_dksh.c" -o "$OUT/ff_dksh.o"
"$GCC" -specs="$DEVKITPRO/libnx/switch.specs" $ARCH -Wl,-Map,"$OUT/firstframe.map" "$OUT/firstframe_main.o" "$OUT/nxgpu4_selftest.o" "$OUT/ff_dksh.o" \
	"$NXDK_LIB" -L"$DEKO3D/lib" -ldeko3d -L"$DEVKITPRO/libnx/lib" -lnx -o "$OUT/firstframe.elf"
python3 -I "$TC/tools/elf2nro.py" --nacp-create "$OUT/control.nacp" --name "fnv-nx firstframe" --author "fnv-nx (bring your own game)" --version "$SHA"
python3 -I "$TC/tools/elf2nro.py" "$OUT/firstframe.elf" "$OUT/firstframe.nro" --nacp "$OUT/control.nacp"
echo "build_nro.sh: $OUT/firstframe.nro ($SHA)"
