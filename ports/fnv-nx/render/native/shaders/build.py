#!/usr/bin/env python3
"""Build the native renderer's shader package (stream S6n).

    render/native/shaders/build.py <out dir> [--uam <uam binary>]

Each <name>.vert.glsl / <name>.frag.glsl is one shader. `#include "file"` lines are expanded textually (uam and GL
have no include support). Outputs in <out dir>:
  <name>.<stage>.glsl   expanded GLSL 4.60 (deko3d flavour: per-stage binding slots)
  <name>.<stage>.dksh   uam output (only with --uam, or $UAM)
  nx_shaders.c / nx_shaders.h   the package: a table of {name, stage, glsl, dksh} for both backends
The GL backend turns the same GLSL into GL 4.50 at load time (nxgl_shim_glsl: version + binding = stage*16+n).
"""
import os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
INC = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')


def expand(path, seen=()):
    out = []
    for line in open(path, encoding="utf-8"):
        m = INC.match(line)
        if m:
            inc = os.path.join(os.path.dirname(path), m.group(1))
            if inc in seen:
                raise SystemExit("include cycle: " + inc)
            out.append("// begin %s\n" % m.group(1))
            out.extend(expand(inc, seen + (inc,)))
            out.append("// end %s\n" % m.group(1))
        else:
            out.append(line)
    return out


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 24):
        rows.append("    " + "".join("%d," % b for b in data[i:i + 24]))
    return "\n".join(rows) if rows else "    0,"


def main():
    args = sys.argv[1:]
    if not args:
        raise SystemExit(__doc__)
    out = os.path.abspath(args[0])
    uam = os.environ.get("UAM")
    if "--uam" in args:
        uam = args[args.index("--uam") + 1]
    os.makedirs(out, exist_ok=True)
    shaders = []
    for fn in sorted(os.listdir(HERE)):
        m = re.match(r"^([a-z0-9_]+)\.(vert|frag)\.glsl$", fn)
        if not m:
            continue
        name, stage = m.groups()
        text = "".join(expand(os.path.join(HERE, fn)))
        gpath = os.path.join(out, "%s.%s.glsl" % (name, stage))
        open(gpath, "w").write(text)
        dksh = b""
        if uam:
            dpath = os.path.join(out, "%s.%s.dksh" % (name, stage))
            r = subprocess.run([uam, "-s", stage, "-o", dpath, gpath], capture_output=True, text=True)
            if r.returncode != 0:
                sys.stderr.write(r.stdout + r.stderr)
                raise SystemExit("uam failed on %s" % fn)
            dksh = open(dpath, "rb").read()
        shaders.append((name, stage, text.encode() + b"\0", dksh))
    with open(os.path.join(out, "nx_shaders.h"), "w") as h:
        h.write("/* generated by render/native/shaders/build.py */\n#ifndef NX_SHADERS_H\n#define NX_SHADERS_H\n"
                "#include <stdint.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
                "typedef struct NxShaderBlob { const char* name; uint32_t stage; const uint8_t* glsl; uint32_t glsl_size;\n"
                "    const uint8_t* dksh; uint32_t dksh_size; } NxShaderBlob;\n"
                "extern const NxShaderBlob nx_shader_blobs[];\nextern const uint32_t nx_shader_blob_count;\n"
                "/* index of name.stage (stage 0 vert, 1 frag), -1 if absent */\n"
                "int nx_shader_find(const char* name, uint32_t stage);\n"
                "#ifdef __cplusplus\n}\n#endif\n#endif\n")
    with open(os.path.join(out, "nx_shaders.c"), "w") as c:
        c.write("/* generated by render/native/shaders/build.py */\n#include <string.h>\n#include \"nx_shaders.h\"\n")
        for i, (name, stage, glsl, dksh) in enumerate(shaders):
            c.write("static const uint8_t glsl_%d[] = {\n%s\n};\n" % (i, c_bytes(glsl)))
            c.write("static const uint8_t dksh_%d[] __attribute__((aligned(256))) = {\n%s\n};\n" % (i, c_bytes(dksh)))
        c.write("const NxShaderBlob nx_shader_blobs[] = {\n")
        for i, (name, stage, glsl, dksh) in enumerate(shaders):
            c.write('    {"%s", %d, glsl_%d, %d, dksh_%d, %d},\n'
                    % (name, 0 if stage == "vert" else 1, i, len(glsl) - 1, i, len(dksh)))
        c.write("};\nconst uint32_t nx_shader_blob_count = %d;\n" % len(shaders))
        c.write("int nx_shader_find(const char* name, uint32_t stage) {\n"
                "    for (uint32_t i = 0; i < nx_shader_blob_count; i++)\n"
                "        if (nx_shader_blobs[i].stage == stage && !strcmp(nx_shader_blobs[i].name, name)) return (int)i;\n"
                "    return -1;\n}\n")
    print("shaders: %d (%s)" % (len(shaders), "with DKSH" if uam else "GLSL only"))


if __name__ == "__main__":
    main()
