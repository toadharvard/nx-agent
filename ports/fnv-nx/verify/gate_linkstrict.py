COMMON, GLOBAL, WEAK, UNIQUE, IFUNC = 0xFFF2, 1, 2, 10, 10


def elf_symbols(path):
    """[(name, value, size, type, bind, shndx)] of the `.symtab` of an ELF (32 or 64 bit, little endian; relocatable or linked), or None
    when the file has no `.symtab`. Symbol 0, STT_SECTION and STT_FILE are left out."""
    d = open(path, "rb").read()
    if d[:4] != b"\x7fELF" or d[5] != 1 or d[4] not in (1, 2):
        raise ValueError("%s: not a little-endian ELF" % path)
    w64 = d[4] == 2
    shoff, = struct.unpack_from("<Q" if w64 else "<I", d, 0x28 if w64 else 0x20)
    shent, shnum = struct.unpack_from("<HH", d, 0x3A if w64 else 0x2E)
    secs = [struct.unpack_from("<IIQQQQIIQQ" if w64 else "<IIIIIIIIII", d, shoff + i * shent) for i in range(shnum)]   # name type flags addr off size link ...
    out, found = [], False
    for s in secs:
        typ, off, size, link = s[1], s[4], s[5], s[6]
        if typ != 2:
            continue
        found = True
        st = secs[link]
        strtab = d[st[4]:st[4] + st[5]]
        for t in struct.iter_unpack("<IBBHQQ" if w64 else "<IIIBBH", d[off:off + size]):
            n, val, sz, info, shn = (t[0], t[4], t[5], t[1], t[3]) if w64 else (t[0], t[1], t[2], t[3], t[5])
            if n and info & 15 not in (3, 4):
                out.append((strtab[n:strtab.index(b"\0", n)].decode("latin-1"), val, sz, info & 15, info >> 4, shn))
    return out if found else None


def _sections(path):
    """(data, w64, secs, name of a section) of an ELF relocatable, ELF32 or ELF64 little endian. secs: (name_off, type, flags, addr, off,
    size, link, info, align, entsize)."""
    d = open(path, "rb").read()
    if d[:4] != b"\x7fELF" or d[5] != 1 or d[4] not in (1, 2):
        raise ValueError("%s: not a little-endian ELF" % path)
    w64 = d[4] == 2
    shoff, = struct.unpack_from("<Q" if w64 else "<I", d, 0x28 if w64 else 0x20)
    shent, shnum, shstr = struct.unpack_from("<HHH", d, 0x3A if w64 else 0x2E)
    secs = [struct.unpack_from("<IIQQQQIIQQ" if w64 else "<IIIIIIIIII", d, shoff + i * shent) for i in range(shnum)]
    cs = lambda off, n: d[off + n:d.index(b"\0", off + n)].decode("latin-1")
    return d, w64, secs, [cs(secs[shstr][4], s[0]) if shstr else "" for s in secs], cs


def elf_comdat(path):
    """COMDAT groups of an ELF relocatable (b1 of the module docstring) -> (member, groups). MEMBER {section index of a member of a
    GRP_COMDAT group: signature}; GROUPS {signature: sha256 hex of the copy's canonical form (member sections in group order, their
    relocations normalised)}. A signature that occurs twice in one object keeps the digest of both joined (two copies in one object)."""
    d, w64, secs, names, cs = _sections(path)
    symtab = next((i for i, s in enumerate(secs) if s[1] == 2), None)
    if symtab is None:
        return {}, {}
    st = secs[secs[symtab][6]]
    sfmt = "<IBBHQQ" if w64 else "<IIIBBH"
    syms = []
    for t in struct.iter_unpack(sfmt, d[secs[symtab][4]:secs[symtab][4] + secs[symtab][5]]):
        n, info, shn, val = (t[0], t[1], t[3], t[4]) if w64 else (t[0], t[3], t[5], t[1])
        syms.append((cs(st[4], n), info, shn, val))
    rels = {}
    for i, s in enumerate(secs):
        if s[1] == 4:   # SHT_RELA: the object's relocations of section s[7]
            for o, inf, a in struct.iter_unpack("<QQq" if w64 else "<IIi", d[s[4]:s[4] + s[5]]):
                rels.setdefault(s[7], []).append((o, inf >> 32 if w64 else inf >> 8, inf & 0xFFFFFFFF if w64 else inf & 255, a))
    member, groups = {}, {}
    for gi, g in enumerate(secs):
        if g[1] != 17 or g[5] < 4 or struct.unpack_from("<I", d, g[4])[0] & 1 == 0:   # SHT_GROUP with GRP_COMDAT
            continue
        sn, sinfo, sval_shn, _ = syms[g[7]]
        sig = names[sval_shn] if sinfo & 15 == 3 else sn
        mem = [m for m in struct.unpack_from("<%dI" % (g[5] // 4 - 1), d, g[4] + 4) if secs[m][1] != 4]   # relocation sections follow their section
        ordinal = {m: k for k, m in enumerate(mem)}
        canon = []
        for m in mem:
            member[m] = sig
            s = secs[m]
            body = b"" if s[1] == 8 else d[s[4]:s[4] + s[5]]
            rl = []
            for o, si, ty, a in sorted(rels.get(m, [])):
                n, inf, shn, val = syms[si]
                if inf >> 4 != 0 and shn != 0xFFF2 and inf & 15 != 3:   # global or weak symbol (or undefined): by name
                    tgt = ("sym", n, a)
                elif shn in ordinal:
                    tgt = ("member", ordinal[shn], val + a)
                elif 0 < shn < len(secs) and secs[shn][2] & 0x10 and secs[shn][9]:   # SHF_MERGE: the entity pointed at
                    base = secs[shn][4] + val + a
                    es = secs[shn][9]
                    end = base + es
                    while secs[shn][2] & 0x20 and d[end - es:end] != bytes(es):   # SHF_STRINGS: up to the terminating all-zero entity
                        end += es
                    
                    tgt = ("merge", d[base:end].hex())
                else:
                    tgt = ("local", names[shn] if 0 < shn < len(secs) else shn, n if inf & 15 != 3 else "", val + a)
                rl.append((o, ty, tgt))
            canon.append((names[m], s[1], s[2], s[8], body.hex(), rl))
        h = hashlib.sha256(repr(canon).encode()).hexdigest()
        groups[sig] = hashlib.sha256((groups[sig] + h).encode()).hexdigest() if sig in groups else h
    return member, groups


OUTLINE = re.compile(r"__aarch64_(cas|swp|ldadd|ldclr|ldeor|ldset)[0-9]+_(relax|acq|rel|acq_rel|sync)")   # libgcc's outline-atomics ABI: __aarch64_<op><bytes>_<memory model>
HOST_RUNTIME_PKGS = ("libc6", "libgcc-s1", "libstdc++6")   # packages of verify/env.json whose shared objects are the host boundary (envcheck pins them)


def elf_dynsyms(path):
    """Names of the symbols a shared object EXPORTS: the defined GLOBAL and WEAK entries of its `.dynsym` (ELF64 little endian)."""
    d, w64, secs, names, cs = _sections(path)
    out = set()
    for s in secs:
        if s[1] == 11 and w64:   # SHT_DYNSYM
            st = secs[s[6]]
            for t in struct.iter_unpack("<IBBHQQ", d[s[4]:s[4] + s[5]]):
                if t[0] and t[3] != 0 and t[1] >> 4 in (GLOBAL, WEAK) and t[1] & 15 in (0, 1, 2, 6, 10):
                    out.add(cs(st[4], t[0]))
    return out


def host_exports(cache):
    """The host boundary as a fact of the pinned packages (rule (d)): the exported dynamic symbols of every shared object (file whose real
    path is a regular ELF64 `.so`) that dpkg lists for HOST_RUNTIME_PKGS, with the package versions and each file's sha256 in the cache key,
    cached at CACHE/hostexports/<key>.json. -> (sorted names, key). Versions are pinned by envcheck (env.json), the key makes a change show."""
    import subprocess
    files, h = [], hashlib.sha256()
    for pkg in HOST_RUNTIME_PKGS:
        ver = subprocess.run(["dpkg-query", "-W", "-f", "${Version}", pkg], capture_output=True, text=True).stdout
        lst = subprocess.run(["dpkg-query", "-L", pkg], capture_output=True, text=True).stdout.split("\n")
        if not ver:
            raise ValueError("host runtime package %s is not installed" % pkg)
        h.update(("%s=%s\0" % (pkg, ver)).encode())
        for p in sorted({os.path.realpath(x) for x in lst if ".so" in os.path.basename(x)}):
            if os.path.isfile(p) and open(p, "rb").read(5) == b"\x7fELF\x02":
                files.append(p)
                h.update(hashlib.sha256(open(p, "rb").read()).digest())
    key = h.hexdigest()
    cp = os.path.join(cache, "hostexports", key + ".json")
    if os.path.exists(cp):
        return json.load(open(cp)), key
    names = sorted(set().union(*[elf_dynsyms(p) for p in files])) if files else []
    os.makedirs(os.path.dirname(cp), exist_ok=True)
    tmp = "%s.tmp%d" % (cp, os.getpid())
    json.dump(names, open(tmp, "w"))
    os.replace(tmp, cp)
    return names, key


def judge(objs, elfs, tables, comdat=None, host=None, guest=()):
    """OBJS {object id: [symbol tuples]}; ELFS {elf id: symbols or None}; TABLES {(root id, elf id or None): [(symbol, body id)]};
    COMDAT {object id: (member, groups)} as elf_comdat (an object missing from it has no COMDAT group)
    GUEST ["<root>/"] prefixes of guest roots: rule (e)
    HOST (host root prefixes ["<root>/"], exports {name}) or None: rule (d), the host boundary
    -> (items [(id, name)], findings [(id, name, KIND, detail)] sorted). Pure function of its arguments."""
    items, out, comdat = [], set(), comdat or {}
    defs, refs, copies = {}, [], {}
    for oid, syms in sorted(objs.items()):
        member = comdat.get(oid, ({}, {}))[0]
        for name, val, size, typ, bind, shn in syms:
            if bind not in (GLOBAL, WEAK, UNIQUE):
                continue
            if shn == 0:
                refs.append((oid, name))
            else:
                defs.setdefault(name, []).append((oid, bind, shn, typ, member.get(shn) if bind != GLOBAL else None))
        for sig, dg in sorted(comdat.get(oid, ({}, {}))[1].items()):
            copies.setdefault(sig, {})[oid] = dg
    bad = {}
    for sig, c in sorted(copies.items()):
        items.append(("<comdat>", sig))
        if len(set(c.values())) > 1:
            out.add(("<comdat>", sig, "comdat-differs", "copies differ across %s" % ", ".join(sorted(c))[:200]))
    script = {}   # elf id -> names the link script (or anything not an object) defines GLOBAL
    for eid, syms in elfs.items():
        script[eid] = {n for n, val, size, typ, bind, shn in syms or [] if shn != 0 and bind == GLOBAL}
    for name, ds in sorted(defs.items()):
        items.append(("<defs>", name))
        strong = [d for d in ds if d[1] == GLOBAL and d[2] != COMMON]
        cdef = [d for d in ds if d[4] is not None]
        differs = any(len(set(copies[d[4]].values())) > 1 for d in cdef)
        for kind, why in (("common", any(d[2] == COMMON for d in ds)), ("ifunc", any(d[3] == IFUNC for d in ds)),
                          ("duplicate-strong", len(strong) > 1), ("comdat-differs", differs and not strong),
                          ("weak-only", not strong and not any(d[2] == COMMON for d in ds) and (not cdef or any(d[4] is None for d in ds)))):
            if why:
                bad[name] = kind
                out.add(("<defs>", name, kind, "defined in %s" % ", ".join(sorted({d[0] for d in ds}))[:200]))
    for oid, name in refs:
        items.append((oid, name))
        if OUTLINE.fullmatch(name) and any(oid.startswith(p) for p in guest):
            out.add((oid, name, "outline-atomic", "a guest object references a libgcc outline-atomics helper (needs getauxval; build with -mno-outline-atomics)"))
            continue
        if name not in defs:
            if host and name in host[1] and any(oid.startswith(p) for p in host[0]):
                pass   # (d): an import of a host-target root, exported by the pinned host runtime
            elif not any(oid.startswith(eid.rsplit("/", 1)[0] + "/") and name in names for eid, names in script.items()):
                out.add((oid, name, "undefined", "no object of any product root defines it, nor the link script of its root"))
        elif name in bad:
            out.add((oid, name, "unresolved", "its definition is %s" % bad[name]))
    for eid, syms in sorted(elfs.items()):
        items.append((eid, "<elf>"))
        if syms is None:
            out.add((eid, "<elf>", "elf-no-symtab", "the linked ELF has no .symtab"))
            continue
        for name, val, size, typ, bind, shn in syms:
            if shn == 0:   # any binding: a relocation against an undefined symbol needs one, so a linked ELF without one has no such relocation
                out.add((eid, "<elf>", "elf-weak-undefined" if bind in (WEAK, UNIQUE) else "elf-undefined", name))
            if shn != 0 and typ == IFUNC:
                out.add((eid, "<elf>", "elf-ifunc", name))
    for (rid, eid), rows in sorted(tables.items()):
        syms = (elfs.get(eid) or []) if eid else []
        at = {}
        for name, val, size, typ, bind, shn in syms:
            if shn != 0 and (name not in at or bind != 0):
                at[name] = (val, size)
        body = {}
        for name, b in rows:
            if body.setdefault(name, b) != b:
                out.add((rid, "contract:" + name, "contract-duplicate", "listed with two body ids"))
        groups = {}
        for name, b in sorted(body.items()):
            items.append((rid, "contract:" + name))
            if eid is None:
                out.add((rid, "contract:" + name, "contract-no-elf", "the root links no ELF to decide on"))
            elif name not in at or not at[name][1]:
                out.add((rid, "contract:" + name, "contract-undefined", "not defined in the ELF with a nonzero size"))
            else:
                groups.setdefault(at[name][0], []).append((name, b))
        for val, g in groups.items():
            if len({b for _, b in g}) > 1:
                for name, b in g:
                    out.add((rid, "contract:" + name, "contract-alias", "address 0x%x shared with %s" % (val, ", ".join(
                        "%s (body %s)" % x for x in g if x[0] != name)[:200])))
    return items, sorted(out)


def foreign_flags(root, res, cache, repo):
    """Rule (f) of ROOT (a guest root that links an ELF): the objects its link stage takes from externals (producers.link_inputs) each show, in their
    DW_AT_producer, the option set the pinned driver writes for the recipe's semantic set. -> (items [(id, name)], findings)."""
    roots = recipe.load_admit(repo)
    rec = recipe.load_recipe(repo, roots, root)
    doc = None
    for k in res.get("stage_keys", []):
        p = os.path.join(cache, "store", "stage-docs", k[:2], k + ".json")
        if os.path.isfile(p):
            d = json.load(open(p))
            if d.get("stage") == "ld:" + root:
                doc = d
    if doc is None:
        return [(root, "<link-stage>")], [(root, "<link-stage>", "no-link-stage", "no ld stage document for the root's link")]
    at = {e["at"]: recipe.exttree(e, cache) for e in rec.get("external", [])}
    cc, cxx = recipe.host_compilers(rec, cache)
    return producers.foreign_items(root, doc, at, {"c": producers.expected(cc, "c"), "cxx": producers.expected(cxx, "cxx")})


def main():
    tmp = None if os.environ.get("GATE_CACHE") else tempfile.mkdtemp(prefix="gate-linkstrict-")
    cache, repo = os.environ.get("GATE_CACHE") or tmp, "."
    items, finds, why, objs, elfs, tables, roots, comdat = [], [], "", {}, {}, {}, gate_build.buildable_roots(repo), {}
    host, guest = None, []
    try:
        hroots = [r + "/" for r, e in recipe.load_admit(repo).items() if e.get("class") in ("product", "test") and e.get("target") == "host"]
        host = (hroots, set(host_exports(cache)[0])) if hroots else None
        guest = [r + "/" for r, e in recipe.load_admit(repo).items() if e.get("class") == "product" and e.get("target") == "guest"]
        for root in roots:
            res, _ = gate_build.ensure(root, cache, repo)
            if res["status"] == "red":
                items.append((root, "<build>"))
                finds.append((root, "<build>", "build-red", "stage %s" % res["failure"]["stage"]))
                continue
            for o in res["objects"]:
                objs[root + "/" + o["unit"]] = elf_symbols(o["object"]) or []
                comdat[root + "/" + o["unit"]] = elf_comdat(o["object"])
            for m in res.get("link_archives", []):     # the members ld pulled from an archive are objects of the link, judged like every other
                mid = "%s/%s(%s)" % (root, m["archive"].lstrip("/"), m["member"])
                objs[mid] = elf_symbols(m["object"]) or []
                comdat[mid] = elf_comdat(m["object"])
            eid = root + "/" + os.path.basename(res["elf"]["path"]) if res["elf"] else None
            if eid:
                elfs[eid] = elf_symbols(res["elf"]["path"])
            if eid and root + "/" in guest:   # rule (f): what an external contributes to the link was built with the one semantic set
                fitems, ffinds = foreign_flags(root, res, cache, repo)
                items += fitems
                finds += ffinds
            if res.get("contract_names"):
                rows = [l.rstrip("\n").split("\t") for l in open(res["contract_names"]) if l.strip()]
                if any(len(r) != 2 or not r[0] or not r[1] for r in rows):
                    raise ValueError("%s: contract names must be `symbol<TAB>body_id` rows" % root)
                tables[(root, eid)] = [tuple(r) for r in rows]
    except recipe.RecipeError as e:
        why = "invalid recipe: %s" % "; ".join(e.errors)[:300]
    except (ValueError, KeyError, OSError, struct.error) as e:
        why = "input error: %s" % (str(e)[:300] or type(e).__name__)
    finally:
        if tmp and not os.environ.get("GATE_KEEP"):
            shutil.rmtree(tmp, ignore_errors=True)
    its, fs = judge(objs, elfs, tables, comdat, host, guest)
    items, finds = items + its, finds + fs
    bad = {(o, s) for o, s, _, _ in finds}
    cert = len([it for it in items if it not in bad])
    kinds = {}
    for _, _, k, _ in finds:
        kinds[k] = kinds.get(k, 0) + 1
    if why:
        status, detail = "red", why
    elif not roots:
        status, detail = "green", "no product root (nothing to certify yet)"
    elif finds:
        status, detail = "red", "%d findings: %s" % (len(finds), ", ".join("%s %d" % kv for kv in sorted(kinds.items())))
    else:
        status, detail = "green", "%d items of %d roots: every reference has one strong definition" % (len(items), len(roots))
    res = {"format": "fnvnx-gate/1", "name": "linkstrict", "status": status, "universe": len(items), "certified": cert,
           "uncertified": sorted("%s:%s" % x for x in bad)[:50], "detail": detail}
